\set SHOW_CONTEXT never
SET search_path = public;
CREATE EXTENSION kingres_shard;
SELECT kingres.init_cluster('localhost', current_setting('port')::int);

CREATE TABLE e1 (id int GENERATED ALWAYS AS IDENTITY (START 5 INCREMENT 3 MINVALUE 2 MAXVALUE 1000 CACHE 4 CYCLE), tenant int, v text);
CREATE TABLE e2 (id int GENERATED BY DEFAULT AS IDENTITY (START 5 INCREMENT 3 MINVALUE 2 MAXVALUE 1000 CACHE 4 CYCLE), tenant int, v text,
                 PRIMARY KEY (tenant, id));
INSERT INTO e2 (tenant, v) SELECT g, 'x' FROM generate_series(1, 6) g;
CREATE TABLE e3 (id serial, s2 bigserial, tenant int, v text);
ALTER SEQUENCE e3_id_seq INCREMENT BY 7 MINVALUE 3 MAXVALUE 500 START 9 RESTART WITH 9 CACHE 3 CYCLE;
SELECT setval('e3_id_seq', 30);
CREATE TABLE e4 (id serial, tenant int, v text, PRIMARY KEY (tenant, id));
ALTER SEQUENCE e4_id_seq INCREMENT BY 7 MINVALUE 3 MAXVALUE 500 START 9 RESTART WITH 9 CACHE 3 CYCLE;
INSERT INTO e4 (tenant, v) SELECT g, 'x' FROM generate_series(1, 4) g;
CREATE TABLE e5 (id int GENERATED BY DEFAULT AS IDENTITY (START 5 INCREMENT 3), tenant int, v text);
SELECT setval('e5_id_seq', 20);

CREATE FUNCTION seqs() RETURNS TABLE (relname name, typ regtype, st bigint, inc bigint, mx bigint, mn bigint, cache bigint, cyc bool, owned text)
LANGUAGE sql AS $$
SELECT c.relname, s.seqtypid::regtype, s.seqstart, s.seqincrement, s.seqmax, s.seqmin, s.seqcache, s.seqcycle,
       (SELECT d.refobjid::regclass::text || '/' || d.deptype::text FROM pg_depend d
         WHERE d.classid = 'pg_class'::regclass AND d.objid = c.oid AND d.refclassid = 'pg_class'::regclass LIMIT 1)
  FROM pg_sequence s JOIN pg_class c ON c.oid = s.seqrelid WHERE c.relname ~ '^e[0-9]' ORDER BY c.relname $$;
CREATE FUNCTION seqvals() RETURNS TABLE (t text, last_value bigint, is_called bool) LANGUAGE plpgsql AS $$
DECLARE r record;
BEGIN
  FOR r IN SELECT c.relname FROM pg_class c WHERE c.relkind = 'S' AND c.relname ~ '^e[0-9]' ORDER BY 1 LOOP
    EXECUTE format('SELECT %L, last_value, is_called FROM %I', r.relname, r.relname) INTO t, last_value, is_called;
    RETURN NEXT;
  END LOOP;
END $$;
CREATE TABLE before_opts AS SELECT * FROM seqs();
CREATE TABLE before_vals AS SELECT * FROM seqvals();
SELECT * FROM before_opts ORDER BY relname;
SELECT * FROM before_vals ORDER BY t;

-- the empty table, with an identity column
SELECT kingres.create_distributed_table('e1', 'tenant', bucket_count => 4);
-- the tables with rows, and the empty ones
SELECT kingres.create_distributed_table('e2', 'tenant', colocate_with => 'e1');
SELECT kingres.create_distributed_table('e3', 'tenant', colocate_with => 'e1');
SELECT kingres.create_distributed_table('e4', 'tenant', colocate_with => 'e1');
SELECT kingres.create_distributed_table('e5', 'tenant', colocate_with => 'e1');

-- nothing changed: the same options, the same owners, the same values
SELECT count(*) AS options_that_changed
  FROM ((SELECT * FROM before_opts EXCEPT SELECT * FROM seqs()) UNION ALL (SELECT * FROM seqs() EXCEPT SELECT * FROM before_opts)) d;
SELECT count(*) AS values_that_changed
  FROM ((SELECT * FROM before_vals EXCEPT SELECT * FROM seqvals()) UNION ALL (SELECT * FROM seqvals() EXCEPT SELECT * FROM before_vals)) d;

-- the next values are the ones the sequences would have given
INSERT INTO e1 (tenant, v) VALUES (1, 'a'), (1, 'b');
INSERT INTO e2 (tenant, v) VALUES (7, 'a'), (7, 'b');
INSERT INTO e3 (tenant, v) VALUES (1, 'a'), (1, 'b');
INSERT INTO e4 (tenant, v) VALUES (7, 'a'), (7, 'b');
INSERT INTO e5 (tenant, v) VALUES (1, 'a'), (1, 'b');
SELECT 'e1' AS t, id FROM e1 UNION ALL SELECT 'e2', id FROM e2 WHERE tenant = 7 UNION ALL SELECT 'e3', id FROM e3
  UNION ALL SELECT 'e4', id FROM e4 WHERE tenant = 7 UNION ALL SELECT 'e5', id FROM e5 ORDER BY 1, 2;
SELECT 'e3' AS t, s2 FROM e3 ORDER BY 2;

DROP TABLE before_opts, before_vals, e1, e2, e3, e4, e5;
DROP FUNCTION seqs(), seqvals();
DROP EXTENSION kingres_shard;
