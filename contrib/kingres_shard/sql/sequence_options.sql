-- sql/sequence_options.sql
--   The options and the current value of the sequences of a table survive create_distributed_table() (the blocking
--   variant builds a shadow table): identity columns (ALWAYS and BY DEFAULT) and serial columns, on an empty table
--   and on a table with rows, with START, INCREMENT, MINVALUE, MAXVALUE, CACHE and CYCLE that are not the defaults,
--   and the value that the next row gets is the one it would have had (no value is given twice).  One node: the
--   origin; the other nodes are compared in t/144 and t/140.
