# mk-install-script.sh: write kingres_shard--0.8.sql, the install script of the current version: the 0.7
# install script from its \echo line on, followed by the 0.7--0.8 upgrade script after its \echo line (the
# convention of the older scripts; the "upgrade" regression test compares the catalogs of the two ways).
# Run it in contrib/kingres_shard after every change of kingres_shard--0.7--0.8.sql, kingres_shard--0.7.sql or kingres_shard--0.6--0.7.sql (a merge that
# changes the 0.7 scripts too); t/250_install_script_current.pl fails when the committed file differs (KS_INSTALL_SCRIPT_OUT names another output file).
set -eu
d=$(cd "$(dirname "$0")" && pwd)
out=${KS_INSTALL_SCRIPT_OUT:-$d/kingres_shard--0.8.sql}
{
  cat <<'HDR'
-- SPDX-License-Identifier: AGPL-3.0-only
-- Portions Copyright (c) 2026, RooyeKhat Media Co
--
-- kingres_shard--0.8.sql
--   Install script of the kingres_shard extension, version 0.8: everything of 0.7 and the changes of
--   kingres_shard--0.7--0.8.sql appended (elasticity and distributed schemas).  Generated by
--   mk-install-script.sh from the 0.7 install script and the 0.7--0.8 upgrade script: change the
--   upgrade script and run the generator, never edit this file by hand.
--
HDR
  n=$(grep -n "^.echo Use \"CREATE EXTENSION" "$d/kingres_shard--0.7.sql" | head -1 | cut -d: -f1)
  tail -n +"$n" "$d/kingres_shard--0.7.sql"
  echo
  echo "-- ---------------------------------------------------------------------------"
  echo "-- Version 0.8: elasticity and distributed schemas (the upgrade script 0.7--0.8, appended)"
  echo "-- ---------------------------------------------------------------------------"
  n=$(grep -n "^.echo Use \"ALTER EXTENSION kingres_shard UPDATE TO" "$d/kingres_shard--0.7--0.8.sql" | head -1 | cut -d: -f1)
  tail -n +"$((n + 1))" "$d/kingres_shard--0.7--0.8.sql"
} > "$out"

# kingres_shard--0.9.sql: the 0.8 install script from its \echo line on, followed by the 0.8--0.9 upgrade script after its \echo line.
out9=${KS_INSTALL_SCRIPT_OUT_09:-$d/kingres_shard--0.9.sql}
{
  cat <<'HDR'
-- SPDX-License-Identifier: AGPL-3.0-only
-- Portions Copyright (c) 2026, RooyeKhat Media Co
--
-- kingres_shard--0.9.sql
--   Install script of the kingres_shard extension, version 0.9: everything of 0.8 and the changes of
--   kingres_shard--0.8--0.9.sql appended (columnar storage in the sharding extension).  Generated by
--   mk-install-script.sh from the 0.8 install script and the 0.8--0.9 upgrade script: change the
--   upgrade script and run the generator, never edit this file by hand.
--
HDR
  n=$(grep -n "^.echo Use \"CREATE EXTENSION" "$d/kingres_shard--0.8.sql" | head -1 | cut -d: -f1)
  # The 0.9 install script makes the schema kingres only when it does not exist, and refuses one that a role that is not a superuser made in advance (or
  # that grants CREATE to such a role): that role would own what the service role runs.  The 0.8 script has the line that is replaced; it stays as it is
  # (the older versions are only upgraded from, and the control plane refuses such a schema at run time as well).
  KS_BLOCK=$(cat <<'BLK'
-- The schema kingres is made here, or it exists already (another KingresDB extension made it).  Not CREATE SCHEMA IF NOT EXISTS: PostgreSQL refuses that in
-- a script when the schema exists and is not a member of the extension.  An existing schema must be owned by a superuser and give CREATE to no role that is
-- not a superuser: a role that made it in advance would otherwise own what the service role, a superuser, reads and runs.
DO $ks$
DECLARE
    v_owner pg_catalog.name;
BEGIN
    IF pg_catalog.to_regnamespace('kingres') IS NULL THEN
        CREATE SCHEMA kingres;
        RETURN;
    END IF;
    SELECT r.rolname INTO v_owner
      FROM pg_catalog.pg_namespace n JOIN pg_catalog.pg_roles r ON r.oid OPERATOR(pg_catalog.=) n.nspowner
     WHERE n.nspname OPERATOR(pg_catalog.=) 'kingres' AND NOT r.rolsuper;
    IF v_owner IS NOT NULL THEN
        RAISE EXCEPTION 'the schema kingres already exists and is owned by %, which is not a superuser', v_owner
            USING ERRCODE = 'insufficient_privilege',
                  HINT = 'Drop the schema, or make a superuser its owner, before CREATE EXTENSION kingres_shard.';
    END IF;
    IF EXISTS (SELECT 1
                 FROM pg_catalog.pg_namespace n,
                      LATERAL pg_catalog.aclexplode(COALESCE(n.nspacl, pg_catalog.acldefault('n', n.nspowner))) a
                WHERE n.nspname OPERATOR(pg_catalog.=) 'kingres'
                  AND a.privilege_type OPERATOR(pg_catalog.=) 'CREATE'
                  AND (a.grantee OPERATOR(pg_catalog.=) 0
                       OR NOT EXISTS (SELECT 1 FROM pg_catalog.pg_roles g WHERE g.oid OPERATOR(pg_catalog.=) a.grantee AND g.rolsuper))) THEN
        RAISE EXCEPTION 'the schema kingres grants CREATE to a role that is not a superuser (or to PUBLIC)'
            USING ERRCODE = 'insufficient_privilege',
                  HINT = 'Revoke CREATE on the schema before CREATE EXTENSION kingres_shard.';
    END IF;
END
$ks$;
BLK
)
  export KS_BLOCK
  tail -n +"$n" "$d/kingres_shard--0.8.sql" | awk 'BEGIN { old = "DO $ks$ BEGIN IF pg_catalog.to_regnamespace(\047kingres\047) IS NULL THEN CREATE SCHEMA kingres; END IF; END $ks$;" }
    $0 == old && !done { print ENVIRON["KS_BLOCK"]; done = 1; next } { print } END { if (!done) exit 3 }'
  echo
  echo "-- ---------------------------------------------------------------------------"
  echo "-- Version 0.9: columnar storage in the sharding extension (the upgrade script 0.8--0.9, appended)"
  echo "-- ---------------------------------------------------------------------------"
  n=$(grep -n "^.echo Use \"ALTER EXTENSION kingres_shard UPDATE TO" "$d/kingres_shard--0.8--0.9.sql" | head -1 | cut -d: -f1)
  tail -n +"$((n + 1))" "$d/kingres_shard--0.8--0.9.sql"
} > "$out9"
