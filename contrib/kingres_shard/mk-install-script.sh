# mk-install-script.sh: write kingres_shard--0.8.sql, the install script of the current version: the 0.7
# install script from its \echo line on, followed by the 0.7--0.8 upgrade script after its \echo line (the
# convention of the older scripts; the "upgrade" regression test compares the catalogs of the two ways).
# Run it in contrib/kingres_shard after every change of kingres_shard--0.7--0.8.sql, kingres_shard--0.7.sql or kingres_shard--0.6--0.7.sql (a merge that
# changes the 0.7 scripts too); t/250_install_script_current.pl fails when the committed file differs (KS_INSTALL_SCRIPT_OUT names another output file).
set -eu
d=$(cd "$(dirname "$0")" && pwd)
out=${KS_INSTALL_SCRIPT_OUT:-$d/kingres_shard--0.8.sql}
{
  cat <<'HDR'
-- SPDX-License-Identifier: AGPL-3.0-only
-- Portions Copyright (c) 2026, RooyeKhat Media Co
--
-- kingres_shard--0.8.sql
--   Install script of the kingres_shard extension, version 0.8: everything of 0.7 and the changes of
--   kingres_shard--0.7--0.8.sql appended (elasticity and distributed schemas).  Generated by
--   mk-install-script.sh from the 0.7 install script and the 0.7--0.8 upgrade script: change the
--   upgrade script and run the generator, never edit this file by hand.
--
HDR
  n=$(grep -n "^.echo Use \"CREATE EXTENSION" "$d/kingres_shard--0.7.sql" | head -1 | cut -d: -f1)
  tail -n +"$n" "$d/kingres_shard--0.7.sql"
  echo
  echo "-- ---------------------------------------------------------------------------"
  echo "-- Version 0.8: elasticity and distributed schemas (the upgrade script 0.7--0.8, appended)"
  echo "-- ---------------------------------------------------------------------------"
  n=$(grep -n "^.echo Use \"ALTER EXTENSION kingres_shard UPDATE TO" "$d/kingres_shard--0.7--0.8.sql" | head -1 | cut -d: -f1)
  tail -n +"$((n + 1))" "$d/kingres_shard--0.7--0.8.sql"
} > "$out"

# kingres_shard--0.9.sql: the 0.8 install script from its \echo line on, followed by the 0.8--0.9 upgrade script after its \echo line.
out9=${KS_INSTALL_SCRIPT_OUT_09:-$d/kingres_shard--0.9.sql}
