# t/130_router_identity.pl
#
# Step 3 of phase 2b, the row router (design/shard-phase2b.md, 11.2, 11.3 and 11.5): the columns that the
# origin computes (an identity, a serial, a volatile default) are sent to the group as values and the group
# stores them: the insert fragment carries OVERRIDING SYSTEM VALUE when the table has a GENERATED ALWAYS
# identity column.  A stored generated column is never sent (the group computes it); a virtual one (PostgreSQL
# 19) is not stored at all.  Every case runs on the cluster and on a twin node, and the rows (identity values
# included) are compared one by one; the sequence state of the origin is compared with the twin's.  A user's own
# OVERRIDING SYSTEM VALUE keeps PostgreSQL's meaning (the given value is stored); OVERRIDING USER VALUE ignores
# the given value and draws from the sequence; a value without OVERRIDING is refused as on one node.  The
# same through COPY FROM.

use strict;
use warnings FATAL => 'all';
use FindBin;
use lib $FindBin::RealBin;
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
use KingresShardTest qw(run_sql);
use KingresShardCompare;

my $c = KingresShardCompare->new('ri');
my ($n1, $n2, $n3) = $c->nodes;
my $single = $c->single;
my $major = $n1->safe_psql('postgres', q{SELECT current_setting('server_version_num')::int / 10000});

sub table
{
	my ($create, $dist) = @_;
	$c->on_cluster($create . ($dist // ''));
	$c->on_single($create);
}

sub seq_state
{
	my ($node, $table, $col) = @_;
	my $seq = $node->safe_psql('postgres', "SELECT pg_get_serial_sequence('$table', '$col')");
	return $node->safe_psql('postgres', "SELECT last_value || '/' || is_called FROM $seq");
}

# name, columns, key, the computed column
my @cases = (
	[ 'always_first',    q{id int GENERATED ALWAYS AS IDENTITY, k int PRIMARY KEY, v text}, 'k', 'id' ],
	[ 'always_last',     q{k int PRIMARY KEY, v text, id bigint GENERATED ALWAYS AS IDENTITY}, 'k', 'id' ],
	[ 'bydefault',       q{id int GENERATED BY DEFAULT AS IDENTITY, k int PRIMARY KEY, v text}, 'k', 'id' ],
	[ 'serial_volatile', q{k int PRIMARY KEY, s serial, r int DEFAULT (random() * 0)::int, v text}, 'k', 's' ],
	[ 'stored_generated', q{k int PRIMARY KEY, id int GENERATED ALWAYS AS IDENTITY, g int GENERATED ALWAYS AS (k * 2) STORED, v text}, 'k', 'id' ],
);
push @cases, [ 'virtual_generated', q{k int PRIMARY KEY, id int GENERATED ALWAYS AS IDENTITY, g int GENERATED ALWAYS AS (k * 3) VIRTUAL, v text}, 'k', 'id' ]
  if $major >= 19;

for my $case (@cases)
{
	my ($name, $cols, $key, $idcol) = @$case;
	my $t = "public.ri_$name";
	table("CREATE TABLE $t ($cols)", "; SELECT kingres.create_distributed_table('$t', '$key', bucket_count => 12)");
	$c->compare_dml("$name: multi-row insert", "INSERT INTO $t (k, v) VALUES " . join(', ', map { "($_, 'x$_')" } (1 .. 12)));
	$c->compare_dml("$name: insert select", "INSERT INTO $t (k, v) SELECT g, 'g' || g FROM generate_series(100, 140) g");
	{
		my $sql = "INSERT INTO $t (k, v) VALUES (200, 'r'), (201, 'r'), (202, 'r'), (203, 'r') RETURNING $idcol";
		my ($rs, $os) = run_sql($single, $sql);
		my ($rd, $od, $ed) = run_sql($n1, $sql);
		is($rd, 0, "$name: returning runs") or diag($ed);
		is(join(",", sort split /
/, $od), join(",", sort split /
/, $os), "$name: RETURNING gives the twin's values");
	}
	$c->compare_dml("$name: on conflict do nothing", "INSERT INTO $t (k, v) VALUES (1, 'dup'), (300, 'new'), (301, 'new'), (100, 'dup') ON CONFLICT DO NOTHING");
	$c->compare_dml("$name: DEFAULT given for the computed column", "INSERT INTO $t (k, $idcol, v) VALUES (310, DEFAULT, 'd'), (311, DEFAULT, 'd'), (312, DEFAULT, 'd')");
	$c->compare_tables($t, order_by => '1, 2', name => "$name: the rows (identity values included) are the twin's");
	is(seq_state($n1, $t, $idcol), seq_state($single, $t, $idcol), "$name: the sequence of the origin is where the twin's is");
	for my $n ($n2, $n3)
	{
		my $from = $n == $n2 ? 400 : 500;
		my ($rc, $out, $err) = run_sql($n, "INSERT INTO $t (k, v) SELECT g, 'n' FROM generate_series($from, " . ($from + 10) . ") g");
		is($rc, 0, "$name: an insert from " . $n->name) or diag($err);
	}
	my ($cnt, $dist) = split /\|/, $n1->safe_psql('postgres', "SELECT count(*), count(DISTINCT k) FROM $t");
	is($cnt, $dist, "$name: no row was stored twice");
}

# the identity is the key: the origin computes it and hashes it
table(q{CREATE TABLE public.ri_key (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, v text)},
	q{; SELECT kingres.create_distributed_table('public.ri_key', 'id', bucket_count => 12)});
$c->compare_dml('identity key: multi-row insert', q{INSERT INTO public.ri_key (v) VALUES ('a'), ('b'), ('c'), ('d'), ('e'), ('f')});
$c->compare_dml('identity key: insert select', q{INSERT INTO public.ri_key (v) SELECT 'g' || g FROM generate_series(1, 30) g});
$c->compare_tables('public.ri_key', order_by => '1', name => 'identity key: the rows');

# a user's own OVERRIDING, and a value without it
{
	my $t = 'public.ri_always_first';
	$c->compare_dml('OVERRIDING SYSTEM VALUE stores the given value', "INSERT INTO $t (id, k, v) OVERRIDING SYSTEM VALUE VALUES (9001, 601, 'o'), (9002, 602, 'o'), (9003, 603, 'o'), (9004, 604, 'o')");
	$c->compare_dml('OVERRIDING USER VALUE draws from the sequence', "INSERT INTO $t (id, k, v) OVERRIDING USER VALUE VALUES (9101, 611, 'u'), (9102, 612, 'u'), (9103, 613, 'u'), (9104, 614, 'u')");
	$c->compare_dml('OVERRIDING SYSTEM VALUE with a select', "INSERT INTO $t (id, k, v) OVERRIDING SYSTEM VALUE SELECT 9200 + g, 620 + g, 's' FROM generate_series(1, 9) g");
	$c->compare_tables($t, order_by => '2', name => 'user OVERRIDING: the rows', query => "SELECT * FROM $t WHERE k >= 600 ORDER BY k");
	my $before = seq_state($n1, $t, 'id');
	$c->compare_dml('a value for an ALWAYS identity without OVERRIDING is refused', "INSERT INTO $t (id, k, v) VALUES (9300, 701, 'n'), (9301, 702, 'n')",
		expect_error => qr/cannot insert a non-DEFAULT value into column "id"/, single_fails => 1);
	is(seq_state($n1, $t, 'id'), $before, 'a refused statement draws nothing from the sequence');
	$c->compare_dml('a value for a stored generated column is refused', 'INSERT INTO public.ri_stored_generated (k, g, v) VALUES (801, 1, 1), (802, 2, 2)',
		expect_error => qr/cannot insert a non-DEFAULT value into column "g"/, single_fails => 1);
}

# COPY FROM through the router
{
	my $t = 'public.ri_always_first';
	my $rows = join('', map { sprintf("%d\tcopy%d\n", 1000 + $_, $_) } (1 .. 30));
	my ($cc, $cs) = $c->copy_in_both($t, $rows, columns => ['k', 'v']);
	is($cc->[0], 0, 'COPY into a table with an ALWAYS identity') or diag($cc->[2]);
	is($cs->[0], 0, '... and on the twin');
	$c->compare_tables($t, order_by => '2', name => 'COPY: the rows (identity values included)', query => "SELECT * FROM $t WHERE k >= 1000 ORDER BY k");
	is(seq_state($n1, $t, 'id'), seq_state($single, $t, 'id'), 'COPY: the sequence is where the twin\'s is');
	my $ro = join('', map { sprintf("%d\t%d\tov\n", 2000 + $_, 5000 + $_) } (1 .. 12));
	($cc, $cs) = $c->copy_in_both($t, $ro, columns => ['k', 'id', 'v']);
	is($cc->[0], 0, 'COPY with a value for the ALWAYS identity is accepted (COPY does not look at OVERRIDING)');
	is($cs->[0], 0, '... as on the twin');
	$c->compare_tables($t, order_by => '2', name => 'COPY with identity values: the rows', query => "SELECT * FROM $t WHERE k >= 2000 ORDER BY k");
	my $b = 'public.ri_bydefault';
	($cc, $cs) = $c->copy_in_both($b, $ro, columns => ['k', 'id', 'v']);
	is($cc->[0], 0, 'COPY with values for a BY DEFAULT identity') or diag($cc->[2]);
	$c->compare_tables($b, order_by => '2', name => 'COPY BY DEFAULT: the rows', query => "SELECT * FROM $b WHERE k >= 2000 ORDER BY k");
}

done_testing();
