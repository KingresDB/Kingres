# t/280_runtime_objects_owner.pl: what the extension moves into the schema kingres at run time belongs to the bootstrap superuser (XCAT-2, M1 to M3).
#
#   The orphan tables (orphan_<move>_<n>, orphan_s<split>_<n>) and the retired copy of a table (kingres_old_<oid>) used to keep the owner of the distributed table
#   after ALTER TABLE ... SET SCHEMA kingres.  That owner could attach views, foreign keys and triggers to them, and the drop that the extension runs later would
#   fail for good.
#   A. a move: the orphan table is the superuser's, its former owner cannot change it, the cleanup drops it
#   B. an online alter: the retired copy and the sequences it owns are the superuser's
#   C. a split: the generated capture function qualifies every operator of its body with pg_catalog

use strict;
use warnings FATAL => 'all';
use FindBin;
use lib $FindBin::RealBin;
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use POSIX ();
use Test::More;
use KingresShardTest qw(make_cluster run_sql wait_for_fault_file);

my $tmp = PostgreSQL::Test::Utils::tempdir();
my @nodes = make_cluster('ro', 3, logical => 1, recovery_interval => 0,
	extra => "max_connections = 100\nkingres_shard.node_timeout = 10\nkingres_shard.move_cleanup_delay = 1\n");
my ($n1, $n2, $n3) = @nodes;
sub q1 { my ($node, $sql) = @_; return $node->safe_psql('postgres', $sql); }

$_->safe_psql('postgres', q{CREATE ROLE ro_owner LOGIN; GRANT CREATE, USAGE ON SCHEMA public TO ro_owner; GRANT USAGE ON SCHEMA kingres TO ro_owner}) for @nodes;
q1($n1, q{
	CREATE TABLE public.orders (id int PRIMARY KEY, note text);
	SELECT kingres.create_distributed_table('public.orders', 'id', bucket_count => 6);
	ALTER TABLE public.orders OWNER TO ro_owner;
	INSERT INTO public.orders SELECT g, 'n' || g FROM generate_series(1, 120) g;
});
is(q1($n1, q{SELECT pg_get_userbyid(relowner) FROM pg_class WHERE oid = 'public.orders'::regclass}), 'ro_owner', 'the table is the owners');

# ---------------------------------------------------------------------------------------------------------------------------------
# A. a move
# ---------------------------------------------------------------------------------------------------------------------------------
my $bucket = q1($n1, 'SELECT kingres.bucket_for(1, 1)');
my $source = q1($n1, "SELECT group_id FROM kingres.bucket_map WHERE colocation_id = 1 AND bucket = $bucket");
my $target = ($source + 1) % 3;
my $src = $nodes[$source];
my $move = q1($n1, "SELECT kingres.move_bucket(1, $bucket, $target)");
like($move, qr/^\d+$/, "A: the bucket moved (move $move)");
my $su = q1($src, q{SELECT rolname FROM pg_roles WHERE oid = 10});
is(q1($src, "SELECT string_agg(pg_get_userbyid(relowner), ',') FROM pg_class WHERE relnamespace = 'kingres'::regnamespace AND relname LIKE 'orphan\\_${move}\\_%' AND relkind IN ('r', 'p')"), $su,
	'A: the orphan table belongs to the bootstrap superuser');
my ($rc, $out, $err) = run_sql($src, "SET ROLE ro_owner; ALTER TABLE kingres.orphan_${move}_1 ADD COLUMN extra int");
isnt($rc, 0, 'A: the former owner cannot change the orphan table');
like($err, qr/must be owner/, 'A: ... it is not the owner any more') or diag($err);
($rc, $out, $err) = run_sql($src, "SET ROLE ro_owner; CREATE TRIGGER x AFTER INSERT ON kingres.orphan_${move}_1 FOR EACH ROW EXECUTE FUNCTION pg_catalog.suppress_redundant_updates_trigger()");
isnt($rc, 0, 'A: nor attach a trigger to it');
q1($n1, 'SELECT kingres.cleanup_moved_buckets(true)');
is(q1($src, "SELECT count(*) FROM pg_class WHERE relname LIKE 'orphan\\_${move}\\_%'"), '0', 'A: the cleanup drops the orphan table');

# ---------------------------------------------------------------------------------------------------------------------------------
# B. the retired copy of an online alter
# ---------------------------------------------------------------------------------------------------------------------------------
q1($n1, q{CREATE TABLE public.ident (id int PRIMARY KEY, g int GENERATED BY DEFAULT AS IDENTITY, note text); SELECT kingres.create_distributed_table('public.ident', 'id', bucket_count => 6); ALTER TABLE public.ident OWNER TO ro_owner; INSERT INTO public.ident (id, note) SELECT g, 'n' || g FROM generate_series(1, 60) g});
($rc, $out, $err) = run_sql($n1, q{SELECT kingres.alter_distributed_table_concurrently('public.ident', bucket_count => 12)});
is($rc, 0, 'B: alter_distributed_table_concurrently') or diag($err);
for my $n (@nodes)
{
	my $su2 = q1($n, q{SELECT rolname FROM pg_roles WHERE oid = 10});
	is(q1($n, q{SELECT string_agg(DISTINCT pg_get_userbyid(relowner), ',') FROM pg_class WHERE relnamespace = 'kingres'::regnamespace AND relname ~ '^kingres_old_[0-9]+(_s[0-9]+)?$' AND relkind IN ('r', 'p', 'S')}),
		$su2, 'B: the retired copy (and its sequence) belong to the bootstrap superuser on ' . $n->name);
}
is(q1($n1, q{SELECT count(*) FROM pg_class WHERE relnamespace = 'kingres'::regnamespace AND relname ~ '^kingres_old_[0-9]+_s[0-9]+$' AND relkind = 'S'}), '1', 'B: there is a sequence of the retired copy');

# ---------------------------------------------------------------------------------------------------------------------------------
# C. the capture function of a split
# ---------------------------------------------------------------------------------------------------------------------------------
q1($n1, q{
	CREATE TABLE public.s1 (id int PRIMARY KEY, v text);
	INSERT INTO public.s1 SELECT g, 'v' || g FROM generate_series(1, 200) g;
	SELECT kingres.create_distributed_table('public.s1', 'id', bucket_count => 4);
});
my $C = q1($n1, q{SELECT colocation_id FROM kingres.dist_table WHERE relid = 'public.s1'::regclass});
my $file = "$tmp/wait_c";
open(my $fh, '>', $file) or die;
close($fh);
my $pid = fork();
die 'fork' unless defined $pid;
if ($pid == 0)
{
	my $s = "SET kingres_shard.fault_injection = 'split_after_triggers:wait:$file'; SELECT kingres.split_bucket($C, 1, 2, 'none')";
	system("psql -X -q -h " . $n1->host . " -p " . $n1->port . " -d postgres -c \"$s\" > $tmp/out_c 2>&1");
	POSIX::_exit(0);
}
ok(wait_for_fault_file("$file.reached", 60), 'C: the split reached the point after its triggers');
my $found = 0;
for my $n (@nodes)
{
	my $bodies = q1($n, q{SELECT coalesce(string_agg(prosrc, E'\n--\n'), '') FROM pg_proc WHERE pronamespace = 'kingres'::regnamespace AND proname LIKE 'split\_capture\_%'});
	next if $bodies eq '';
	$found++;
	unlike($bodies, qr/TG_OP\s*=\s|TG_OP\s+IN\b/, 'C: no unqualified operator on TG_OP in the capture function of ' . $n->name);
	like($bodies, qr/TG_OP OPERATOR\(pg_catalog\.=\)/, 'C: ... they are written as OPERATOR(pg_catalog.=)');
	unlike($bodies, qr/\w\s=\s(OLD|NEW)\./, 'C: nor on the key columns');
	like($bodies, qr/OPERATOR\(pg_catalog\.=\) OLD\./, 'C: ... those are qualified too');
}
cmp_ok($found, '>=', 1, 'C: a node holds the capture function');
unlink($file);
waitpid($pid, 0);
q1($n1, q{SELECT kingres.cleanup_bucket_splits(true)});

$_->stop for @nodes;
done_testing();
