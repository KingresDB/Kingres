# t/187_online_undistribute.pl: kingres.undistribute_table_concurrently() (design/shard-phase9.md, increment 9.4, part two): the rebuild engine
# of 9.3 with a distributed table as its source.
#
#   A. a table with every kind of object becomes an ordinary table while it is in use: the definition, the rows, the old copies that stay on
#      every node until they are dropped, the verification
#   B. a writer on another node races every phase of the operation (the call is held at the point, the writer goes on or waits for the locks
#      of the switch); the table is the table of a twin that got the same writes
#   C. an error at every point: the table is as it was, nothing is left on any node, and the next call succeeds; an error after the switch is
#      finished by another call
#   D. refusals before anything is made, code of an untrusted role, the DDL guard on every node, a cancel

