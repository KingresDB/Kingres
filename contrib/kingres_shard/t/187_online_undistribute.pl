my ($n1, $n2, $n3) = make_cluster('ou', 3);
my @nodes = ($n1, $n2, $n3);
sub q1 { my ($node, $sql) = @_; return $node->safe_psql('postgres', $sql); }

for my $n (@nodes)
{
	$n->append_conf('postgresql.conf', "kingres_shard.rebuild_batch_rows = 100\nkingres_shard.node_timeout = 10\n");
	$n->reload;
}
$_->safe_psql('postgres', q{CREATE ROLE ou_owner LOGIN; CREATE ROLE ou_reader; GRANT CREATE, USAGE ON SCHEMA public TO ou_owner}) for @nodes;

my $fingerprint_sql = q{
CREATE FUNCTION public.fingerprint(t regclass) RETURNS SETOF text LANGUAGE sql AS $$
  SELECT 'column ' || a.attnum || ' ' || a.attname || ' ' || format_type(a.atttypid, a.atttypmod)
         || ' notnull=' || a.attnotnull || ' identity=' || a.attidentity::text || ' generated=' || a.attgenerated::text
         || ' default=' || coalesce(pg_get_expr(d.adbin, d.adrelid), '-')
         || ' acl=' || coalesce(a.attacl::text, '-') || ' comment=' || coalesce(col_description(t, a.attnum), '-')
    FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
   WHERE a.attrelid = t AND a.attnum > 0 AND NOT a.attisdropped
  UNION ALL
  SELECT 'constraint ' || c.conname || ' ' || pg_get_constraintdef(c.oid) || ' comment=' || coalesce(obj_description(c.oid, 'pg_constraint'), '-')
    FROM pg_constraint c WHERE c.conrelid = t AND c.conparentid = 0
  UNION ALL
  SELECT 'index ' || ic.relname || ' ' || replace(pg_get_indexdef(i.indexrelid), ' ONLY ', ' ') || ' comment=' || coalesce(obj_description(i.indexrelid, 'pg_class'), '-')
    FROM pg_index i JOIN pg_class ic ON ic.oid = i.indexrelid WHERE i.indrelid = t
  UNION ALL
  SELECT 'table owner=' || c.relowner::regrole || ' acl=' || coalesce(c.relacl::text, '-') || ' comment=' || coalesce(obj_description(t, 'pg_class'), '-')
    FROM pg_class c WHERE c.oid = t
  UNION ALL
  SELECT 'sequence ' || s.seqrelid::regclass || ' type=' || s.seqtypid::regtype || ' start=' || s.seqstart || ' inc=' || s.seqincrement
         || ' min=' || s.seqmin || ' max=' || s.seqmax || ' cache=' || s.seqcache || ' cycle=' || s.seqcycle
    FROM pg_sequence s
   WHERE s.seqrelid IN (SELECT d.objid FROM pg_depend d WHERE d.classid = 'pg_class'::regclass
                         AND d.refclassid = 'pg_class'::regclass AND d.refobjid = t AND d.deptype IN ('a', 'i'))
$$;
};
$_->safe_psql('postgres', $fingerprint_sql) for @nodes;
sub fp { my ($node, $t) = @_; return q1($node, "SELECT line FROM public.fingerprint('$t') line ORDER BY 1"); }

$n1->safe_psql('postgres', q{CREATE TABLE public.k_ref (id int PRIMARY KEY); INSERT INTO public.k_ref SELECT g FROM generate_series(1, 20) g; SELECT kingres.create_reference_table('public.k_ref')});

my $case = 0;
# a table of the kinds of objects, in use, and a twin that gets every write too
sub new_table
{
	my ($name) = @_;
	$n1->safe_psql('postgres', qq{
		CREATE TABLE public.$name (tenant int NOT NULL, id int NOT NULL, v text DEFAULT 'd', qty int, ser serial,
		    ident bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5), calc int GENERATED ALWAYS AS (qty * 2) STORED,
		    r int REFERENCES public.k_ref (id), PRIMARY KEY (tenant, id));
		CREATE INDEX ${name}_v ON public.$name (v);
		COMMENT ON TABLE public.$name IS 'the table'; COMMENT ON INDEX public.${name}_v IS 'by value';
		ALTER TABLE public.$name OWNER TO ou_owner; GRANT SELECT ON public.$name TO ou_reader;
		INSERT INTO public.$name (tenant, id, v, qty, r) SELECT g % 7, g, 'v' || g, g % 50, 1 + g % 20 FROM generate_series(1, 400) g;
		CREATE TABLE public.${name}_tw (tenant int NOT NULL, id int NOT NULL, v text, qty int, PRIMARY KEY (tenant, id));
		INSERT INTO public.${name}_tw SELECT tenant, id, v, qty FROM public.$name;
		SELECT kingres.create_distributed_table('public.$name', 'tenant', bucket_count => 6);
	});
}
sub writes
{
	my ($t, $r) = @_;
	return qq{INSERT INTO public.$t (tenant, id, v, qty) SELECT g % 7, 100000 * $r + g, 'w$r', g FROM generate_series(1, 15) g;
		UPDATE public.$t SET v = 'u$r' WHERE id % 11 = $r % 11 AND id < 1000;
		DELETE FROM public.$t WHERE id % 17 = $r % 17 AND id < 1000 AND id % 2 = 1;};
}
sub content
{
	my ($t) = @_;
	return q1($n1, "SELECT count(*) || '|' || md5(string_agg(tenant || ':' || id || ':' || coalesce(v, '') || ':' || coalesce(qty::text, ''), ',' ORDER BY tenant, id)) FROM public.$t");
}
# The table is an ordinary table on node 1 after the operation and is gone from the other nodes: a statement of a writer on another node that
# comes after the switch fails with "does not exist" and writes nothing (the twin is then not written either); one that comes before it is
# applied, and so is its twin.
sub gone { my ($err) = @_; return $err =~ /relation "public\.\w+" does not exist/; }
sub both
{
	my ($name, $r) = @_;
	my ($rc, $out, $err) = run_sql($n2, writes($name, $r));
	$n1->safe_psql('postgres', writes("${name}_tw", $r)) if $rc == 0;
	return (gone($err) ? 0 : $rc, $err);
}

# nothing of an operation is left on any node
sub no_leftovers
{
	my ($label) = @_;
	for my $n (@nodes)
	{
		is(q1($n, q{SELECT (SELECT count(*) FROM pg_class WHERE relname LIKE 'kingres\_shadow%') || '|' || (SELECT count(*) FROM pg_class WHERE relname LIKE 'tlog\_%')
		            || '|' || (SELECT count(*) FROM pg_trigger WHERE tgname LIKE 'kingres\_capture\_%' OR tgname LIKE 'kingres\_notrunc\_%')
		            || '|' || (SELECT count(*) FROM kingres.table_operation WHERE spec ? 'mirror')}), '0|0|0|0', "$label: no shadow, log, capture trigger or mirror on " . $n->name);
		is(prepared_count($n), '0', "$label: nothing is prepared on " . $n->name);
	}
	is(q1($n1, 'SELECT count(*) FROM kingres.table_operation_lock'), '0', "$label: no group is claimed");
}

# ---------------------------------------------------------------------------
# A. a table with every kind of object, while it is in use
# ---------------------------------------------------------------------------
{
	my $name = 'a1';
	new_table($name);
	my $fp = fp($n1, "public.$name");
	my $gate_tail = '';
	my ($rc, $out, $err) = both($name, 1);
	is($rc, 0, 'A: a write from another node') or diag($err);
	($rc, $out, $err) = run_sql($n1, "SELECT kingres.undistribute_table_concurrently('public.$name')");
	is($rc, 0, 'A: undistribute_table_concurrently runs') or diag($err);
	is(q1($n1, "SELECT count(*) FROM kingres.dist_table WHERE relid = 'public.$name'::regclass"), '0', 'A: the table is not in the catalog');
	is(q1($_, "SELECT count(*) FROM kingres.dist_table"), q1($n1, "SELECT count(*) FROM kingres.dist_table"), 'A: nor in the catalog of ' . $_->name) for ($n2, $n3);
	is(q1($n1, qq{SELECT relkind::text FROM pg_class WHERE oid = 'public.$name'::regclass}), 'r', 'A: it is an ordinary table on node 1');
	is(content($name), content("${name}_tw"), 'A: with the rows of its twin');
	is(fp($n1, "public.$name"), $fp, 'A: the definition is the one of the distributed table');
	is(q1($n2, qq{SELECT to_regclass('public.$name') IS NULL}), 't', 'A: node 2 has no such table');
	is(q1($n1, "SELECT verified FROM kingres.table_operation WHERE op_id = (SELECT max(op_id) FROM kingres.table_operation)"), 'ok', 'A: the verification said ok');
	is(q1($_, q{SELECT count(*) FROM pg_class WHERE relname ~ '^kingres_old_[0-9]+$' AND relkind IN ('r', 'p')}), '1', 'A: the old copy is on ' . $_->name) for @nodes;
	is(q1($n1, q{SELECT count(*) FROM pg_class WHERE relname ~ '^kingres_old_[0-9]+_b[0-9]{4}$'}) > 0 ? 1 : 0, '1', 'A: with its partitions, under names of their own');
	($rc, $out, $err) = run_sql($n1, "INSERT INTO public.$name (tenant, id, qty) VALUES (1, 900000, 5) RETURNING ser, ident");
	is($rc, 0, 'A: the ordinary table takes rows') or diag($err);
	is(q1($n1, 'SELECT kingres.cleanup_table_operations(true)') > 0 ? 1 : 0, '1', 'A: cleanup drops the old copies');
	is(q1($_, q{SELECT count(*) FROM pg_class WHERE relname LIKE 'kingres\_old%'}), '0', 'A: nothing of them is left on ' . $_->name) for @nodes;
	no_leftovers('A');
	is(q1($n1, 'SELECT count(*) FROM kingres.check_cluster()'), '0', 'A: check_cluster() finds nothing');
}

# ---------------------------------------------------------------------------
# B. a writer on another node races every phase
# ---------------------------------------------------------------------------
sub held
{
	my ($point, $call) = @_;
	my $gate = "$PostgreSQL::Test::Utils::tmp_check/gate_${point}_" . ++$case . "_$$";
	append_to_file($gate, 'x');
	my ($hout, $herr) = ('', '');
	my $hh = IPC::Run::start([ 'psql', '-X', '-At', '-h', $n1->host, '-p', $n1->port, '-d', 'postgres',
		'-c', "SET kingres_shard.fault_injection = '$point:wait:$gate'", '-c', "SELECT $call" ], '>', \$hout, '2>', \$herr);
	return { h => $hh, out => \$hout, err => \$herr, gate => $gate };
}
sub any_waiter
{
	for (my $i = 0; $i < 600; $i++)
	{
		for my $n (@nodes) { return 1 if q1($n, 'SELECT count(*) FROM pg_locks WHERE NOT granted') > 0; }
		select(undef, undef, undef, 0.1);
	}
	return 0;
}

my @points = qw(rebuild_after_preparing rebuild_after_shadow rebuild_after_capture rebuild_copy_chunk rebuild_after_copy rebuild_replay_chunk
	rebuild_before_switch rebuild_switch_after_lock rebuild_switch_after_final_replay rebuild_switch_before_swap rebuild_after_switch);
my %blocks = map { $_ => 1 } qw(rebuild_switch_after_lock rebuild_switch_after_final_replay rebuild_switch_before_swap);
for my $point (@points)
{
	my $name = 'b' . ++$case;
	new_table($name);
	my $h = held($point, "kingres.undistribute_table_concurrently('public.$name')");
	ok(wait_for_fault_file("$h->{gate}.reached", 60), "B $point: the call is held");
	# the locks of the switch are held on EVERY node, not only where the call runs: the parent table has the mode of the phase on each one
	if ($blocks{$point})
	{
		my $mode = $point eq 'rebuild_switch_before_swap' ? 'AccessExclusiveLock' : 'ExclusiveLock';
		for my $n (@nodes)
		{
			is(q1($n, "SELECT count(*) FROM pg_locks WHERE locktype = 'relation' AND relation = 'public.$name'::regclass AND mode = '$mode' AND granted"), '1',
			   "B $point: the table is locked in $mode on " . $n->name);
		}
	}
	my ($rc, $err, $w);
	if ($blocks{$point})
	{
		# the locks of the switch are held: a writer waits for them, and goes on when the switch is over
		$w = start_psql($n2, writes($name, $case));
		ok(any_waiter(), "B $point: a writer on another node waits for the locks of the switch");
	}
	else
	{
		($rc, $err) = both($name, $case);
		is($rc, 0, "B $point: a writer on another node goes on") or diag($err);
	}
	unlink $h->{gate};
	my ($out, $herr) = finish_psql($h);
	is($herr, '', "B $point: the call succeeds") or diag($herr);
	if ($w)
	{
		my ($wout, $werr) = finish_psql($w);
		ok($werr eq '' || gone($werr), "B $point: the writer that waited ends cleanly (it ran, or the table is gone from its node)") or diag($werr);
		$n1->safe_psql('postgres', writes("${name}_tw", $case)) if $werr eq '';
	}
	is(q1($n1, "SELECT count(*) FROM kingres.dist_table WHERE relid = 'public.$name'::regclass"), '0', "B $point: the table is undistributed");
	is(content($name), content("${name}_tw"), "B $point: its rows are the rows of the twin: no change of the writer is lost");
	isnt(q1($n1, "SELECT verified FROM kingres.table_operation WHERE op_id = (SELECT max(op_id) FROM kingres.table_operation)"), 'failed', "B $point: the verification did not fail");
	$n1->safe_psql('postgres', 'SELECT kingres.cleanup_table_operations(true)');
	no_leftovers("B $point");
}

# ---------------------------------------------------------------------------
# C. an error at every point
# ---------------------------------------------------------------------------
sub state { my ($name) = @_; return content($name) . '|' . q1($n1, "SELECT relkind::text FROM pg_class WHERE oid = 'public.$name'::regclass") . '|' . q1($n1, "SELECT colocation_id FROM kingres.dist_table WHERE relid = 'public.$name'::regclass"); }
for my $point (@points[0 .. 9], qw(rebuild_switch_after_local_swap rebuild_switch_after_remote_swap rebuild_switch_after_prepare))
{
	my $name = 'e' . ++$case;
	new_table($name);
	my $before = state($name);
	my ($rc, $out, $err) = run_sql($n1, "SET kingres_shard.fault_injection = '$point:error'; SELECT kingres.undistribute_table_concurrently('public.$name')");
	isnt($rc, 0, "C $point: the call fails");
	like($err, qr/injected failure at \Q$point\E/, "C $point: it is the injected error");
	is(state($name), $before, "C $point: the table is as it was");
	is(q1($n1, "SELECT phase FROM kingres.table_operation WHERE op_id = (SELECT max(op_id) FROM kingres.table_operation)"), 'failed', "C $point: the operation is recorded as failed");
	no_leftovers("C $point");
	($rc, $out, $err) = run_sql($n1, "SELECT kingres.undistribute_table_concurrently('public.$name')");
	is($rc, 0, "C $point: the next call succeeds") or diag($err);
	is(content($name), content("${name}_tw"), "C $point: with every row");
	$n1->safe_psql('postgres', 'SELECT kingres.cleanup_table_operations(true)');
}
for my $point (qw(rebuild_verify rebuild_cleanup))
{
	my $name = 'f' . ++$case;
	new_table($name);
	my ($rc, $out, $err) = run_sql($n1, "SET kingres_shard.fault_injection = '$point:error'; SELECT kingres.undistribute_table_concurrently('public.$name')");
	isnt($rc, 0, "C $point: the call fails after the switch");
	my $op = q1($n1, 'SELECT max(op_id) FROM kingres.table_operation');
	is(q1($n1, "SELECT phase FROM kingres.table_operation WHERE op_id = $op"), 'cleaning', "C $point: the operation is in cleaning");
	is(q1($n1, qq{SELECT relkind::text FROM pg_class WHERE oid = 'public.$name'::regclass}), 'r', "C $point: the table is an ordinary table");
	is(content($name), content("${name}_tw"), "C $point: with its rows");
	is(q1($n1, "SELECT kingres.table_operation_advance($op, 'cleaning')"), 'done', "C $point: another call finishes it");
	$n1->safe_psql('postgres', 'SELECT kingres.cleanup_table_operations(true)');
	no_leftovers("C $point");
}

# ---------------------------------------------------------------------------
# D. refusals, untrusted code, the guard on every node, a cancel
# ---------------------------------------------------------------------------
{
	$n1->safe_psql('postgres', q{
		CREATE TABLE public.d_nokey (tenant int, id int, v text); INSERT INTO public.d_nokey SELECT g % 3, g, 'x' FROM generate_series(1, 20) g;
		SELECT kingres.create_distributed_table('public.d_nokey', 'tenant', bucket_count => 3);
		CREATE TABLE public.d_plain (id int PRIMARY KEY);
		CREATE TABLE public.d_p (id int PRIMARY KEY, v text); CREATE TABLE public.d_c (id int PRIMARY KEY, w text);
		INSERT INTO public.d_p SELECT g, 'p' FROM generate_series(1, 30) g; INSERT INTO public.d_c SELECT g, 'c' FROM generate_series(1, 30) g;
		SELECT kingres.create_distributed_table('public.d_p', 'id', bucket_count => 4);
		SELECT kingres.create_distributed_table('public.d_c', 'id', colocate_with => 'public.d_p');
		ALTER TABLE public.d_c ADD CONSTRAINT d_c_p FOREIGN KEY (id) REFERENCES public.d_p (id);
	});
	my ($rc, $out, $err) = run_sql($n1, "SELECT kingres.undistribute_table_concurrently('public.d_nokey')");
	isnt($rc, 0, 'D: a table without a key is refused'); like($err, qr/no primary key or unique index/, 'D: and the error says what is needed');
	($rc, $out, $err) = run_sql($n1, "SELECT kingres.undistribute_table_concurrently('public.d_plain')");
	isnt($rc, 0, 'D: an ordinary table is refused');
	($rc, $out, $err) = run_sql($n1, "SELECT kingres.undistribute_table_concurrently('public.d_p', true)");
	isnt($rc, 0, 'D: tables that are linked by keys are left to the blocking variant'); like($err, qr/blocking variant/, 'D: and the error says so');
	($rc, $out, $err) = run_sql($n2, "SELECT kingres.undistribute_table_concurrently('public.d_p')");
	isnt($rc, 0, 'D: a node that is not the map group primary refuses');
	is(q1($n1, 'SELECT count(*) FROM kingres.table_operation'), q1($n1, 'SELECT count(*) FROM kingres.table_operation WHERE phase IN (\'failed\', \'cancelled\', \'done\')'), 'D: no operation was left behind');
	no_leftovers('D refusals');

	# code of an untrusted role is not run by the copy: a domain check whose function belongs to a role who is not a superuser
	$_->safe_psql('postgres', q{
		CREATE ROLE ou_evil; GRANT CREATE ON SCHEMA public TO ou_evil;
		CREATE FUNCTION public.ou_chk(int) RETURNS bool LANGUAGE sql AS 'SELECT true';
		CREATE DOMAIN public.ou_dom AS int CHECK (public.ou_chk(VALUE));
	}) for @nodes;
	$n1->safe_psql('postgres', q{
		CREATE TABLE public.d_dom (tenant int NOT NULL, id int NOT NULL, x public.ou_dom, PRIMARY KEY (tenant, id)); INSERT INTO public.d_dom SELECT g % 3, g, g FROM generate_series(1, 20) g;
		SELECT kingres.create_distributed_table('public.d_dom', 'tenant', bucket_count => 3);
	});
	$_->safe_psql('postgres', 'ALTER FUNCTION public.ou_chk(int) OWNER TO ou_evil') for @nodes;
	for my $call ("kingres.undistribute_table_concurrently('public.d_dom')", "kingres.undistribute_table('public.d_dom')")
	{
		($rc, $out, $err) = run_sql($n1, "SELECT $call");
		isnt($rc, 0, "D: $call refuses code of an untrusted role");
		like($err, qr/function_owner_not_superuser:|who is not a superuser/s, 'D: and says why') or diag($err);
	}
	is(q1($n1, q{SELECT count(*) FROM kingres.dist_table WHERE relid = 'public.d_dom'::regclass}), '1', 'D: the table is still distributed');
	no_leftovers('D untrusted');

	# the DDL guard on every node, and a cancel
	my $name = 'g' . ++$case;
	new_table($name);
	my $h = held('rebuild_after_copy', "kingres.undistribute_table_concurrently('public.$name')");
	ok(wait_for_fault_file("$h->{gate}.reached", 60), 'D: a call is held after the copy');
	my $op = q1($n1, 'SELECT max(op_id) FROM kingres.table_operation');
	($rc, $out, $err) = run_sql($n1, "ALTER TABLE public.$name ADD COLUMN extra int");
	isnt($rc, 0, 'D: ALTER TABLE on the map group primary is refused'); like($err, qr/is being rebuilt by table operation $op/, 'D: and says why');
	for my $n ($n2, $n3)
	{
		for my $stmt ("DROP TRIGGER kingres_capture_$op ON public.$name", "ALTER TABLE public.$name RENAME TO ${name}_x", "CREATE INDEX ON public.$name (qty)")
		{
			($rc, $out, $err) = run_sql($n, "SET ROLE ou_owner; $stmt");
			isnt($rc, 0, "D: on " . $n->name . ": $stmt is refused");
			like($err, qr/is being rebuilt by table operation $op|permission denied|must be owner/, 'D: with a reason') or diag($err);
		}
	}
	($rc, $out, $err) = run_sql($n2, "TRUNCATE public.$name");
	isnt($rc, 0, 'D: TRUNCATE from another node is refused'); like($err, qr/is being rebuilt|TRUNCATE is not allowed/, 'D: and says why');
	# a cancel from another session: the call ends, everything is undone
	q1($n1, "SELECT kingres.cancel_table_operation($op)");
	unlink $h->{gate};
	my ($hout, $herr) = finish_psql($h);
	isnt($herr, '', 'D: the call that was cancelled fails');
	is(q1($n1, "SELECT phase FROM kingres.table_operation WHERE op_id = $op"), 'cancelled', 'D: the operation is cancelled');
	is(q1($n1, "SELECT count(*) FROM kingres.dist_table WHERE relid = 'public.$name'::regclass"), '1', 'D: the table is still distributed');
	is(content($name), content("${name}_tw"), 'D: with its rows');
	no_leftovers('D cancel');
}
done_testing();
