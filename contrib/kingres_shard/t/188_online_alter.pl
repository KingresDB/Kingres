$_->safe_psql('postgres', q{CREATE FUNCTION public.part_rows(t regclass) RETURNS bigint LANGUAGE plpgsql AS $$ DECLARE r record; n bigint := 0; c bigint; BEGIN FOR r IN SELECT inhrelid::regclass AS p FROM pg_inherits WHERE inhparent = t LOOP EXECUTE format('SELECT count(*) FROM %s', r.p) INTO c; n := n + c; END LOOP; RETURN n; END $$}) for @nodes;
sub fp { my ($node, $t) = @_; return q1($node, "SELECT line FROM public.fingerprint('$t') line ORDER BY 1"); }

$n1->safe_psql('postgres', q{CREATE TABLE public.k_ref (id int PRIMARY KEY); INSERT INTO public.k_ref SELECT g FROM generate_series(1, 20) g; SELECT kingres.create_reference_table('public.k_ref')});

