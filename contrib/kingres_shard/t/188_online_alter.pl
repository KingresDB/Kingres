# a table of the kinds of objects, in use, and a twin that gets every write too
sub new_table
{
	my ($name) = @_;
	$n1->safe_psql('postgres', qq{
		CREATE TABLE public.$name (tenant int NOT NULL, id int NOT NULL, v text DEFAULT 'd', qty int, ser serial,
		    ident bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5), calc int GENERATED ALWAYS AS (qty * 2) STORED,
		    r int REFERENCES public.k_ref (id), PRIMARY KEY (tenant, id));
		CREATE INDEX ${name}_v ON public.$name (v);
		COMMENT ON TABLE public.$name IS 'the table'; COMMENT ON INDEX public.${name}_v IS 'by value';
		ALTER TABLE public.$name OWNER TO ou_owner; GRANT SELECT ON public.$name TO ou_reader;
		INSERT INTO public.$name (tenant, id, v, qty, r) SELECT g % 7, g, 'v' || g, g % 50, 1 + g % 20 FROM generate_series(1, 400) g;
		CREATE TABLE public.${name}_tw (tenant int NOT NULL, id int NOT NULL, v text, qty int, PRIMARY KEY (tenant, id));
		INSERT INTO public.${name}_tw SELECT tenant, id, v, qty FROM public.$name;
		SELECT kingres.create_distributed_table('public.$name', 'tenant', bucket_count => 6);
	});
}
sub writes
{
	my ($t, $r) = @_;
	return qq{INSERT INTO public.$t (tenant, id, v, qty) SELECT g % 7, 100000 * $r + g, 'w$r', g FROM generate_series(1, 15) g;
		UPDATE public.$t SET v = 'u$r' WHERE id % 11 = $r % 11 AND id < 1000;
		DELETE FROM public.$t WHERE id % 17 = $r % 17 AND id < 1000 AND id % 2 = 1;};
}
sub content
{
	my ($t) = @_;
	return q1($n1, "SELECT count(*) || '|' || md5(string_agg(tenant || ':' || id || ':' || coalesce(v, '') || ':' || coalesce(qty::text, ''), ',' ORDER BY tenant, id)) FROM public.$t");
}
# The table is an ordinary table on node 1 after the operation and is gone from the other nodes: a statement of a writer on another node that
# comes after the switch fails with "does not exist" and writes nothing (the twin is then not written either); one that comes before it is
# applied, and so is its twin.
sub gone { my ($err) = @_; return $err =~ /relation "public\.\w+" does not exist/; }
sub both
{
	my ($name, $r) = @_;
	my ($rc, $out, $err) = run_sql($n2, writes($name, $r));
	$n1->safe_psql('postgres', writes("${name}_tw", $r)) if $rc == 0;
	return (gone($err) ? 0 : $rc, $err);
}

# nothing of an operation is left on any node
sub no_leftovers
{
	my ($label) = @_;
	for my $n (@nodes)
	{
		is(q1($n, q{SELECT (SELECT count(*) FROM pg_class WHERE relname LIKE 'kingres\_shadow%') || '|' || (SELECT count(*) FROM pg_class WHERE relname LIKE 'tlog\_%')
		            || '|' || (SELECT count(*) FROM pg_trigger WHERE tgname LIKE 'kingres\_capture\_%' OR tgname LIKE 'kingres\_notrunc\_%')
		            || '|' || (SELECT count(*) FROM kingres.table_operation WHERE spec ? 'mirror')}), '0|0|0|0', "$label: no shadow, log, capture trigger or mirror on " . $n->name);
		is(prepared_count($n), '0', "$label: nothing is prepared on " . $n->name);
	}
	is(q1($n1, 'SELECT count(*) FROM kingres.table_operation_lock'), '0', "$label: no group is claimed");
}


# ---------------------------------------------------------------------------
# A. a table with every kind of object, in use: more buckets (the buckets stay on their nodes), another distribution column
# ---------------------------------------------------------------------------
sub layout_ok
{
	my ($label, $t, $key, $rows) = @_;
	my $total = 0;
	for my $n (@nodes)
	{
			$total += q1($n, qq{SELECT public.part_rows('$t'::regclass)});
	}
	is($total, $rows, "$label: every row is stored once in the partitions");
}
sub groups_of { my ($name) = @_; return q1($n1, "SELECT string_agg(m.bucket || ':' || m.group_id, ',' ORDER BY m.bucket) FROM kingres.bucket_map m JOIN kingres.dist_table d USING (colocation_id) WHERE d.relid = 'public.$name'::regclass"); }
sub nrows { my ($name) = @_; return q1($n1, "SELECT count(*) FROM public.$name"); }
{
	my $name = 'a1';
	new_table($name);
	my $fp = fp($n1, "public.$name");
	my %old = map { split /:/ } split /,/, groups_of($name);
	my ($rc, $out, $err) = both($name, 1);
	is($rc, 0, 'A: a write from another node') or diag($err);
	my $oid = q1($n1, "SELECT 'public.$name'::regclass::oid");
	($rc, $out, $err) = run_sql($n1, "SELECT kingres.alter_distributed_table_concurrently('public.$name', bucket_count => 12)");
	is($rc, 0, 'A: alter_distributed_table_concurrently runs') or diag($err);
	isnt(q1($n1, "SELECT 'public.$name'::regclass::oid"), $oid, 'A: it is another table');
	is(q1($n1, "SELECT bucket_count FROM kingres.colocation WHERE colocation_id = (SELECT colocation_id FROM kingres.dist_table WHERE relid = 'public.$name'::regclass)"), '12', 'A: of twelve buckets');
	is(content($name), content("${name}_tw"), 'A: with the rows of its twin');
	is(fp($n1, "public.$name"), $fp, 'A: the definition is the same');
	layout_ok('A', "public.$name", 'tenant', nrows($name));
	my %new = map { split /:/ } split /,/, groups_of($name);
	is(join(',', map { $new{$_} == $old{$_ % 6} ? 'ok' : "bad$_" } sort { $a <=> $b } keys %new), join(',', ('ok') x 12), 'A: every new bucket is where its rows were');
	is(q1($_, "SELECT count(*) FROM kingres.dist_table WHERE relid = 'public.$name'::regclass"), '1', 'A: the catalog of ' . $_->name . ' has the table') for @nodes;
	is(q1($n1, "SELECT count(*) FROM kingres.colocation"), '1', 'A: the old group is gone');
	is(q1($n1, "SELECT verified FROM kingres.table_operation WHERE op_id = (SELECT max(op_id) FROM kingres.table_operation)"), 'ok', 'A: the verification said ok');
	is(q1($_, q{SELECT count(*) FROM pg_class WHERE relname ~ '^kingres_old_[0-9]+$' AND relkind IN ('r', 'p')}), '1', 'A: the old copy is on ' . $_->name) for @nodes;
	is(q1($n1, q{SELECT count(*) FROM pg_index i JOIN pg_class ic ON ic.oid = i.indexrelid JOIN pg_class c ON c.oid = i.indrelid JOIN pg_inherits h ON h.inhrelid = c.oid
	              WHERE h.inhparent = 'public.a1'::regclass AND ic.relname NOT LIKE c.relname || '\_%'}), '0', 'A: the indexes of the partitions are named after their partitions');
	($rc, $out, $err) = both($name, 2);
	is($rc, 0, 'A: the new table takes writes from another node') or diag($err);
	is(content($name), content("${name}_tw"), 'A: and keeps matching its twin');
	($rc, $out, $err) = run_sql($n1, "ALTER TABLE public.$name ADD COLUMN extra int");
	is($rc, 0, 'A: DDL on the new table goes to every node') or diag($err);
	is(q1($n3, qq{SELECT count(*) FROM pg_attribute WHERE attrelid = 'public.$name'::regclass AND attname = 'extra'}), '1', 'A: node 3 has the column');
	$n1->safe_psql('postgres', "ALTER TABLE public.$name DROP COLUMN extra");
	is(q1($n1, 'SELECT kingres.cleanup_table_operations(true)') > 0 ? 1 : 0, '1', 'A: cleanup drops the old copies');
	is(q1($_, q{SELECT count(*) FROM pg_class WHERE relname LIKE 'kingres\_old%'}), '0', 'A: nothing of them is left on ' . $_->name) for @nodes;
	no_leftovers('A');
	is(q1($n1, 'SELECT count(*) FROM kingres.check_cluster()'), '0', 'A: check_cluster() finds nothing');

	# another distribution column
	($rc, $out, $err) = run_sql($n1, "SELECT kingres.alter_distributed_table_concurrently('public.$name', distribution_column => 'id')");
	is($rc, 0, 'A: another distribution column') or diag($err);
	like(q1($n1, "SELECT dist_column FROM kingres.dist_table WHERE relid = 'public.$name'::regclass"), qr/^id$/, 'A: the catalog has it');
	is(content($name), content("${name}_tw"), 'A: with the rows of its twin');
	layout_ok('A', "public.$name", 'id', nrows($name));
	is(fp($n1, "public.$name"), $fp, 'A: and the same definition');
	$n1->safe_psql('postgres', 'SELECT kingres.cleanup_table_operations(true)');
	no_leftovers('A column');

	# a request that moves no rows is the blocking function's: nothing to follow
	($rc, $out, $err) = run_sql($n1, "SELECT kingres.alter_distributed_table_concurrently('public.$name', colocate_with => 'none')");
	is($rc, 0, 'A: a change of the catalog only runs') or diag($err);
	is($out, '', 'A: and returns no operation');
}

# ---------------------------------------------------------------------------
# B. a writer on another node races every phase
# ---------------------------------------------------------------------------
sub held
{
	my ($point, $call) = @_;
	my $gate = "$PostgreSQL::Test::Utils::tmp_check/gate_${point}_" . ++$case . "_$$";
	append_to_file($gate, 'x');
	my ($hout, $herr) = ('', '');
	my $hh = IPC::Run::start([ 'psql', '-X', '-At', '-h', $n1->host, '-p', $n1->port, '-d', 'postgres',
		'-c', "SET kingres_shard.fault_injection = '$point:wait:$gate'", '-c', "SELECT $call" ], '>', \$hout, '2>', \$herr);
	return { h => $hh, out => \$hout, err => \$herr, gate => $gate };
}
sub any_waiter
{
	for (my $i = 0; $i < 600; $i++)
	{
		for my $n (@nodes) { return 1 if q1($n, 'SELECT count(*) FROM pg_locks WHERE NOT granted') > 0; }
		select(undef, undef, undef, 0.1);
	}
	return 0;
}
my @points = qw(rebuild_after_preparing rebuild_after_shadow rebuild_after_capture rebuild_copy_chunk rebuild_after_copy rebuild_replay_chunk
	rebuild_before_switch rebuild_switch_after_lock rebuild_switch_after_final_replay rebuild_switch_before_swap rebuild_after_switch);
my %blocks = map { $_ => 1 } qw(rebuild_switch_after_lock rebuild_switch_after_final_replay rebuild_switch_before_swap);
for my $point (@points)
{
	my $name = 'b' . ++$case;
	new_table($name);
	my $h = held($point, "kingres.alter_distributed_table_concurrently('public.$name', bucket_count => 9)");
	ok(wait_for_fault_file("$h->{gate}.reached", 60), "B $point: the call is held");
	# the locks of the switch are held on EVERY node, not only where the call runs: the parent table has the mode of the phase on each one
	if ($blocks{$point})
	{
		my $mode = $point eq 'rebuild_switch_before_swap' ? 'AccessExclusiveLock' : 'ExclusiveLock';
		for my $n (@nodes)
		{
			is(q1($n, "SELECT count(*) FROM pg_locks WHERE locktype = 'relation' AND relation = 'public.$name'::regclass AND mode = '$mode' AND granted"), '1',
			   "B $point: the table is locked in $mode on " . $n->name);
		}
	}
	my ($w, $rc, $err);
	if ($blocks{$point})
	{
		$w = start_psql($n2, writes($name, $case));
		ok(any_waiter(), "B $point: a writer on another node waits for the locks of the switch");
	}
	else
	{
		($rc, $err) = both($name, $case);
		is($rc, 0, "B $point: a writer on another node goes on") or diag($err);
	}
	unlink $h->{gate};
	my ($out, $herr) = finish_psql($h);
	($point eq 'rebuild_after_switch' ? like($herr, qr/\A(?:WARNING:  the verification of table operation \d+ was not done: the table was written to after the switch.*)?\z/s, "B $point: the call ends, with the warning that the verification is not possible after writes") : is($herr, '', "B $point: the call succeeds")) or diag($herr);
	if ($w)
	{
		my ($wout, $werr) = finish_psql($w);
		is($werr, '', "B $point: the writer that waited goes on, on the new table") or diag($werr);
		$n1->safe_psql('postgres', writes("${name}_tw", $case)) if $werr eq '';
	}
	is(q1($n1, "SELECT bucket_count FROM kingres.colocation WHERE colocation_id = (SELECT colocation_id FROM kingres.dist_table WHERE relid = 'public.$name'::regclass)"), '9', "B $point: the table has nine buckets");
	is(content($name), content("${name}_tw"), "B $point: its rows are the rows of the twin: no change of the writer is lost");
	layout_ok("B $point", "public.$name", 'tenant', nrows($name));
	isnt(q1($n1, "SELECT verified FROM kingres.table_operation WHERE op_id = (SELECT max(op_id) FROM kingres.table_operation)"), 'failed', "B $point: the verification did not fail");
	$n1->safe_psql('postgres', 'SELECT kingres.cleanup_table_operations(true)');
	no_leftovers("B $point");
}

