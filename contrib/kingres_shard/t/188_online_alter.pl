sub state { my ($name) = @_; return content($name) . '|' . q1($n1, "SELECT relkind::text FROM pg_class WHERE oid = 'public.$name'::regclass") . '|' . q1($n1, "SELECT colocation_id FROM kingres.dist_table WHERE relid = 'public.$name'::regclass") . '|' . q1($n1, 'SELECT count(*) FROM kingres.colocation'); }
for my $point (@points[0 .. 9], qw(rebuild_switch_after_local_swap rebuild_switch_after_remote_swap rebuild_switch_after_prepare))
{
	my $name = 'e' . ++$case;
	new_table($name);
	my $before = state($name);
	my ($rc, $out, $err) = run_sql($n1, "SET kingres_shard.fault_injection = '$point:error'; SELECT kingres.alter_distributed_table_concurrently('public.$name', bucket_count => 9)");
	isnt($rc, 0, "C $point: the call fails");
	like($err, qr/injected failure at \Q$point\E/, "C $point: it is the injected error");
	is(state($name), $before, "C $point: the table is as it was, and so are the groups");
	is(q1($n1, "SELECT phase FROM kingres.table_operation WHERE op_id = (SELECT max(op_id) FROM kingres.table_operation)"), 'failed', "C $point: the operation is recorded as failed");
	no_leftovers("C $point");
	layout_ok("C $point", "public.$name", 'tenant', nrows($name));
	($rc, $out, $err) = run_sql($n1, "SELECT kingres.alter_distributed_table_concurrently('public.$name', bucket_count => 9)");
	is($rc, 0, "C $point: the next call succeeds") or diag($err);
	is(content($name), content("${name}_tw"), "C $point: with every row");
	$n1->safe_psql('postgres', 'SELECT kingres.cleanup_table_operations(true)');
}
