-- Is the table named by a policy row one that the calling role owns (has the
-- privileges of the owner of)?  Used by the views of the policy
-- and history tables, so it judges current_user, the role whose privileges
-- PostgreSQL is applying, and not the role that logged in.
CREATE FUNCTION kingres.timepart__owns(p_schema name, p_table name)
RETURNS boolean
LANGUAGE sql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
    SELECT coalesce(
        (SELECT pg_has_role(current_user, c.relowner, 'USAGE')
           FROM pg_class c
          WHERE c.oid = kingres.timepart__oid(p_schema, p_table)
            AND c.relkind = 'p'), false)
$$;

-- What the views of the policy and the history show to the calling role: the
-- rows of the tables it owns; a superuser sees every row (the policy of a
-- table that is gone too: timepart_check reports it).
CREATE FUNCTION kingres.timepart__visible(p_schema name, p_table name)
RETURNS boolean
LANGUAGE sql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
    SELECT coalesce((SELECT r.rolsuper FROM pg_roles r
                      WHERE r.rolname = current_user), false)
           OR kingres.timepart__owns(p_schema, p_table)
$$;

-- The checks on the values of a policy that do not depend on who sets it.
CREATE FUNCTION kingres.timepart__validate_policy(
    p_keytype text, p_every interval, p_tz text, p_ahead interval,
    p_retention interval, p_action text, p_col_after interval,
    p_col_sort text[], p_col_options jsonb, p_run_every interval)
RETURNS void
LANGUAGE plpgsql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_parts record;
BEGIN
    PERFORM kingres.timepart__check_tz(p_tz);
    SELECT * INTO v_parts FROM kingres.timepart_interval_parts(p_every);
    IF p_keytype = 'date' AND v_parts.unit = 'hour' THEN
        RAISE EXCEPTION 'partition_every in hours needs a timestamp or timestamptz column, not date'
            USING ERRCODE = '22023';
    END IF;
    IF p_ahead IS NULL OR p_ahead < interval '0' THEN
        RAISE EXCEPTION 'create_ahead must not be negative' USING ERRCODE = '22023';
    END IF;
    IF p_run_every IS NULL OR p_run_every <= interval '0' THEN
        RAISE EXCEPTION 'run_every must be positive' USING ERRCODE = '22023';
    END IF;
    IF p_action IS NULL OR p_action NOT IN ('drop', 'detach') THEN
        RAISE EXCEPTION 'retention_action must be drop or detach'
            USING ERRCODE = '22023';
    END IF;
    IF p_retention IS NOT NULL AND p_retention < p_every THEN
        RAISE EXCEPTION 'retention must be at least one partition_every'
            USING ERRCODE = '22023',
                  HINT = 'Retention drops whole partitions only.';
    END IF;
    IF p_col_after IS NOT NULL AND p_col_after < interval '0' THEN
        RAISE EXCEPTION 'columnar_after must not be negative' USING ERRCODE = '22023';
    END IF;
    IF p_col_after IS NOT NULL AND p_retention IS NOT NULL
       AND p_col_after > p_retention THEN
        RAISE EXCEPTION 'columnar_after must not be longer than retention'
            USING ERRCODE = '22023';
    END IF;
    IF p_col_options IS NOT NULL
       AND jsonb_typeof(p_col_options) <> 'object' THEN
        RAISE EXCEPTION 'columnar_options must be a JSON object'
            USING ERRCODE = '22023';
    END IF;
    IF p_col_sort IS NOT NULL
       AND (cardinality(p_col_sort) = 0
            OR array_position(p_col_sort, NULL::text) IS NOT NULL) THEN
        RAISE EXCEPTION 'columnar_sort must be a non-empty list of column names'
            USING ERRCODE = '22023';
    END IF;
END;
$$;

-- The rows of the policy table can be written directly by the role that owns
-- the table (through the view), so what only the extension may decide is
-- pinned here, for every role that is not a superuser: the stamp and the OID
-- hint, the owner recorded for the owner_changed check (renewed only when the
-- policy is written again by a role that owns the table now), who created the
-- policy and when; and the values of the policy are checked.  A superuser
-- (the extension's own code, a restore) is trusted: what it leaves out is
-- filled in, what it gives is kept.
CREATE FUNCTION kingres.timepart__policy_trg()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_oid  oid;
    v_info record;
    v_set  boolean;
    v_me   oid;
BEGIN
    SELECT r.oid INTO v_me FROM pg_roles r WHERE r.rolname = current_user;
    IF EXISTS (SELECT 1 FROM pg_roles r WHERE r.rolname = current_user AND r.rolsuper) THEN
        IF NEW.table_owner_oid IS NULL OR NEW.table_owner IS NULL THEN
            SELECT c.relowner, pg_get_userbyid(c.relowner) INTO NEW.table_owner_oid, NEW.table_owner
              FROM pg_class c WHERE c.oid = kingres.timepart__oid(NEW.schema_name, NEW.table_name);
        END IF;
        IF NEW.created_by IS NULL THEN
            NEW.created_by := current_user;
            NEW.created_by_oid := v_me;
        END IF;
        RETURN NEW;
    END IF;
    v_oid := kingres.timepart__oid(NEW.schema_name, NEW.table_name);
    IF v_oid IS NULL THEN
        RAISE EXCEPTION 'table %.% does not exist',
            quote_ident(NEW.schema_name), quote_ident(NEW.table_name)
            USING ERRCODE = '42P01';
    END IF;
    SELECT * INTO v_info FROM kingres.timepart__key_info(v_oid);
    PERFORM kingres.timepart__require_owner(
        current_user, v_info.r_owner_oid,
        format('%I.%I', v_info.r_schema, v_info.r_table));
    PERFORM kingres.timepart__validate_policy(
        v_info.r_keytype, NEW.partition_every, NEW.timezone, NEW.create_ahead,
        NEW.retention, NEW.retention_action, NEW.columnar_after,
        NEW.columnar_sort, NEW.columnar_options, NEW.run_every);
    NEW.parent_oid := v_oid;
    NEW.stamp := kingres.timepart__stamp();
    IF TG_OP = 'INSERT' THEN
        NEW.table_owner := v_info.r_owner;
        NEW.table_owner_oid := v_info.r_owner_oid;
        NEW.created_by := current_user;
        NEW.created_by_oid := v_me;
        NEW.created_at := now();
        NEW.updated_at := now();
    ELSE
        NEW.created_by := OLD.created_by;
        NEW.created_by_oid := OLD.created_by_oid;
        NEW.created_at := OLD.created_at;
        v_set := (NEW.schema_name, NEW.table_name,
                  NEW.partition_every, NEW.timezone, NEW.create_ahead,
                  NEW.retention, NEW.retention_action, NEW.columnar_after,
                  NEW.columnar_sort, NEW.columnar_options, NEW.run_every,
                  NEW.enabled, NEW.updated_at)
                 IS DISTINCT FROM
                 (OLD.schema_name, OLD.table_name,
                  OLD.partition_every, OLD.timezone, OLD.create_ahead,
                  OLD.retention, OLD.retention_action, OLD.columnar_after,
                  OLD.columnar_sort, OLD.columnar_options, OLD.run_every,
                  OLD.enabled, OLD.updated_at);
        IF v_set THEN
            NEW.table_owner := v_info.r_owner;
            NEW.table_owner_oid := v_info.r_owner_oid;
            NEW.updated_at := now();
        ELSE
            NEW.table_owner := OLD.table_owner;
            NEW.table_owner_oid := OLD.table_owner_oid;
            NEW.stamp := OLD.stamp;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER timepart_policy_pin
    BEFORE INSERT OR UPDATE ON kingres.timepart_policy_data
    FOR EACH ROW EXECUTE FUNCTION kingres.timepart__policy_trg();

-- What a role may see and change of the three tables is decided by views, not
-- by row-level security.  Row-level security would make pg_dump fail for
-- every role that is not a superuser, not the owner and without BYPASSRLS,
-- also a role with pg_read_all_data, because pg_dump runs with
-- row_security = off.  The base tables grant nothing to PUBLIC, so pg_dump
-- (a superuser, or a role that reads every table) reads them as they are.
-- Everybody else reaches them through these views.  A view is checked
-- against the privileges of its owner (the extension owner) for the table it
-- reads, while the condition of the view calls timepart__visible, which judges
-- current_user: the role whose privileges PostgreSQL is applying, also inside
-- a SECURITY DEFINER function of another role.  security_barrier keeps a
-- function of the caller in a WHERE clause from seeing a row before the
-- condition of the view has hidden it, and the CASCADED CHECK OPTION keeps a
-- write from making a row the view would not show (a policy for a table the
-- role does not own).  The views are not security_invoker: that would check
-- the privileges of the caller on the base tables, which has none.
-- The roles are shown by their names in the catalog now (table_owner and
-- created_by are computed, so they cannot be written; the trigger decides
-- them).  A policy is shown to the roles that own its table now.  A run is
-- shown to the roles that owned the table when the run began (see
-- timepart__run_visible), so the history of a dropped table stays with the
-- owner it had and is not shown to whoever makes a table of that name later;
-- table_oid is the table the run was made for, null when it is gone.
CREATE VIEW kingres.timepart_policy WITH (security_barrier = true) AS
SELECT p.schema_name, p.table_name, p.parent_oid, p.partition_every,
       p.timezone, p.create_ahead, p.retention, p.retention_action,
       p.columnar_after, p.columnar_sort, p.columnar_options, p.run_every,
       p.enabled, p.next_run_at,
       kingres.timepart__role_name(p.stamp, p.table_owner_oid, p.table_owner)
           AS table_owner,
       kingres.timepart__role_name(p.stamp, p.created_by_oid, p.created_by)
           AS created_by,
       p.created_at, p.updated_at
  FROM kingres.timepart_policy_data p
 WHERE kingres.timepart__visible(p.schema_name, p.table_name)
WITH CASCADED CHECK OPTION;

CREATE VIEW kingres.timepart_run WITH (security_barrier = true) AS
SELECT r.run_id, r.schema_name, r.table_name,
       kingres.timepart__run_table(r.stamp, r.table_oid, r.schema_name,
                                   r.table_name, r.table_owner_oid,
                                   r.table_owner) AS table_oid,
       kingres.timepart__role_name(r.stamp, r.table_owner_oid, r.table_owner)
           AS table_owner,
       r.as_of, r.trigger, r.state, r.started_at, r.finished_at,
       kingres.timepart__role_name(r.stamp, r.started_by_oid, r.started_by)
           AS started_by,
       r.error, r.backend_pid, r.backend_start
  FROM kingres.timepart_run_data r
 WHERE kingres.timepart__run_visible(r.stamp, r.table_owner_oid, r.table_owner);

CREATE VIEW kingres.timepart_run_action WITH (security_barrier = true) AS
SELECT a.* FROM kingres.timepart_run_action_data a
 WHERE EXISTS (SELECT 1 FROM kingres.timepart_run_data r
                WHERE r.run_id = a.run_id
                  AND kingres.timepart__run_visible(r.stamp, r.table_owner_oid,
                                                    r.table_owner));

CREATE FUNCTION kingres.timepart_set_policy(
    rel regclass, partition_every interval,
    create_ahead interval DEFAULT '7 days',
    retention interval DEFAULT NULL,
    retention_action text DEFAULT 'drop',
    columnar_after interval DEFAULT NULL,
    columnar_sort text[] DEFAULT NULL,
    columnar_options jsonb DEFAULT NULL,
    timezone text DEFAULT 'UTC',
    run_every interval DEFAULT '1 hour',
    enabled boolean DEFAULT true)
RETURNS void
LANGUAGE plpgsql
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_info   record;
BEGIN
    SELECT * INTO v_info FROM kingres.timepart__key_info(rel::oid);
    PERFORM kingres.timepart__require_owner(
        current_user, v_info.r_owner_oid,
        format('%I.%I', v_info.r_schema, v_info.r_table));
    IF v_info.r_default IS NOT NULL THEN
        RAISE EXCEPTION 'table %.% has a default partition "%"',
            quote_ident(v_info.r_schema), quote_ident(v_info.r_table),
            v_info.r_default
            USING ERRCODE = '0A000',
                  HINT = 'ATTACH PARTITION scans the default partition under a strong lock, and DETACH ... CONCURRENTLY is refused; create partitions far enough ahead instead.';
    END IF;
    PERFORM kingres.timepart__validate_policy(
        v_info.r_keytype, partition_every, timezone, create_ahead, retention,
        retention_action, columnar_after, columnar_sort, columnar_options,
        run_every);

    -- A role writes through the view, and the trigger pins what it must not
    -- choose (the owner, the stamp, who made the policy).  A superuser, which
    -- the trigger trusts, writes the table itself, with the same values.
    IF EXISTS (SELECT 1 FROM pg_roles r
                WHERE r.rolname = current_user AND r.rolsuper) THEN
        INSERT INTO kingres.timepart_policy_data AS p (
            schema_name, table_name, parent_oid, partition_every, timezone,
            create_ahead, retention, retention_action, columnar_after,
            columnar_sort, columnar_options, run_every, enabled, table_owner,
            table_owner_oid, created_by, created_by_oid, stamp)
        VALUES (
            v_info.r_schema, v_info.r_table, rel::oid, partition_every, timezone,
            create_ahead, retention, retention_action, columnar_after,
            columnar_sort, columnar_options, run_every, enabled, v_info.r_owner,
            v_info.r_owner_oid, current_user,
            (SELECT r.oid FROM pg_roles r WHERE r.rolname = current_user),
            kingres.timepart__stamp())
        ON CONFLICT (schema_name, table_name) DO UPDATE SET
            parent_oid = EXCLUDED.parent_oid,
            partition_every = EXCLUDED.partition_every,
            timezone = EXCLUDED.timezone,
            create_ahead = EXCLUDED.create_ahead,
            retention = EXCLUDED.retention,
            retention_action = EXCLUDED.retention_action,
            columnar_after = EXCLUDED.columnar_after,
            columnar_sort = EXCLUDED.columnar_sort,
            columnar_options = EXCLUDED.columnar_options,
            run_every = EXCLUDED.run_every,
            enabled = EXCLUDED.enabled,
            table_owner = EXCLUDED.table_owner,
            table_owner_oid = EXCLUDED.table_owner_oid,
            stamp = EXCLUDED.stamp,
            updated_at = clock_timestamp();
    ELSE
        INSERT INTO kingres.timepart_policy AS p (
            schema_name, table_name, parent_oid, partition_every, timezone,
            create_ahead, retention, retention_action, columnar_after,
            columnar_sort, columnar_options, run_every, enabled)
        VALUES (
            v_info.r_schema, v_info.r_table, rel::oid, partition_every, timezone,
            create_ahead, retention, retention_action, columnar_after,
            columnar_sort, columnar_options, run_every, enabled)
        ON CONFLICT (schema_name, table_name) DO UPDATE SET
            parent_oid = EXCLUDED.parent_oid,
            partition_every = EXCLUDED.partition_every,
            timezone = EXCLUDED.timezone,
            create_ahead = EXCLUDED.create_ahead,
            retention = EXCLUDED.retention,
            retention_action = EXCLUDED.retention_action,
            columnar_after = EXCLUDED.columnar_after,
            columnar_sort = EXCLUDED.columnar_sort,
            columnar_options = EXCLUDED.columnar_options,
            run_every = EXCLUDED.run_every,
            enabled = EXCLUDED.enabled,
            updated_at = clock_timestamp();
    END IF;
END;
$$;

