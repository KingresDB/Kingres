-- Event triggers: a rename or a drop of the table updates the policy
------------------------------------------------------------------------

-- A renamed or moved table keeps its policy and its history: the rows follow
-- the OID.  Only the rows of this installation are followed (see "Identity"):
-- the OID in a row that a backup carried means nothing here, and may be the
-- OID of an unrelated table.  A policy is changed only when the table it
-- names is gone, too.
CREATE FUNCTION kingres.timepart__on_ddl_end()
RETURNS event_trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    r record;
BEGIN
    FOR r IN SELECT d.objid FROM pg_event_trigger_ddl_commands() d
              WHERE d.object_type = 'table' AND d.objid IS NOT NULL
    LOOP
        UPDATE kingres.timepart_policy_data p
           SET schema_name = n.nspname, table_name = c.relname,
               updated_at = now()
          FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
         WHERE c.oid = r.objid AND c.relkind = 'p'
           AND p.parent_oid = r.objid
           AND p.stamp = kingres.timepart__stamp()
           AND (p.schema_name, p.table_name) IS DISTINCT FROM (n.nspname, c.relname)
           AND kingres.timepart__oid(p.schema_name, p.table_name) IS NULL
           AND NOT EXISTS (SELECT 1 FROM kingres.timepart_policy_data p2
                            WHERE p2.schema_name = n.nspname
                              AND p2.table_name = c.relname);
        -- the runs of the table carry its name as it is now
        UPDATE kingres.timepart_run_data x
           SET schema_name = n.nspname, table_name = c.relname
          FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
         WHERE c.oid = r.objid AND c.relkind = 'p'
           AND x.table_oid = r.objid
           AND x.stamp = kingres.timepart__stamp()
           AND (x.schema_name, x.table_name) IS DISTINCT FROM (n.nspname, c.relname);
    END LOOP;
END;
$$;

-- A dropped table loses its policy; its history stays, with the owner the
-- table had, and no longer belongs to any table (the OID is forgotten, so that
-- a later table of the same name, or with the same OID, is another table).
CREATE FUNCTION kingres.timepart__on_sql_drop()
RETURNS event_trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    r record;
BEGIN
    FOR r IN SELECT o.objid FROM pg_event_trigger_dropped_objects() o
              WHERE o.object_type = 'table'
    LOOP
        DELETE FROM kingres.timepart_policy_data p
         WHERE p.parent_oid = r.objid
           AND p.stamp = kingres.timepart__stamp()
           AND kingres.timepart__oid(p.schema_name, p.table_name) IS NULL;
        UPDATE kingres.timepart_run_data x SET table_oid = NULL
         WHERE x.table_oid = r.objid AND x.stamp = kingres.timepart__stamp();
    END LOOP;
END;
$$;

CREATE EVENT TRIGGER kingres_timepart_ddl_end ON ddl_command_end
    WHEN TAG IN ('ALTER TABLE')
    EXECUTE FUNCTION kingres.timepart__on_ddl_end();
ALTER EVENT TRIGGER kingres_timepart_ddl_end ENABLE ALWAYS;

CREATE EVENT TRIGGER kingres_timepart_sql_drop ON sql_drop
    EXECUTE FUNCTION kingres.timepart__on_sql_drop();
ALTER EVENT TRIGGER kingres_timepart_sql_drop ENABLE ALWAYS;

