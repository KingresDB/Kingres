-- Install script of the kingres_timepart extension, version 0.1: time
-- partitioning of ordinary (non-distributed) tables.  Creates the partitions
-- of a table partitioned by a time column for a period ahead, drops or
-- detaches partitions older than a retention period, and keeps a policy per
-- table and a history of runs.  The design is section 10 of
-- kingres/docs/design/analytics-phase12-storage.md.
--
