-- The OID of the relation of that name, by a catalog lookup that, unlike
-- to_regclass, does not check the caller's right on the schema: the names come
-- from the policy and history tables, which name tables of other roles.
CREATE FUNCTION kingres.timepart__oid(p_schema name, p_table name)
RETURNS oid
LANGUAGE sql STABLE
SET search_path = pg_catalog, pg_temp
AS $$
    SELECT c.oid FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = p_schema AND c.relname = p_table
$$;

-- The check PostgreSQL makes for ALTER TABLE: the role has the privileges of
-- the owner (it is the owner, a member that inherits, or a superuser).
CREATE FUNCTION kingres.timepart__require_owner(p_who name, p_owner oid,
                                                p_table text)
RETURNS void
LANGUAGE plpgsql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
BEGIN
    IF NOT pg_has_role(p_who, p_owner, 'USAGE') THEN
        RAISE EXCEPTION 'must be owner of table %', p_table
            USING ERRCODE = '42501';
    END IF;
END;
$$;

CREATE FUNCTION kingres.timepart__require_superuser()
RETURNS void
LANGUAGE plpgsql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles r
                   WHERE r.rolname = current_user AND r.rolsuper) THEN
        RAISE EXCEPTION 'permission denied: only a superuser may call this function'
            USING ERRCODE = '42501';
    END IF;
END;
$$;

-- The role that a recorded role is, now: by OID for a row written here, by name
-- for a row from a backup (see "Identity"); null when there is none (the role
-- was dropped, or the backup names a role this cluster does not have).
CREATE FUNCTION kingres.timepart__role_oid(p_stamp uuid, p_oid oid, p_name name)
RETURNS oid
LANGUAGE sql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
    SELECT CASE WHEN p_stamp = kingres.timepart__stamp()
                THEN (SELECT r.oid FROM pg_roles r WHERE r.oid = p_oid)
                ELSE (SELECT r.oid FROM pg_roles r WHERE r.rolname = p_name)
           END
$$;

-- The name of a recorded role, from the catalog (a renamed role shows its new
-- name); the name as recorded when the role is gone.
CREATE FUNCTION kingres.timepart__role_name(p_stamp uuid, p_oid oid, p_name name)
RETURNS name
LANGUAGE sql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
    SELECT coalesce((SELECT r.rolname FROM pg_roles r
                      WHERE r.oid = kingres.timepart__role_oid(p_stamp, p_oid, p_name)),
                    p_name)
$$;

-- The table a run was made for, if it still exists: by OID for a run recorded
-- here (null once the table is dropped, also when the name is used again), by
-- schema, name and owner for a run restored from a backup.
CREATE FUNCTION kingres.timepart__run_table(
    p_stamp uuid, p_table_oid oid, p_schema name, p_table name,
    p_owner_oid oid, p_owner name)
RETURNS oid
LANGUAGE sql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
    SELECT CASE WHEN p_stamp = kingres.timepart__stamp()
                THEN (SELECT c.oid FROM pg_class c
                       WHERE c.oid = p_table_oid AND c.relkind = 'p')
                ELSE (SELECT c.oid FROM pg_class c
                        JOIN pg_namespace n ON n.oid = c.relnamespace
                       WHERE n.nspname = p_schema AND c.relname = p_table
                         AND c.relkind = 'p'
                         AND c.relowner = kingres.timepart__role_oid(p_stamp, p_owner_oid, p_owner))
           END
$$;

-- What the history views show to the calling role: the runs of tables that it
-- owned (has the privileges of the owner of) when the run began, whether the
-- table is still there, was renamed, was dropped, or was dropped and made
-- again by another role; a superuser sees every run.  The role judged is the
-- one recorded in the run, so an owner that was dropped leaves runs that only
-- a superuser sees.  Judges current_user, as the other views do.
CREATE FUNCTION kingres.timepart__run_visible(p_stamp uuid, p_owner_oid oid,
                                              p_owner name)
RETURNS boolean
LANGUAGE sql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
    SELECT coalesce((SELECT r.rolsuper FROM pg_roles r
                      WHERE r.rolname = current_user), false)
           OR coalesce(pg_has_role(
                  current_user,
                  kingres.timepart__role_oid(p_stamp, p_owner_oid, p_owner),
                  'USAGE'), false)
$$;

