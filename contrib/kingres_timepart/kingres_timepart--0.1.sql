CREATE FUNCTION kingres.timepart_plan(rel regclass,
                                      as_of timestamptz DEFAULT now())
RETURNS TABLE (seq integer, kind text, partition_name name,
               range_from timestamptz, range_to timestamptz, reason text)
LANGUAGE plpgsql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_info   record;
    v_pol    kingres.timepart_policy%ROWTYPE;
BEGIN
    -- Reading the bounds of the partitions takes locks: bound the wait, so that
    -- a long transaction on the table cannot hold a monitor up.
    PERFORM pg_catalog.set_config('lock_timeout', kingres.timepart__lock_timeout('create'), true);
    SELECT * INTO v_info FROM kingres.timepart__key_info(rel::oid);
    PERFORM kingres.timepart__require_owner(
        current_user, v_info.r_owner_oid,
        format('%I.%I', v_info.r_schema, v_info.r_table));
    SELECT p.* INTO v_pol FROM kingres.timepart_policy p
     WHERE p.schema_name = v_info.r_schema AND p.table_name = v_info.r_table;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'table %.% has no time partitioning policy',
            quote_ident(v_info.r_schema), quote_ident(v_info.r_table)
            USING ERRCODE = '42704';
    END IF;
    RETURN QUERY
    SELECT pr.seq, pr.kind, pr.part_name, pr.range_from, pr.range_to, pr.reason
      FROM kingres.timepart__plan_rows(
               rel::oid, v_pol.partition_every, v_pol.timezone,
               v_pol.create_ahead, v_pol.retention, v_pol.retention_action,
               v_pol.columnar_after, as_of) pr
     ORDER BY pr.seq;
END;
$$;

