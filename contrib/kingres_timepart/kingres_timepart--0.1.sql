-- Split an interval into the unit and the count the grid understands (10.3):
-- N hours with 24 mod N = 0; N days (7 days is the week, aligned on Monday);
-- N months with 12 mod N = 0; N years.  Anything else, a mixture of units, a
-- zero or a negative value is refused.
CREATE FUNCTION kingres.timepart_interval_parts(p_every interval,
                                                OUT unit text, OUT n integer)
LANGUAGE plpgsql IMMUTABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_m numeric;
    v_d numeric;
    v_t numeric;
BEGIN
    IF p_every IS NULL THEN
        RAISE EXCEPTION 'partition_every must not be null'
            USING ERRCODE = '22004';
    END IF;
    v_m := extract(year FROM p_every) * 12 + extract(month FROM p_every);
    v_d := extract(day FROM p_every);
    v_t := extract(hour FROM p_every) * 3600
         + extract(minute FROM p_every) * 60
         + extract(second FROM p_every);
    IF v_m < 0 OR v_d < 0 OR v_t < 0
       OR (v_m > 0)::int + (v_d > 0)::int + (v_t > 0)::int <> 1 THEN
        RAISE EXCEPTION 'invalid partition_every "%"', p_every
            USING ERRCODE = '22023',
                  HINT = 'Use N hours (24 mod N = 0), N days, 1 week, N months (12 mod N = 0) or N years, in one unit.';
    END IF;
    IF v_t > 0 THEN
        IF v_t % 3600 <> 0 OR 24 % (v_t / 3600) <> 0 THEN
            RAISE EXCEPTION 'invalid partition_every "%"', p_every
                USING ERRCODE = '22023',
                      HINT = 'Hours must divide a day: 1, 2, 3, 4, 6, 8, 12 or 24.';
        END IF;
        unit := 'hour';
        n := (v_t / 3600)::int;
    ELSIF v_d > 0 THEN
        IF v_d > 3660 THEN
            RAISE EXCEPTION 'invalid partition_every "%"', p_every
                USING ERRCODE = '22023', HINT = 'At most 3660 days.';
        END IF;
        IF v_d = 7 THEN
            unit := 'week';
            n := 1;
        ELSE
            unit := 'day';
            n := v_d::int;
        END IF;
    ELSIF v_m % 12 = 0 THEN
        IF v_m / 12 > 1000 THEN
            RAISE EXCEPTION 'invalid partition_every "%"', p_every
                USING ERRCODE = '22023', HINT = 'At most 1000 years.';
        END IF;
        unit := 'year';
        n := (v_m / 12)::int;
    ELSIF 12 % v_m = 0 THEN
        unit := 'month';
        n := v_m::int;
    ELSE
        RAISE EXCEPTION 'invalid partition_every "%"', p_every
            USING ERRCODE = '22023',
                  HINT = 'Months must divide a year: 1, 2, 3, 4, 6 or 12.';
    END IF;
END;
$$;

-- The time zone must be a name from pg_timezone_names: an offset or an
-- abbreviation has no daylight-saving rules and would make the bounds depend
-- on a setting nobody can see.
CREATE FUNCTION kingres.timepart__check_tz(p_tz text)
RETURNS void
LANGUAGE plpgsql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
BEGIN
    IF p_tz IS NULL OR NOT EXISTS (SELECT 1 FROM pg_timezone_names n
                                   WHERE n.name = p_tz) THEN
        RAISE EXCEPTION 'unknown time zone "%"', p_tz
            USING ERRCODE = '22023',
                  HINT = 'Use a name from pg_timezone_names, for example UTC or Europe/Berlin.';
    END IF;
END;
$$;

-- The start of the cell number k of the grid.  Hours are absolute lengths
-- counted from 2000-01-01 00:00 of the zone, so a daylight-saving change
-- never makes a cell shorter or longer than N hours.  Days, weeks, months
-- and years follow the calendar of the zone: the cell starts at local
-- midnight, so a day of a change is 23 or 25 hours long.  Weeks start on
-- Monday; N days count from 2000-01-01.  Every cell ends where the next one
-- starts, because both come from this one function.
CREATE FUNCTION kingres.timepart_cell_start(p_every interval, p_tz text,
                                            p_k bigint)
RETURNS timestamptz
LANGUAGE plpgsql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_unit text;
    v_n    integer;
BEGIN
    SELECT u.unit, u.n INTO v_unit, v_n
      FROM kingres.timepart_interval_parts(p_every) u;
    IF v_unit = 'hour' THEN
        RETURN (timestamp '2000-01-01 00:00:00' AT TIME ZONE p_tz)
               + (p_k * v_n)::float8 * interval '1 hour';
    ELSIF v_unit = 'day' THEN
        RETURN ((date '2000-01-01' + (p_k * v_n)::int)::timestamp)
               AT TIME ZONE p_tz;
    ELSIF v_unit = 'week' THEN
        RETURN ((date '2000-01-03' + (p_k * 7)::int)::timestamp)
               AT TIME ZONE p_tz;
    ELSIF v_unit = 'month' THEN
        RETURN (timestamp '2000-01-01'
                + (p_k * v_n)::float8 * interval '1 month')
               AT TIME ZONE p_tz;
    ELSE
        RETURN (timestamp '2000-01-01'
                + (p_k * v_n)::float8 * interval '1 year')
               AT TIME ZONE p_tz;
    END IF;
END;
$$;

-- The number of the cell that contains the instant p_t.
CREATE FUNCTION kingres.timepart_cell_of(p_every interval, p_tz text,
                                         p_t timestamptz)
RETURNS bigint
LANGUAGE plpgsql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_unit  text;
    v_n     integer;
    v_local timestamp;
    v_k     bigint;
    v_mi    integer;
BEGIN
    IF p_t IS NULL OR p_t IN ('infinity', '-infinity') THEN
        RAISE EXCEPTION 'time value must be finite'
            USING ERRCODE = '22008';
    END IF;
    SELECT u.unit, u.n INTO v_unit, v_n
      FROM kingres.timepart_interval_parts(p_every) u;
    v_local := p_t AT TIME ZONE p_tz;
    IF v_unit = 'hour' THEN
        v_k := floor((extract(epoch FROM p_t)
                      - extract(epoch FROM (timestamp '2000-01-01 00:00:00'
                                            AT TIME ZONE p_tz)))
                     / (v_n * 3600))::bigint;
    ELSIF v_unit = 'day' THEN
        v_k := floor(((v_local::date - date '2000-01-01')::numeric) / v_n)::bigint;
    ELSIF v_unit = 'week' THEN
        v_k := floor(((v_local::date - date '2000-01-03')::numeric) / 7)::bigint;
    ELSIF v_unit = 'month' THEN
        v_mi := (extract(year FROM v_local)::int - 2000) * 12
                + extract(month FROM v_local)::int - 1;
        v_k := floor(v_mi::numeric / v_n)::bigint;
    ELSE
        v_k := floor((extract(year FROM v_local)::int - 2000)::numeric / v_n)::bigint;
    END IF;
    -- A zone whose local midnight does not exist on a day of change can put
    -- the start of a cell a little after the local date says; settle it.
    WHILE kingres.timepart_cell_start(p_every, p_tz, v_k) > p_t LOOP
        v_k := v_k - 1;
    END LOOP;
    WHILE kingres.timepart_cell_start(p_every, p_tz, v_k + 1) <= p_t LOOP
        v_k := v_k + 1;
    END LOOP;
    RETURN v_k;
END;
$$;

-- Is p_t the start of a cell?
CREATE FUNCTION kingres.timepart__on_grid(p_every interval, p_tz text,
                                          p_t timestamptz)
RETURNS boolean
LANGUAGE plpgsql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
BEGIN
    IF p_t IN ('infinity', '-infinity') THEN
        RETURN false;
    END IF;
    RETURN kingres.timepart_cell_start(
               p_every, p_tz,
               kingres.timepart_cell_of(p_every, p_tz, p_t)) = p_t;
END;
$$;

-- Local calendar arithmetic: p_t plus (p_sign = 1) or minus (p_sign = -1) an
-- interval, counted in the wall clock of the zone.
CREATE FUNCTION kingres.timepart__add(p_t timestamptz, p_i interval,
                                      p_tz text, p_sign integer)
RETURNS timestamptz
LANGUAGE sql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
    SELECT ((p_t AT TIME ZONE p_tz) + p_i * p_sign) AT TIME ZONE p_tz
$$;

-- The instant that stands for p_t on the grid of a key.  A timestamptz key
-- is an instant and is used as it is.  A timestamp or date key holds wall
-- clock values: p_t is read in the policy's zone and the wall clock value is
-- then treated as a UTC instant, so the grid has no daylight-saving change.
CREATE FUNCTION kingres.timepart__eff(p_t timestamptz, p_keytype text,
                                      p_tz text)
RETURNS timestamptz
LANGUAGE sql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
    SELECT CASE WHEN p_keytype = 'timestamptz' THEN p_t
                ELSE (p_t AT TIME ZONE p_tz) AT TIME ZONE 'UTC' END
$$;

-- The text of a partition bound for the key type: an ISO literal that does
-- not depend on DateStyle or TimeZone.
CREATE FUNCTION kingres.timepart__bound_literal(p_keytype text,
                                                p_b timestamptz)
RETURNS text
LANGUAGE sql IMMUTABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
    SELECT CASE p_keytype
        WHEN 'timestamptz' THEN
            to_char(p_b AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"')
        WHEN 'timestamp' THEN
            to_char(p_b AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS.US')
        ELSE
            to_char(p_b AT TIME ZONE 'UTC', 'YYYY-MM-DD')
    END
$$;

-- The generated name of a partition: <table>_p<suffix> with the suffix
-- YYYYMMDDHH24 (hours, in UTC), YYYYMMDD (days and weeks, the first day, in
-- the zone), YYYYMM (months) or YYYY (years).  The table's name is cut,
-- character by character, until the whole name fits in 63 bytes.
CREATE FUNCTION kingres.timepart_part_name(p_base name, p_every interval,
                                           p_tz text, p_start timestamptz)
RETURNS name
LANGUAGE plpgsql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_unit   text;
    v_n      integer;
    v_tail   text;
    v_base   text := p_base::text;
BEGIN
    SELECT u.unit, u.n INTO v_unit, v_n
      FROM kingres.timepart_interval_parts(p_every) u;
    v_tail := '_p' || CASE v_unit
        WHEN 'hour'  THEN to_char(p_start AT TIME ZONE 'UTC', 'YYYYMMDDHH24')
        WHEN 'day'   THEN to_char(p_start AT TIME ZONE p_tz, 'YYYYMMDD')
        WHEN 'week'  THEN to_char(p_start AT TIME ZONE p_tz, 'YYYYMMDD')
        WHEN 'month' THEN to_char(p_start AT TIME ZONE p_tz, 'YYYYMM')
        ELSE              to_char(p_start AT TIME ZONE p_tz, 'YYYY')
    END;
    WHILE octet_length(v_base) + octet_length(v_tail) > 63 LOOP
        v_base := left(v_base, char_length(v_base) - 1);
    END LOOP;
    RETURN (v_base || v_tail)::name;
END;
$$;

-- An integer setting of the extension with a default and a range.  The
-- values are plain integers so that a test or an operator can bound every
-- wait; a value out of range is an error, not a silent clamp.
CREATE FUNCTION kingres.timepart__setting_int(p_name text, p_default integer,
                                              p_min integer, p_max integer)
RETURNS integer
LANGUAGE plpgsql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_text text := nullif(pg_catalog.current_setting(p_name, true), '');
    v_val  integer;
BEGIN
    IF v_text IS NULL THEN
        RETURN p_default;
    END IF;
    BEGIN
        v_val := v_text::integer;
    EXCEPTION WHEN invalid_text_representation OR numeric_value_out_of_range THEN
        RAISE EXCEPTION 'invalid value "%" for "%"', v_text, p_name
            USING ERRCODE = '22023', HINT = 'The value is an integer.';
    END;
    IF v_val < p_min OR v_val > p_max THEN
        RAISE EXCEPTION 'value % of "%" is out of range', v_val, p_name
            USING ERRCODE = '22023',
                  HINT = format('The range is %s to %s.', p_min, p_max);
    END IF;
    RETURN v_val;
END;
$$;

-- The lock_timeout, as the text of a setting, from the settings
-- kingres_timepart.create_lock_timeout_ms (default 5000) or
-- kingres_timepart.retire_lock_timeout_ms (default 2000).  The caller applies
-- it with set_config('lock_timeout', ..., true) itself: a function that has a
-- SET clause gives back every setting it changed when it returns, so the
-- setting has to be made by a function that runs the statements.  The callers
-- have a SET clause too, so lock_timeout is back to what it was when they
-- return.
CREATE FUNCTION kingres.timepart__lock_timeout(p_what text)
RETURNS text
LANGUAGE plpgsql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
BEGIN
    IF p_what = 'create' THEN
        RETURN kingres.timepart__setting_int(
                   'kingres_timepart.create_lock_timeout_ms', 5000, 1, 60000)::text || 'ms';
    END IF;
    RETURN kingres.timepart__setting_int(
               'kingres_timepart.retire_lock_timeout_ms', 2000, 1, 60000)::text || 'ms';
END;
$$;

