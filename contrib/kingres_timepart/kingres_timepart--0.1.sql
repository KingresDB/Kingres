-- Runs of a table are kept for 90 days (counted from p_as_of) and at most
-- 1000 of them.  Returns the number deleted.
CREATE FUNCTION kingres.timepart_prune_runs(
    p_schema name, p_table name, p_as_of timestamptz DEFAULT now())
RETURNS bigint
LANGUAGE plpgsql
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_n bigint;
BEGIN
    PERFORM kingres.timepart__require_superuser();
    WITH doomed AS (
        SELECT r.run_id
          FROM kingres.timepart_run_data r
         WHERE r.schema_name = p_schema AND r.table_name = p_table
           AND r.state <> 'running'
           AND (r.as_of < p_as_of - interval '90 days'
                OR r.run_id NOT IN (
                    SELECT r2.run_id FROM kingres.timepart_run_data r2
                     WHERE r2.schema_name = p_schema AND r2.table_name = p_table
                     ORDER BY r2.run_id DESC LIMIT 1000))
    ), d AS (
        DELETE FROM kingres.timepart_run_data r USING doomed
         WHERE r.run_id = doomed.run_id RETURNING 1
    )
    SELECT count(*) INTO v_n FROM d;
    RETURN v_n;
END;
$$;

-- Give the rows that a backup carried here the identity of this installation
-- (see "Identity"): the roles by the OIDs of the roles of those names, a
-- policy's table by the table of its name, a run's table by the table of its
-- name that the recorded owner owns, and the stamp of this installation.  A
-- row whose owner role does not exist here is left as it is (a superuser
-- sees it; it is adopted when a role of that name is made).  Returns the
-- number of rows changed.  Called by every timepart_begin_run; superuser only.
CREATE FUNCTION kingres.timepart_adopt()
RETURNS bigint
LANGUAGE plpgsql
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_n bigint := 0;
    v_k bigint;
BEGIN
    PERFORM kingres.timepart__require_superuser();
    UPDATE kingres.timepart_policy_data p
       SET stamp = kingres.timepart__stamp(),
           table_owner_oid = o.oid,
           created_by_oid = (SELECT c.oid FROM pg_roles c WHERE c.rolname = p.created_by),
           parent_oid = coalesce(
               (SELECT t.oid FROM pg_class t JOIN pg_namespace n ON n.oid = t.relnamespace
                 WHERE n.nspname = p.schema_name AND t.relname = p.table_name
                   AND t.relkind = 'p'), p.parent_oid)
      FROM pg_roles o
     WHERE p.stamp <> kingres.timepart__stamp() AND o.rolname = p.table_owner;
    GET DIAGNOSTICS v_k = ROW_COUNT;
    v_n := v_n + v_k;
    UPDATE kingres.timepart_run_data r
       SET stamp = kingres.timepart__stamp(),
           table_owner_oid = o.oid,
           started_by_oid = (SELECT c.oid FROM pg_roles c WHERE c.rolname = r.started_by),
           table_oid = (SELECT t.oid FROM pg_class t JOIN pg_namespace n ON n.oid = t.relnamespace
                         WHERE n.nspname = r.schema_name AND t.relname = r.table_name
                           AND t.relkind = 'p' AND t.relowner = o.oid)
      FROM pg_roles o
     WHERE r.stamp <> kingres.timepart__stamp() AND o.rolname = r.table_owner;
    GET DIAGNOSTICS v_k = ROW_COUNT;
    RETURN v_n + v_k;
END;
$$;

-- Record a run and claim the table (10.7).  The claim is a row lock on the
-- table's row of kingres.timepart_lock, which only the extension owner can
-- touch (FOR UPDATE NOWAIT, held to the end of this transaction, so it
-- serialises concurrent begins), and the run row itself: it records the
-- backend that made it.  A run whose row says "running" and whose backend
-- (pid and start time) is still alive in pg_stat_activity is live, and a new
-- begin raises 55P03; when the backend is gone the run is marked failed with
-- error 'interrupted'.  A begin in the session that made the live run takes
-- it over.  A run that cannot start (the owner changed, the table is no
-- longer a suitable table) is recorded as failed at once and its id returned.
CREATE FUNCTION kingres.timepart_begin_run(
    rel regclass, as_of timestamptz DEFAULT now(),
    trigger text DEFAULT 'sql')
RETURNS bigint
LANGUAGE plpgsql
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_info   record;
    v_schema name;
    v_table  name;
    v_pol    kingres.timepart_policy_data%ROWTYPE;
    r        record;
    v_run    bigint;
    v_error  text;
    v_owner_oid oid;
BEGIN
    PERFORM kingres.timepart__require_superuser();
    -- Rows that a backup carried here get the OIDs of this cluster first.
    PERFORM kingres.timepart_adopt();
    -- Reading the partitions of the table takes locks: bound the wait.
    PERFORM pg_catalog.set_config('lock_timeout', kingres.timepart__lock_timeout('create'), true);
    IF as_of IS NULL OR as_of IN ('infinity', '-infinity') THEN
        RAISE EXCEPTION 'as_of must be a finite time' USING ERRCODE = '22008';
    END IF;
    IF trigger IS NULL OR trigger NOT IN ('schedule', 'manual', 'sql') THEN
        RAISE EXCEPTION 'trigger must be schedule, manual or sql'
            USING ERRCODE = '22023';
    END IF;
    SELECT n.nspname, cl.relname, cl.relowner INTO v_schema, v_table, v_owner_oid
      FROM pg_class cl JOIN pg_namespace n ON n.oid = cl.relnamespace
     WHERE cl.oid = rel::oid;
    SELECT p.* INTO v_pol FROM kingres.timepart_policy_data p
     WHERE p.schema_name = v_schema AND p.table_name = v_table;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'table %.% has no time partitioning policy',
            quote_ident(v_schema), quote_ident(v_table)
            USING ERRCODE = '42704';
    END IF;

    PERFORM kingres.timepart__claim(v_schema, v_table, 'another run of table %.% is in progress');
    FOR r IN SELECT x.run_id, x.backend_pid
               FROM kingres.timepart_run_data x
              WHERE x.schema_name = v_schema AND x.table_name = v_table
                AND x.state = 'running'
                AND x.backend_pid IS DISTINCT FROM pg_backend_pid()
                AND EXISTS (SELECT 1 FROM pg_stat_activity a
                             WHERE a.pid = x.backend_pid
                               AND a.backend_start = x.backend_start)
    LOOP
        RAISE EXCEPTION 'another run of table %.% is in progress (backend %)',
            quote_ident(v_schema), quote_ident(v_table), r.backend_pid
            USING ERRCODE = '55P03';
    END LOOP;
    UPDATE kingres.timepart_run_data x
       SET state = 'failed', finished_at = now(), error = 'interrupted'
     WHERE x.schema_name = v_schema AND x.table_name = v_table
       AND x.state = 'running';

    -- The policy is bound to the table by name; refresh the OID hint.
    IF v_pol.parent_oid <> rel::oid THEN
        UPDATE kingres.timepart_policy_data p SET parent_oid = rel::oid
         WHERE p.schema_name = v_pol.schema_name AND p.table_name = v_pol.table_name;
    END IF;

    v_error := NULL;
    BEGIN
        SELECT * INTO v_info FROM kingres.timepart__key_info(rel::oid);
        -- the owner is the role of the policy, by OID: a role that was renamed
        -- is the same owner
        IF v_info.r_owner_oid IS DISTINCT FROM v_pol.table_owner_oid THEN
            RAISE EXCEPTION 'owner_changed: the owner of %.% is now "%", the policy was set for "%"',
                quote_ident(v_info.r_schema), quote_ident(v_info.r_table),
                v_info.r_owner,
                kingres.timepart__role_name(v_pol.stamp, v_pol.table_owner_oid,
                                            v_pol.table_owner)
                USING ERRCODE = '42501';
        END IF;
    EXCEPTION WHEN OTHERS THEN
        v_error := SQLSTATE || ': ' || SQLERRM;
    END;

    -- The run belongs to this table and to the owner it has now, whoever the
    -- policy was set for (a run that fails on owner_changed is the new
    -- owner's to read).
    INSERT INTO kingres.timepart_run_data (schema_name, table_name, as_of, trigger,
                                      state, started_by, started_by_oid,
                                      finished_at, error,
                                      backend_pid, backend_start,
                                      table_oid, table_owner_oid, table_owner)
    VALUES (v_pol.schema_name, v_pol.table_name, as_of, trigger,
            CASE WHEN v_error IS NULL THEN 'running' ELSE 'failed' END,
            session_user,
            (SELECT sr.oid FROM pg_roles sr WHERE sr.rolname = session_user),
            CASE WHEN v_error IS NULL THEN NULL ELSE now() END, v_error,
            pg_backend_pid(),
            (SELECT a.backend_start FROM pg_stat_activity a
              WHERE a.pid = pg_backend_pid()),
            rel::oid, v_owner_oid, pg_get_userbyid(v_owner_oid))
    RETURNING run_id INTO v_run;
    RETURN v_run;
END;
$$;

-- Lock the row of the table in kingres.timepart_lock, making it if needed,
-- without waiting.  The lock lasts to the end of the transaction.
CREATE FUNCTION kingres.timepart__claim(p_schema name, p_table name,
                                        p_message text)
RETURNS void
LANGUAGE plpgsql
SET search_path = pg_catalog, kingres, pg_temp
AS $$
BEGIN
    INSERT INTO kingres.timepart_lock (schema_name, table_name)
    VALUES (p_schema, p_table) ON CONFLICT DO NOTHING;
    PERFORM 1 FROM kingres.timepart_lock l
     WHERE l.schema_name = p_schema AND l.table_name = p_table
       FOR UPDATE NOWAIT;
EXCEPTION WHEN lock_not_available THEN
    RAISE EXCEPTION '%', format(p_message, quote_ident(p_schema),
                                quote_ident(p_table))
        USING ERRCODE = '55P03';
END;
$$;

-- Execute statements as the owner of a table, in a context the owner's own
-- code cannot leave.  The statements are DDL on the owner's table, and DDL
-- makes PostgreSQL run code that the owner wrote: an index expression is
-- evaluated while a partition is attached, a default or a check expression
-- when a table is made.  Run with SET ROLE in the session of a superuser
-- (which the maintenance is), that code runs with the owner's rights but can
-- say RESET ROLE, or set_config('role', 'none', false) from a function it
-- declares IMMUTABLE, and has the superuser's rights from then on (the test
-- timepart_privilege shows it).  PostgreSQL itself runs such code of the
-- table owner (REINDEX, CLUSTER, VACUUM, REFRESH MATERIALIZED VIEW) under
-- SetUserIdAndSecContext, which no SQL can reach, so SET ROLE and SET SESSION
-- AUTHORIZATION are refused inside.  The one thing SQL can do is the
-- security-definer frame: a function that is SECURITY DEFINER runs with the
-- user id of its owner and forbids both statements ("cannot set parameter
-- "role" within security-definer function").  So a function that is owned by
-- the table owner is made in the temporary schema of this session, called, and
-- dropped, in the transaction of the action; no other session sees it (it is
-- not committed), and no object of the extension is owned by the owner.  Its
-- body is a loop over the statements.  If the owner no longer exists, or the
-- statements fail, the error is raised to the caller, which rolls the
-- subtransaction back and takes the function with it.
CREATE FUNCTION kingres.timepart__exec_as(p_owner oid, p_stmts text[])
RETURNS void
LANGUAGE plpgsql
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_name name := pg_get_userbyid(p_owner);
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles r WHERE r.oid = p_owner) THEN
        RAISE EXCEPTION 'role with OID % does not exist', p_owner
            USING ERRCODE = '42704';
    END IF;
    EXECUTE $def$
        CREATE FUNCTION pg_temp.timepart_exec(p_stmts pg_catalog.text[])
        RETURNS pg_catalog.void LANGUAGE plpgsql SECURITY DEFINER
        SET search_path = pg_catalog, pg_temp
        AS 'DECLARE s pg_catalog.text; BEGIN FOREACH s IN ARRAY p_stmts LOOP EXECUTE s; END LOOP; END'
    $def$;
    EXECUTE format('ALTER FUNCTION pg_temp.timepart_exec(pg_catalog.text[]) OWNER TO %I', v_name);
    PERFORM pg_temp.timepart_exec(p_stmts);
    EXECUTE 'DROP FUNCTION pg_temp.timepart_exec(pg_catalog.text[])';
END;
$$;

-- Execute the next outstanding action of one phase and record it; return
-- false when the phase has nothing left.  A driver that wants a time limit for
-- an action issues each call as a statement of its own after SET
-- statement_timeout (see timepart_action_timeout): when the limit strikes while
-- the action runs, the action is recorded as failed with detail
-- statement_timeout and the run goes on.  (A timer cannot be started from
-- inside a running statement, so timepart_run and timepart_run_phase, which
-- are one statement, can only be bounded as a whole.)  It re-plans from the catalog at
-- the run's as_of every time, so it is idempotent: after an interruption the
-- same call does what is left.  An action that failed or was skipped in this
-- run is not tried again in it.  Each call is one transaction of the caller
-- (timepart_run_phase commits after each).  The DDL runs as the owner of the
-- table (timepart__exec_as), and lock waits are bounded by the settings
-- kingres_timepart.create_lock_timeout_ms / retire_lock_timeout_ms with up to
-- kingres_timepart.lock_retries attempts separated by a random sleep between
-- retry_sleep_min_ms and retry_sleep_max_ms.
CREATE FUNCTION kingres.timepart_run_action(p_run bigint, p_phase text)
RETURNS boolean
LANGUAGE plpgsql
SET search_path = pg_catalog, kingres, pg_temp
SET DateStyle = 'ISO, MDY'
AS $$
DECLARE
    v_run     kingres.timepart_run_data%ROWTYPE;
    v_pol     kingres.timepart_policy_data%ROWTYPE;
    v_info    record;
    v_parent  oid;
    v_row     record;
    v_kinds   text[];
    v_seq     integer;
    v_state   text;
    v_detail  text;
    v_bytes   bigint;
    v_retries integer;
    v_sleep_min integer;
    v_sleep_max integer;
    v_attempt integer;
    v_ncols   integer;
    v_stmts   text[];
    v_have    boolean;
BEGIN
    PERFORM kingres.timepart__require_superuser();
    IF p_phase IS NULL OR p_phase NOT IN ('create', 'convert', 'retire') THEN
        RAISE EXCEPTION 'phase must be create, convert or retire'
            USING ERRCODE = '22023';
    END IF;
    SELECT r.* INTO v_run FROM kingres.timepart_run_data r
     WHERE r.run_id = p_run FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'run % does not exist', p_run USING ERRCODE = '42704';
    END IF;
    IF v_run.state <> 'running' THEN
        RETURN false;
    END IF;
    -- One step per table at a time, whatever session runs it: a scheduler may
    -- use another connection for each step.  Steps re-plan from the catalog, so
    -- steps of two runs that follow each other are safe; they must not overlap.
    PERFORM kingres.timepart__claim(v_run.schema_name, v_run.table_name,
                                    'another step of a run of table %.% is in progress');
    v_retries := kingres.timepart__setting_int(
                     'kingres_timepart.lock_retries', 5, 1, 20);
    v_sleep_min := kingres.timepart__setting_int(
                     'kingres_timepart.retry_sleep_min_ms', 200, 0, 60000);
    v_sleep_max := kingres.timepart__setting_int(
                     'kingres_timepart.retry_sleep_max_ms', 2000, 0, 60000);
    IF v_sleep_max < v_sleep_min THEN
        v_sleep_max := v_sleep_min;
    END IF;

    BEGIN
        -- Reading the bounds of the partitions takes a lock on them: the wait is
        -- bounded from the first statement on.
        PERFORM pg_catalog.set_config('lock_timeout', kingres.timepart__lock_timeout(
            CASE WHEN p_phase = 'retire' THEN 'retire' ELSE 'create' END), true);
        v_parent := kingres.timepart__oid(v_run.schema_name, v_run.table_name)::oid;
        IF v_parent IS NULL THEN
            RAISE EXCEPTION 'table %.% does not exist',
                quote_ident(v_run.schema_name), quote_ident(v_run.table_name)
                USING ERRCODE = '42P01';
        END IF;
        SELECT p.* INTO v_pol FROM kingres.timepart_policy_data p
         WHERE p.schema_name = v_run.schema_name
           AND p.table_name = v_run.table_name;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'table %.% has no time partitioning policy',
                quote_ident(v_run.schema_name), quote_ident(v_run.table_name)
                USING ERRCODE = '42704';
        END IF;
        SELECT * INTO v_info FROM kingres.timepart__key_info(v_parent);
        IF v_info.r_owner_oid IS DISTINCT FROM v_pol.table_owner_oid THEN
            RAISE EXCEPTION 'owner_changed: the owner of %.% is now "%", the policy was set for "%"',
                quote_ident(v_run.schema_name), quote_ident(v_run.table_name),
                v_info.r_owner,
                kingres.timepart__role_name(v_pol.stamp, v_pol.table_owner_oid,
                                            v_pol.table_owner)
                USING ERRCODE = '42501';
        END IF;
        IF v_pol.parent_oid <> v_parent THEN
            UPDATE kingres.timepart_policy_data p SET parent_oid = v_parent
             WHERE p.schema_name = v_pol.schema_name
               AND p.table_name = v_pol.table_name;
        END IF;

        SELECT coalesce(max(a.seq), 0) + 1 INTO v_seq
          FROM kingres.timepart_run_action_data a WHERE a.run_id = p_run;

        -- The conversion needs kingres_columnar, which this version cannot
        -- use: say so once per run and go on.
        IF p_phase = 'convert' THEN
            SELECT count(*) INTO v_ncols
              FROM kingres.timepart__plan_rows(
                       v_parent, v_pol.partition_every, v_pol.timezone,
                       v_pol.create_ahead, v_pol.retention,
                       v_pol.retention_action, v_pol.columnar_after,
                       v_run.as_of) pr
             WHERE pr.kind = 'convert';
            SELECT EXISTS (SELECT 1 FROM kingres.timepart_run_action_data a
                            WHERE a.run_id = p_run AND a.kind = 'convert')
              INTO v_have;
            IF v_ncols = 0 OR v_have THEN
                RETURN false;
            END IF;
            INSERT INTO kingres.timepart_run_action_data (
                run_id, seq, kind, partition_schema, partition_name, state,
                detail, finished_at)
            VALUES (p_run, v_seq, 'convert', v_run.schema_name,
                    v_run.table_name, 'skipped',
                    CASE WHEN EXISTS (SELECT 1 FROM pg_extension e
                                       WHERE e.extname = 'kingres_columnar')
                         THEN format('conversion is not implemented in kingres_timepart 0.1; %s partition(s) older than columnar_after were not converted', v_ncols)
                         ELSE format('conversion needs kingres_columnar, which is not installed; %s partition(s) older than columnar_after were not converted', v_ncols)
                    END, now());
            RETURN true;
        END IF;

        v_kinds := CASE p_phase WHEN 'create' THEN ARRAY['misaligned', 'create']
                                ELSE ARRAY['drop', 'detach'] END;
        SELECT pr.* INTO v_row
          FROM kingres.timepart__plan_rows(
                   v_parent, v_pol.partition_every, v_pol.timezone,
                   v_pol.create_ahead, v_pol.retention, v_pol.retention_action,
                   v_pol.columnar_after, v_run.as_of) pr
         WHERE pr.kind = ANY (v_kinds)
           AND NOT EXISTS (SELECT 1 FROM kingres.timepart_run_action_data a
                            WHERE a.run_id = p_run AND a.kind = pr.kind
                              AND a.partition_schema = pr.part_schema
                              AND a.partition_name = pr.part_name)
         ORDER BY pr.seq LIMIT 1;
        IF NOT FOUND THEN
            RETURN false;
        END IF;

        IF v_row.kind = 'misaligned' THEN
            INSERT INTO kingres.timepart_run_action_data (
                run_id, seq, kind, partition_schema, partition_name,
                range_from, range_to, state, detail, finished_at)
            VALUES (p_run, v_seq, 'misaligned', v_row.part_schema,
                    v_row.part_name, v_row.range_from, v_row.range_to,
                    'skipped', v_row.reason || '; left alone', now());
            RETURN true;
        END IF;

        v_bytes := CASE WHEN v_row.part_oid IS NULL THEN NULL
                        ELSE pg_total_relation_size(v_row.part_oid) END;
        v_state := 'failed';
        FOR v_attempt IN 1..v_retries LOOP
            BEGIN
                -- The statements and the lock timeout are prepared as the
                -- extension owner; only the DDL runs as the table's owner.
                IF v_row.kind = 'create' THEN
                    PERFORM pg_catalog.set_config('lock_timeout', kingres.timepart__lock_timeout('create'), true);
                    v_stmts := kingres.timepart__create_stmts(
                        v_parent, v_row.part_schema, v_row.part_name,
                        kingres.timepart__bound_literal(v_info.r_keytype, v_row.range_from),
                        kingres.timepart__bound_literal(v_info.r_keytype, v_row.range_to),
                        (SELECT a.amname FROM pg_am a WHERE a.oid = v_info.r_am));
                ELSE
                    PERFORM pg_catalog.set_config('lock_timeout', kingres.timepart__lock_timeout('retire'), true);
                    v_stmts := kingres.timepart__retire_stmts(
                        v_parent, v_row.part_oid, v_row.kind = 'detach');
                END IF;
                PERFORM kingres.timepart__exec_as(v_info.r_owner_oid, v_stmts);
                v_state := 'done';
                v_detail := NULL;
                EXIT;
            EXCEPTION
                WHEN lock_not_available THEN
                    v_state := 'failed';
                    v_detail := 'lock_timeout: ' || SQLERRM
                                || format(' (attempt %s of %s)', v_attempt, v_retries);
                WHEN query_canceled THEN
                    -- The statement_timeout of the driver's statement, or a
                    -- cancel by an operator: only the first is an action's
                    -- failure.
                    IF NOT kingres.timepart__timed_out() THEN
                        RAISE;
                    END IF;
                    v_state := 'failed';
                    v_detail := 'statement_timeout: ' || SQLERRM;
                    EXIT;
                WHEN OTHERS THEN
                    v_state := 'failed';
                    v_detail := SQLSTATE || ': ' || SQLERRM;
                    EXIT;
            END;
            IF v_attempt < v_retries THEN
                PERFORM pg_sleep((v_sleep_min + random() * (v_sleep_max - v_sleep_min)) / 1000.0);
            END IF;
        END LOOP;

        INSERT INTO kingres.timepart_run_action_data (
            run_id, seq, kind, partition_schema, partition_name, range_from,
            range_to, state, detail, bytes_before, finished_at)
        VALUES (p_run, v_seq, v_row.kind, v_row.part_schema, v_row.part_name,
                v_row.range_from, v_row.range_to, v_state, v_detail,
                CASE WHEN v_row.kind IN ('drop', 'detach') THEN v_bytes END,
                now());
        RETURN true;
    EXCEPTION WHEN OTHERS THEN
        -- The run itself failed (not one action): record it.
        UPDATE kingres.timepart_run_data r
           SET state = 'failed', finished_at = now(),
               error = SQLSTATE || ': ' || SQLERRM
         WHERE r.run_id = p_run;
        RETURN false;
    END;
END;
$$;

-- Run one phase of a run: create, convert or retire.  One transaction per
-- action; it cannot run inside a transaction block.  Nothing here may be
-- redirected by the caller's search_path: the first statement, and the first
-- after every COMMIT, sets the path of the transaction (a procedure with a SET
-- clause cannot COMMIT), and every function called is schema-qualified.
CREATE PROCEDURE kingres.timepart_run_phase(run_id bigint, phase text)
LANGUAGE plpgsql
AS $$
DECLARE
    v_more boolean;
BEGIN
    PERFORM pg_catalog.set_config('search_path', 'pg_catalog, pg_temp', true);
    LOOP
        v_more := kingres.timepart_run_action(run_id, phase);
        COMMIT;
        PERFORM pg_catalog.set_config('search_path', 'pg_catalog, pg_temp', true);
        EXIT WHEN NOT v_more;
    END LOOP;
END;
$$;

-- Close a run: the final state, the next run time and the pruning of old runs.  The state is "failed" when the
-- run itself failed, "partial" when an action failed, otherwise "done"
-- (skipped actions are not failures).  next_run_at is as_of + run_every, or
-- as_of + least(run_every, 5 minutes) when an action failed on a lock
-- timeout.
CREATE FUNCTION kingres.timepart_finish_run(run_id bigint)
RETURNS void
LANGUAGE plpgsql
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_run     kingres.timepart_run_data%ROWTYPE;
    v_nfailed integer;
    v_locked  boolean;
    v_state   text;
BEGIN
    PERFORM kingres.timepart__require_superuser();
    PERFORM pg_catalog.set_config('lock_timeout', kingres.timepart__lock_timeout('create'), true);
    SELECT r.* INTO v_run FROM kingres.timepart_run_data r
     WHERE r.run_id = timepart_finish_run.run_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'run % does not exist', run_id USING ERRCODE = '42704';
    END IF;
    SELECT count(*) FILTER (WHERE a.state = 'failed'),
           coalesce(bool_or(a.state = 'failed' AND a.detail LIKE 'lock_timeout%'), false)
      INTO v_nfailed, v_locked
      FROM kingres.timepart_run_action_data a
     WHERE a.run_id = timepart_finish_run.run_id;
    -- A run that could not even read the partitions because of a lock (55P03)
    -- is retried soon, like an action that timed out.
    v_locked := v_locked OR coalesce(v_run.error LIKE '55P03:%', false);
    v_state := CASE WHEN v_run.state = 'failed' THEN 'failed'
                    WHEN v_nfailed > 0 THEN 'partial'
                    ELSE 'done' END;
    UPDATE kingres.timepart_run_data r
       SET state = v_state, finished_at = coalesce(r.finished_at, now())
     WHERE r.run_id = timepart_finish_run.run_id;
    -- The owner of the table can hold a lock on its policy row: then the
    -- policy stays due, and the run is closed all the same.
    BEGIN
        UPDATE kingres.timepart_policy_data p
           SET next_run_at = kingres.timepart__add(
                   v_run.as_of,
                   CASE WHEN v_locked THEN least(p.run_every, interval '5 minutes')
                        ELSE p.run_every END,
                   'UTC', 1)
         WHERE p.schema_name = v_run.schema_name AND p.table_name = v_run.table_name;
    EXCEPTION WHEN lock_not_available THEN
        NULL;
    END;
    PERFORM kingres.timepart_prune_runs(v_run.schema_name, v_run.table_name,
                                        v_run.as_of);
END;
$$;

-- begin, the phases and finish in sequence, for use from psql.  The
-- run's id comes back in run_id.  It commits between actions, so it cannot
-- run inside a transaction block.  Search path: see timepart_run_phase.
CREATE PROCEDURE kingres.timepart_run(
    rel regclass, as_of timestamptz DEFAULT now(),
    phases text[] DEFAULT '{create,convert,retire}',
    INOUT run_id bigint DEFAULT NULL)
LANGUAGE plpgsql
AS $$
DECLARE
    v_ph text;
BEGIN
    PERFORM pg_catalog.set_config('search_path', 'pg_catalog, pg_temp', true);
    -- Refuse a transaction block before anything is done.
    COMMIT;
    PERFORM pg_catalog.set_config('search_path', 'pg_catalog, pg_temp', true);
    PERFORM kingres.timepart__check_phases(phases);
    run_id := kingres.timepart_begin_run(rel, as_of, 'sql');
    COMMIT;
    PERFORM pg_catalog.set_config('search_path', 'pg_catalog, pg_temp', true);
    FOREACH v_ph IN ARRAY ARRAY['create', 'convert', 'retire'] LOOP
        IF v_ph OPERATOR(pg_catalog.=) ANY (phases) THEN
            CALL kingres.timepart_run_phase(run_id, v_ph);
            PERFORM pg_catalog.set_config('search_path', 'pg_catalog, pg_temp', true);
        END IF;
    END LOOP;
    PERFORM kingres.timepart_finish_run(run_id);
    COMMIT;
END;
$$;

CREATE FUNCTION kingres.timepart__check_phases(p_phases text[])
RETURNS void
LANGUAGE plpgsql IMMUTABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
BEGIN
    IF p_phases IS NULL OR EXISTS (SELECT 1 FROM unnest(p_phases) u(x)
                                    WHERE u.x IS NULL
                                       OR u.x NOT IN ('create', 'convert', 'retire')) THEN
        RAISE EXCEPTION 'phases must be a list of create, convert and retire'
            USING ERRCODE = '22023';
    END IF;
END;
$$;

-- True when the statement_timeout of the current statement has run out: the
-- session's setting is above zero and the statement has lasted at least 90
-- percent of it.  Tells the timeout from a cancel by an operator.
CREATE FUNCTION kingres.timepart__timed_out()
RETURNS boolean
LANGUAGE sql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
    SELECT s.setting::bigint > 0
           AND clock_timestamp() - statement_timestamp()
               >= (s.setting::bigint * 0.9) * interval '1 millisecond'
      FROM pg_settings s WHERE s.name = 'statement_timeout'
$$;

-- The statement_timeout, in milliseconds, that a driver sets before it calls
-- timepart_run_action: the setting kingres_timepart.action_timeout_ms (default
-- 300000, 5 minutes).
CREATE FUNCTION kingres.timepart_action_timeout()
RETURNS integer
LANGUAGE sql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
    SELECT kingres.timepart__setting_int(
               'kingres_timepart.action_timeout_ms', 300000, 1, 86400000)
$$;

