-- The two DDL steps (SECURITY INVOKER: PostgreSQL checks the privileges)
------------------------------------------------------------------------

-- Create one partition: a separate table made with CREATE TABLE ... (LIKE
-- parent), then ATTACH PARTITION.  CREATE TABLE ... PARTITION OF would take
-- ACCESS EXCLUSIVE on the parent; LIKE reads it with ACCESS SHARE and ATTACH
-- PARTITION takes SHARE UPDATE EXCLUSIVE, which blocks neither readers nor
-- writers.  The table is empty, so the attach scans nothing and no helper
-- CHECK constraint is needed.  One transaction: a failure leaves nothing.
-- The caller sets lock_timeout.
--
-- The statements are built by timepart__create_stmts and executed by the
-- caller, so that a run can execute them as the owner of the table (see
-- timepart__exec_as) without that role needing any right on this schema.
CREATE FUNCTION kingres.timepart__create_stmts(
    p_parent oid, p_schema name, p_name name, p_from text, p_to text,
    p_am name DEFAULT NULL)
RETURNS text[]
LANGUAGE plpgsql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_info   record;
    v_parent text;
    v_part   text := format('%I.%I', p_schema, p_name);
BEGIN
    SELECT * INTO v_info FROM kingres.timepart__key_info(p_parent);
    v_parent := format('%I.%I', v_info.r_schema, v_info.r_table);
    IF kingres.timepart__oid(p_schema, p_name) IS NOT NULL THEN
        RAISE EXCEPTION 'name_conflict: relation % already exists and is not the expected partition of %',
            v_part, v_parent USING ERRCODE = '42P07';
    END IF;
    RETURN ARRAY[
        format('CREATE TABLE %s (LIKE %s INCLUDING DEFAULTS INCLUDING CONSTRAINTS '
               'INCLUDING INDEXES INCLUDING STORAGE INCLUDING COMMENTS '
               'INCLUDING GENERATED INCLUDING COMPRESSION)%s',
               v_part, v_parent,
               CASE WHEN p_am IS NULL THEN '' ELSE format(' USING %I', p_am) END),
        format('ALTER TABLE %s ATTACH PARTITION %s FOR VALUES FROM (%L) TO (%L)',
               v_parent, v_part, p_from, p_to)];
END;
$$;

CREATE FUNCTION kingres.timepart_create_one(p_parent oid, p_schema name,
                                            p_name name, p_from text,
                                            p_to text, p_am name DEFAULT NULL)
RETURNS void
LANGUAGE plpgsql
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_stmt text;
BEGIN
    FOREACH v_stmt IN ARRAY kingres.timepart__create_stmts(
                 p_parent, p_schema, p_name, p_from, p_to, p_am) LOOP
        EXECUTE v_stmt;
    END LOOP;
END;
$$;

-- Retire one partition: detach it and, unless p_detach_only, drop it, in the
-- caller's transaction.  DETACH PARTITION needs ACCESS EXCLUSIVE on the
-- parent (DETACH ... CONCURRENTLY cannot run inside a function or procedure).
-- The caller sets lock_timeout.  As for creation, the statements are built
-- apart and executed by the caller.
CREATE FUNCTION kingres.timepart__retire_stmts(p_parent oid, p_part oid,
                                               p_detach_only boolean)
RETURNS text[]
LANGUAGE plpgsql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_info   record;
    v_parent text;
    v_part   text;
BEGIN
    SELECT * INTO v_info FROM kingres.timepart__key_info(p_parent);
    v_parent := format('%I.%I', v_info.r_schema, v_info.r_table);
    SELECT format('%I.%I', n.nspname, c.relname) INTO v_part
      FROM pg_inherits i
      JOIN pg_class c ON c.oid = i.inhrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE i.inhparent = p_parent AND i.inhrelid = p_part;
    IF v_part IS NULL THEN
        RAISE EXCEPTION 'relation with OID % is not a partition of %',
            p_part, v_parent USING ERRCODE = '42P01';
    END IF;
    RETURN CASE WHEN p_detach_only
        THEN ARRAY[format('ALTER TABLE %s DETACH PARTITION %s', v_parent, v_part)]
        ELSE ARRAY[format('ALTER TABLE %s DETACH PARTITION %s', v_parent, v_part),
                   format('DROP TABLE %s', v_part)] END;
END;
$$;

CREATE FUNCTION kingres.timepart_retire_one(p_parent oid, p_part oid,
                                            p_detach_only boolean)
RETURNS void
LANGUAGE plpgsql
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_stmt text;
BEGIN
    FOREACH v_stmt IN ARRAY kingres.timepart__retire_stmts(
                 p_parent, p_part, p_detach_only) LOOP
        EXECUTE v_stmt;
    END LOOP;
END;
$$;

------------------------------------------------------------------------
-- create_time_partitions and drop_old_time_partitions
------------------------------------------------------------------------

CREATE FUNCTION kingres.create_time_partitions(
    rel regclass, partition_every interval, end_at timestamptz,
    start_from timestamptz DEFAULT now(), access_method name DEFAULT NULL,
    timezone text DEFAULT 'UTC')
RETURNS integer
LANGUAGE plpgsql
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_info   record;
    v_parts  record;
    v_tz     text;
    v_first  bigint;
    v_last   bigint;
    v_n      integer := 0;
    v_am     name := access_method;
    r        record;
BEGIN
    -- Reading the bounds of the partitions takes a lock on them, so the wait
    -- is bounded from the first statement on.
    PERFORM pg_catalog.set_config('lock_timeout', kingres.timepart__lock_timeout('create'), true);
    SELECT * INTO v_info FROM kingres.timepart__key_info(rel::oid);
    PERFORM kingres.timepart__require_owner(
        current_user, v_info.r_owner_oid,
        format('%I.%I', v_info.r_schema, v_info.r_table));
    IF v_info.r_default IS NOT NULL THEN
        RAISE EXCEPTION 'table %.% has a default partition "%"',
            quote_ident(v_info.r_schema), quote_ident(v_info.r_table),
            v_info.r_default
            USING ERRCODE = '0A000',
                  HINT = 'ATTACH PARTITION scans the default partition under a strong lock; create partitions far enough ahead instead.';
    END IF;
    PERFORM kingres.timepart__check_tz(timezone);
    SELECT * INTO v_parts FROM kingres.timepart_interval_parts(partition_every);
    IF v_info.r_keytype = 'date' AND v_parts.unit = 'hour' THEN
        RAISE EXCEPTION 'partition_every in hours needs a timestamp or timestamptz column, not date'
            USING ERRCODE = '22023';
    END IF;
    IF end_at IS NULL OR start_from IS NULL
       OR end_at IN ('infinity', '-infinity')
       OR start_from IN ('infinity', '-infinity') THEN
        RAISE EXCEPTION 'start_from and end_at must be finite times'
            USING ERRCODE = '22008';
    END IF;
    v_tz := CASE WHEN v_info.r_keytype = 'timestamptz' THEN timezone ELSE 'UTC' END;
    v_first := kingres.timepart_cell_of(
        partition_every, v_tz,
        kingres.timepart__eff(start_from, v_info.r_keytype, timezone));
    v_last := kingres.timepart_cell_of(
        partition_every, v_tz,
        kingres.timepart__eff(end_at, v_info.r_keytype, timezone));
    IF v_last < v_first THEN
        RAISE EXCEPTION 'end_at is before start_from' USING ERRCODE = '22023';
    END IF;
    IF v_am IS NULL THEN
        SELECT a.amname INTO v_am FROM pg_am a WHERE a.oid = v_info.r_am;
    END IF;
    FOR r IN SELECT * FROM kingres.timepart__create_rows(
                 rel::oid, partition_every, v_tz, v_first, v_last) c
    LOOP
        PERFORM kingres.timepart_create_one(
            rel::oid, r.part_schema, r.part_name,
            kingres.timepart__bound_literal(v_info.r_keytype, r.lo),
            kingres.timepart__bound_literal(v_info.r_keytype, r.hi), v_am);
        v_n := v_n + 1;
    END LOOP;
    RETURN v_n;
END;
$$;

CREATE FUNCTION kingres.drop_old_time_partitions(
    rel regclass, older_than timestamptz, detach_only boolean DEFAULT false,
    timezone text DEFAULT 'UTC')
RETURNS integer
LANGUAGE plpgsql
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_info   record;
    v_limit  timestamptz;
    v_n      integer := 0;
    r        record;
BEGIN
    PERFORM pg_catalog.set_config('lock_timeout', kingres.timepart__lock_timeout('retire'), true);
    SELECT * INTO v_info FROM kingres.timepart__key_info(rel::oid);
    PERFORM kingres.timepart__require_owner(
        current_user, v_info.r_owner_oid,
        format('%I.%I', v_info.r_schema, v_info.r_table));
    PERFORM kingres.timepart__check_tz(timezone);
    IF older_than IS NULL OR older_than IN ('infinity', '-infinity') THEN
        RAISE EXCEPTION 'older_than must be a finite time' USING ERRCODE = '22008';
    END IF;
    v_limit := kingres.timepart__eff(older_than, v_info.r_keytype, timezone);
    FOR r IN SELECT * FROM kingres.timepart__children(rel::oid) c
              WHERE NOT c.is_default AND c.hi < 'infinity' AND c.hi <= v_limit
              ORDER BY c.hi
    LOOP
        PERFORM kingres.timepart_retire_one(rel::oid, r.part_oid,
                                            coalesce(detach_only, false));
        v_n := v_n + 1;
    END LOOP;
    RETURN v_n;
END;
$$;

