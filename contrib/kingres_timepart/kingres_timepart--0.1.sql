    retention        interval,
    retention_action text        NOT NULL DEFAULT 'drop',
    columnar_after   interval,
    columnar_sort    text[],
    columnar_options jsonb,
    run_every        interval    NOT NULL DEFAULT '1 hour',
    enabled          boolean     NOT NULL DEFAULT true,
    next_run_at      timestamptz NOT NULL DEFAULT now(),
    table_owner      name        NOT NULL,
    created_by       name        NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    -- see "Identity": the OIDs below are trusted only when stamp is this
