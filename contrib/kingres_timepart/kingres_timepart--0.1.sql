-- The input is called as_of_time, not as_of, because PostgreSQL does not
-- allow an input and an output column of one function to share a name.
CREATE FUNCTION kingres.timepart_due(as_of_time timestamptz DEFAULT now())
RETURNS TABLE (schema_name name, table_name name, as_of timestamptz)
LANGUAGE plpgsql
SET search_path = pg_catalog, kingres, pg_temp
AS $$
BEGIN
    PERFORM kingres.timepart__require_superuser();
    -- the scheduler asks what is due before it runs anything: rows that a
    -- backup carried here are given the roles and tables of this cluster now
    PERFORM kingres.timepart_adopt();
    RETURN QUERY
    SELECT p.schema_name, p.table_name, as_of_time
      FROM kingres.timepart_policy_data p
     WHERE p.enabled AND p.next_run_at <= as_of_time
     ORDER BY p.next_run_at, p.schema_name, p.table_name;
END;
$$;

-- The partitions of a table with bounds, size and format.  Also lists the
-- partitions that a retention policy detached and kept, with attached =
-- false (to the owner of the table only, and only those that the caller can
-- read).  Needs ownership of the table or SELECT on it.
CREATE FUNCTION kingres.timepart_partitions(rel regclass)
RETURNS TABLE (partition regclass, range_from timestamptz,
               range_to timestamptz, access_method name, size_bytes bigint,
               row_estimate bigint, compression_ratio float8,
               attached boolean)
LANGUAGE plpgsql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_info   record;
BEGIN
    -- Reading the bounds of the partitions takes locks: bound the wait, so that
    -- a long transaction on the table cannot hold a monitor up.
    PERFORM pg_catalog.set_config('lock_timeout', kingres.timepart__lock_timeout('create'), true);
    SELECT * INTO v_info FROM kingres.timepart__key_info(rel::oid);
    IF NOT (pg_has_role(current_user, v_info.r_owner_oid, 'USAGE')
            OR has_table_privilege(current_user, rel::oid, 'SELECT')) THEN
        RAISE EXCEPTION 'permission denied for table %',
            format('%I.%I', v_info.r_schema, v_info.r_table)
            USING ERRCODE = '42501';
    END IF;
    RETURN QUERY
    SELECT format('%I.%I', c.part_schema, c.part_name)::regclass,
           c.lo, c.hi, c.am_name,
           pg_total_relation_size(c.part_oid),
           (SELECT CASE WHEN cl.reltuples < 0 THEN NULL
                        ELSE cl.reltuples::bigint END
              FROM pg_class cl WHERE cl.oid = c.part_oid),
           NULL::float8, true
      FROM kingres.timepart__children(rel::oid) c
     WHERE NOT c.is_default
     ORDER BY c.lo;
    RETURN QUERY
    SELECT DISTINCT ON (a.partition_schema, a.partition_name)
           kingres.timepart__oid(a.partition_schema, a.partition_name)::regclass,
           a.range_from, a.range_to,
           (SELECT am.amname FROM pg_class cl JOIN pg_am am ON am.oid = cl.relam
             WHERE cl.oid = kingres.timepart__oid(a.partition_schema, a.partition_name)),
           pg_total_relation_size(kingres.timepart__oid(a.partition_schema, a.partition_name)),
           (SELECT CASE WHEN cl.reltuples < 0 THEN NULL
                        ELSE cl.reltuples::bigint END
              FROM pg_class cl
             WHERE cl.oid = kingres.timepart__oid(a.partition_schema, a.partition_name)),
           NULL::float8, false
      FROM kingres.timepart_run_action a
      JOIN kingres.timepart_run r ON r.run_id = a.run_id
     WHERE r.table_oid = rel::oid
       AND a.kind = 'detach' AND a.state = 'done'
       AND kingres.timepart__oid(a.partition_schema, a.partition_name) IS NOT NULL
       AND has_table_privilege(current_user,
                               kingres.timepart__oid(a.partition_schema, a.partition_name)::oid, 'SELECT')
       AND NOT EXISTS (
           SELECT 1 FROM pg_inherits i
            WHERE i.inhrelid = kingres.timepart__oid(a.partition_schema, a.partition_name)::oid)
     ORDER BY a.partition_schema, a.partition_name, a.run_id DESC;
END;
$$;

-- Problems of the tables that have a policy: ahead_low, last_run_failed,
-- retire_blocked, policy_orphan, default_partition_present, misaligned and
-- lock_timeout.  A superuser sees
-- every table, another role sees the tables it owns.  p_as_of is the time
-- "ahead" is measured from.
CREATE FUNCTION kingres.timepart_check(
    min_ahead interval DEFAULT NULL, as_of timestamptz DEFAULT now())
RETURNS TABLE (schema_name name, table_name name, problem text, detail text)
LANGUAGE plpgsql STABLE
SET search_path = pg_catalog, kingres, pg_temp
AS $$
DECLARE
    v_super  boolean;
    v_pol    kingres.timepart_policy%ROWTYPE;
    v_oid    oid;
    v_info   record;
    v_ok     boolean;
    v_tz     text;
    v_last   timestamptz;
    v_need   timestamptz;
    v_run    kingres.timepart_run%ROWTYPE;
    v_mis    text;
BEGIN
    -- Reading the bounds of the partitions takes locks: bound the wait, so that
    -- a long transaction on the table cannot hold a monitor up.
    PERFORM pg_catalog.set_config('lock_timeout', kingres.timepart__lock_timeout('create'), true);
    SELECT coalesce(bool_or(r.rolsuper), false) INTO v_super
      FROM pg_roles r WHERE r.rolname = current_user;
    FOR v_pol IN SELECT p.* FROM kingres.timepart_policy p
                  ORDER BY p.schema_name, p.table_name
    LOOP
        BEGIN
            v_oid := kingres.timepart__oid(v_pol.schema_name, v_pol.table_name)::oid;
            v_ok := false;
            IF v_oid IS NOT NULL THEN
                BEGIN
                    SELECT * INTO v_info FROM kingres.timepart__key_info(v_oid);
                    v_ok := true;
                EXCEPTION WHEN lock_not_available THEN
                    RAISE;
                WHEN OTHERS THEN
                    v_ok := false;
                END;
            END IF;
            IF NOT v_ok THEN
                IF v_super THEN
                    schema_name := v_pol.schema_name; table_name := v_pol.table_name;
                    problem := 'policy_orphan';
                    detail := 'the table does not exist or is no longer a suitable partitioned table';
                    RETURN NEXT;
                END IF;
                CONTINUE;
            END IF;
            IF NOT pg_has_role(current_user, v_info.r_owner_oid, 'USAGE') THEN
                CONTINUE;
            END IF;

            IF v_info.r_default IS NOT NULL THEN
                schema_name := v_pol.schema_name; table_name := v_pol.table_name;
                problem := 'default_partition_present';
                detail := format('default partition %I', v_info.r_default);
                RETURN NEXT;
            END IF;

            v_tz := CASE WHEN v_info.r_keytype = 'timestamptz'
                         THEN v_pol.timezone ELSE 'UTC' END;
            SELECT max(c.hi) INTO v_last
              FROM kingres.timepart__children(v_oid) c WHERE NOT c.is_default;
            v_need := kingres.timepart__add(
                kingres.timepart__eff(as_of, v_info.r_keytype, v_pol.timezone),
                coalesce(min_ahead, v_pol.create_ahead / 2), v_tz, 1);
            IF v_last IS NULL OR v_last < v_need THEN
                schema_name := v_pol.schema_name; table_name := v_pol.table_name;
                problem := 'ahead_low';
                detail := CASE WHEN v_last IS NULL THEN 'the table has no partitions'
                               ELSE format('the last partition ends at %s, before %s',
                                           v_last, v_need) END;
                RETURN NEXT;
            END IF;

            SELECT string_agg(format('%I', m.part_name), ', ' ORDER BY m.lo)
              INTO v_mis
              FROM kingres.timepart__misaligned(v_oid, v_pol.partition_every, v_tz) m;
            IF v_mis IS NOT NULL THEN
                schema_name := v_pol.schema_name; table_name := v_pol.table_name;
                problem := 'misaligned';
                detail := 'partitions with bounds off the grid: ' || v_mis;
                RETURN NEXT;
            END IF;

            SELECT r.* INTO v_run FROM kingres.timepart_run r
             WHERE r.table_oid = v_oid
               AND r.state <> 'running'
             ORDER BY r.run_id DESC LIMIT 1;
            IF FOUND AND v_run.state IN ('failed', 'partial') THEN
                schema_name := v_pol.schema_name; table_name := v_pol.table_name;
                problem := 'last_run_failed';
                detail := format('the last run (as of %s) ended %s%s', v_run.as_of,
                                 v_run.state, coalesce(': ' || v_run.error, ''));
                RETURN NEXT;
                -- Actions of that run that could not retire a partition: a view or
                -- a foreign key that needs it, a role that does not own it.
                SELECT string_agg(format('%I (%s)', a.partition_name, left(a.detail, 60)),
                                  '; ' ORDER BY a.seq)
                  INTO v_mis
                  FROM kingres.timepart_run_action a
                 WHERE a.run_id = v_run.run_id AND a.state = 'failed'
                   AND a.kind IN ('drop', 'detach');
                IF v_mis IS NOT NULL THEN
                    schema_name := v_pol.schema_name; table_name := v_pol.table_name;
                    problem := 'retire_blocked';
                    detail := 'partitions that could not be retired: ' || v_mis;
                    RETURN NEXT;
                END IF;
            END IF;
        EXCEPTION WHEN lock_not_available THEN
            schema_name := v_pol.schema_name; table_name := v_pol.table_name;
            problem := 'lock_timeout';
            detail := 'the partitions could not be read before the lock timeout';
            RETURN NEXT;
        WHEN OTHERS THEN
            schema_name := v_pol.schema_name; table_name := v_pol.table_name;
            problem := 'check_failed';
            detail := left(SQLSTATE || ': ' || SQLERRM, 200);
            RETURN NEXT;
        END;
    END LOOP;
END;
$$;

CREATE VIEW kingres.timepart_policies WITH (security_invoker = true) AS
SELECT p.schema_name, p.table_name, p.parent_oid, p.partition_every,
       p.timezone, p.create_ahead, p.retention, p.retention_action,
       p.columnar_after, p.columnar_sort, p.columnar_options, p.run_every,
       p.enabled, p.next_run_at, p.table_owner, p.created_by, p.created_at,
       p.updated_at,
       lr.run_id AS last_run_id, lr.state AS last_run_state,
       lr.as_of AS last_run_as_of, lr.finished_at AS last_run_finished_at,
       lr.error AS last_run_error
  FROM kingres.timepart_policy p
  LEFT JOIN LATERAL (
        SELECT r.run_id, r.state, r.as_of, r.finished_at, r.error
          FROM kingres.timepart_run r
         WHERE r.table_oid = kingres.timepart__oid(p.schema_name, p.table_name)
         ORDER BY r.run_id DESC LIMIT 1) lr ON true;

-- The policy and the history are readable by every role through the views,
-- which show the rows of the tables the role owns.  A role changes a policy
-- through timepart_set_policy and timepart_unset_policy, or directly through
-- the view: the trigger timepart_policy_pin and the check option keep a
-- direct write to the tables the role owns, with the values pinned by the
-- extension.  The history is read only.
GRANT SELECT, INSERT, UPDATE, DELETE ON kingres.timepart_policy TO PUBLIC;
GRANT SELECT ON kingres.timepart_run, kingres.timepart_run_action,
    kingres.timepart_policies TO PUBLIC;

