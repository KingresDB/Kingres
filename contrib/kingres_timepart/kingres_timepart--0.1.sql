-- SPDX-License-Identifier: AGPL-3.0-only

\echo Use "CREATE EXTENSION kingres_timepart" to load this file. \quit

-- Conventions of this script
--
--   * The control file sets "schema = kingres" and "relocatable = false".
--     Every object is created in that schema and every reference to an
--     object of the extension is qualified.
--   * Every function carries "SET search_path = pg_catalog, kingres,
--     pg_temp", with two exceptions: the two procedures that commit between
--     their steps (timepart_run and timepart_run_phase).  A procedure with a
--     SET clause or with SECURITY DEFINER cannot COMMIT.  These two carry no
--     SET clause; instead their first statement, and the first statement
--     after each COMMIT, sets the search_path of the transaction to
--     "pg_catalog, pg_temp" with set_config(..., true); every function they
--     call is schema-qualified, and every operator is resolved under that
--     path.  The test timepart_security attacks them with a schema that
--     holds a look-alike of every function the bodies call.
--   * Dynamic SQL is built with format() and %I / %L only.  Names of
--     partitions are generated by timepart_part_name and always quoted.
--   * The caller's identity is current_user.  SECURITY DEFINER is used by the
--     two event trigger functions and by one function that timepart__exec_as
--     makes in the temporary schema of a session for the length of an action
--     (see there).  The policy and history tables
--     (the "_data" tables) grant nothing to PUBLIC; a role reaches them
--     through security_barrier views that show the rows of the tables it owns
--     (judged by current_user), and a trigger pins the columns a role must
--     not choose; so set_policy and the
--     others are SECURITY INVOKER and PostgreSQL checks what the caller may
--     do, also when code of a low-privilege role runs in a session of a
--     superuser.
--   * Names that start with "timepart__" are internal helpers.

------------------------------------------------------------------------
-- Identity: what a row of the policy or the history refers to
------------------------------------------------------------------------

-- A row names a table by schema and name and a role by name, which a backup
-- carries, and keeps the OID of both, which a rename does not change but a
-- backup does not carry: another cluster has other role OIDs, another
-- database other table OIDs, and an OID can even be the one of another object
-- there.  The stamp tells which of the two a row can be trusted for.  It is
-- made when the extension is created, so it differs in every database that
-- was made by CREATE EXTENSION and is never copied by a dump (the function
-- is part of the extension, the rows are data):
--
--   * a row whose stamp is the stamp of this installation was written here:
--     its OIDs are the identity (a role renamed, a table renamed or moved
--     keep it; a role or a table that was dropped is gone for good, and a new
--     one of the same name is another one);
--   * any other row was restored from a backup: its OIDs mean nothing, and its
--     names are the identity until timepart_adopt() (which every
--     timepart_begin_run does first) replaces them by the OIDs of the roles and
--     tables of that name and gives the row the stamp of this installation.
--
-- The function is created by the DO block below because its body holds a
-- random value, and is not part of the pure helpers.
DO $stamp$
BEGIN
    EXECUTE pg_catalog.format(
        'CREATE FUNCTION kingres.timepart__stamp() RETURNS pg_catalog.uuid '
        'LANGUAGE sql STABLE SET search_path = pg_catalog, pg_temp AS %L',
        pg_catalog.format('SELECT %L::pg_catalog.uuid', pg_catalog.gen_random_uuid()));
END
$stamp$;

COMMENT ON FUNCTION kingres.timepart__stamp() IS
    'Identifies this installation of the extension: OIDs in rows with another stamp come from a backup';

