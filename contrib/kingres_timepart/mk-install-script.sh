# mk-install-script.sh: write kingres_timepart--0.3.sql, the install script of the current version: the 0.2
# install script from its \echo line on, followed by the 0.2--0.3 upgrade script after its \echo line (the
# "upgrade" regression test compares the catalogs of the two ways).  Run it in contrib/kingres_timepart after
# every change of kingres_timepart--0.2--0.3.sql; t/010_install_script_current.pl fails when the committed file
# differs (KT_INSTALL_SCRIPT_OUT names another output file).
set -eu
d=$(cd "$(dirname "$0")" && pwd)
out=${KT_INSTALL_SCRIPT_OUT:-$d/kingres_timepart--0.3.sql}
{
  cat <<'HDR'
-- SPDX-License-Identifier: AGPL-3.0-only
-- Portions Copyright (c) 2026, RooyeKhat Media Co
--
-- kingres_timepart--0.3.sql
--   Install script of the kingres_timepart extension, version 0.3: everything of 0.2 and the changes of
--   kingres_timepart--0.2--0.3.sql appended (time partitioning policies on distributed tables).  Generated by
--   mk-install-script.sh from the 0.2 install script and the 0.2--0.3 upgrade script: change the upgrade
--   script and run the generator, never edit this file by hand.
--
HDR
  n=$(grep -n "^.echo Use \"CREATE EXTENSION" "$d/kingres_timepart--0.2.sql" | head -1 | cut -d: -f1)
  tail -n +"$n" "$d/kingres_timepart--0.2.sql"
  echo
  echo "-- ---------------------------------------------------------------------------"
  echo "-- Version 0.3: distributed tables (the upgrade script 0.2--0.3, appended)"
  echo "-- ---------------------------------------------------------------------------"
  n=$(grep -n "^.echo Use \"ALTER EXTENSION kingres_timepart UPDATE TO" "$d/kingres_timepart--0.2--0.3.sql" | head -1 | cut -d: -f1)
  tail -n +"$((n + 1))" "$d/kingres_timepart--0.2--0.3.sql"
} > "$out"
