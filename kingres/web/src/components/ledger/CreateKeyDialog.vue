<script setup lang="ts">
// Creates the first signing key of the ledger, or rotates the key (contract 0.11.0, design 3.2 and 3.3). The first key
// locks the origin prefix, so the dialog shows the prefix and asks for its confirmation before the key exists; a rotation
// adds a key that signs together with the old one for the overlap, then the old one is retired. The panel never asks for
// a private key, a seed or a passphrase: the server generates the key and keeps it.
import { computed, reactive, ref } from 'vue'
import TaskActionDialog from '@/components/TaskActionDialog.vue'
import FormField from '@/components/FormField.vue'
import SafeName from '@/components/SafeName.vue'
import { endpoints } from '@/api/endpoints'
import { keys } from '@/api/queries'
import { BACKUP_TEXT, ORIGIN_PREFIX_HELP } from '@/lib/ledger-signing'

const props = defineProps<{
  first: boolean
  mode: 'file' | 'command'
  /** The origin prefix as the settings say it now: before the first key it is only a proposal. */
  originPrefix: string
}>()
const emit = defineEmits<{ close: [] }>()

const form = reactive({
  prefix: props.originPrefix,
  overlapDays: '30',
  publicKey: '',
  backup: false,
})
const confirmed = ref(false)
const errors = ref<Record<string, string>>({})

const KEY32 = /^[A-Za-z0-9+/]{43}=$/
function validate(): boolean {
  const e: Record<string, string> = {}
  if (props.first) {
    const p = form.prefix
    if (p.length < 1 || p.length > 160 || /:\/\/|\/$|\s/.test(p))
      e['publication.originPrefix'] =
        'Use a name without a scheme, without a trailing slash and without spaces, at most 160 characters.'
  } else {
    const n = Number(form.overlapDays)
    if (!Number.isInteger(n) || n < 1 || n > 365)
      e.overlapDays = 'Enter a whole number of days from 1 to 365.'
  }
  if (props.mode === 'command' && !KEY32.test(form.publicKey))
    e.publicKey = 'Give the 32-byte public key of the external signer as standard base64.'
  errors.value = e
  return Object.keys(e).length === 0
}
const errorFor = (field: string, server: Record<string, string>): string | undefined =>
  errors.value[field] ?? server[field]

async function start() {
  // The prefix is free until the first key exists; a changed value is stored first, then the key is made under it.
  if (props.first && form.prefix !== props.originPrefix)
    await endpoints.updateLedgerSettings({ publication: { originPrefix: form.prefix } })
  return endpoints.createLedgerSigningKey({
    ...(props.first ? {} : { overlapDays: Number(form.overlapDays) }),
    ...(props.mode === 'command' ? { publicKey: form.publicKey } : {}),
    ...(!props.first && form.backup ? { backupMade: true } : {}),
  })
}
const title = computed(() =>
  props.first ? 'Create the first signing key' : 'Rotate the signing key',
)
</script>

<template>
  <TaskActionDialog
    :title="title"
    :confirm-label="first ? 'Create the key' : 'Rotate the key'"
    wide
    :start="start"
    :validate="validate"
    :confirm-disabled="first && !confirmed"
    :invalidate="[
      keys.ledgerSigning,
      keys.ledgerSettings,
      keys.ledgerStatus,
      keys.ledgerPublication,
    ]"
    @close="emit('close')"
  >
    <template #default="{ fieldErrors }">
      <template v-if="first">
        <p>
          The server generates an Ed25519 key, stores it on the servers that may become the manager
          leader, records the event and makes the key active. From then on every checkpoint of every
          log of the cluster is signed with it. The private key never leaves those servers and is
          never shown here.
        </p>
        <FormField
          v-slot="slot"
          label="Origin prefix"
          :hint="ORIGIN_PREFIX_HELP"
          :error="errorFor('publication.originPrefix', fieldErrors)"
          required
        >
          <input
            v-bind="slot"
            v-model="form.prefix"
            class="input mono"
            autocomplete="off"
            spellcheck="false"
          />
        </FormField>
        <label class="check">
          <input v-model="confirmed" type="checkbox" />
          I confirm the origin prefix
          <code class="mono"><SafeName :value="form.prefix" kind="text" :max="160" /></code>. It
          cannot be changed after the key is created.
        </label>
      </template>
      <template v-else>
        <p>
          A rotation adds a new key, generated by the server; its private part is never shown here.
          The old and the new key both sign every checkpoint for the overlap, so that an auditor who
          pinned the old key accepts the new one without a new out-of-band step. Then the old key is
          retired, or you retire it at once on the Signing tab.
        </p>
        <FormField
          v-slot="slot"
          label="Overlap in days"
          hint="From 1 to 365; the default is 30."
          :error="errorFor('overlapDays', fieldErrors)"
        >
          <input
            v-bind="slot"
            v-model="form.overlapDays"
            class="input"
            inputmode="numeric"
            autocomplete="off"
          />
        </FormField>
        <label class="check">
          <input v-model="form.backup" type="checkbox" />
          I have made a backup of the key directory and of the passphrase file, off the cluster.
          This only clears the reminder; it is not a proof.
        </label>
      </template>
      <FormField
        v-if="mode === 'command'"
        v-slot="slot"
        label="Public key of the external signer"
        hint="Standard base64 of the 32-byte public key. This is a public key; the signer keeps the private one."
        :error="errorFor('publicKey', fieldErrors)"
        required
      >
        <input
          v-bind="slot"
          v-model="form.publicKey"
          class="input mono"
          autocomplete="off"
          spellcheck="false"
        />
      </FormField>
      <p class="muted">{{ BACKUP_TEXT }}</p>
    </template>
    <template #result>
      <p class="notice tone-info" role="status" data-testid="create-key-next">
        <span aria-hidden="true">&#9432;</span>
        <span
          >Next: download the trust file and keep a copy outside this cluster, read the fingerprint
          to the auditor, and back up the key directory and the passphrase file separately.</span
        >
      </p>
    </template>
  </TaskActionDialog>
</template>
