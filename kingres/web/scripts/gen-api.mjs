// Generates the two files that are derived from the OpenAPI contract:
//   src/api/schema.d.ts            TypeScript types (openapi-typescript)
//   src/api/operations.generated.ts  operationId -> required cluster role (x-required-role)
//
//   node scripts/gen-api.mjs          write the files
//   node scripts/gen-api.mjs --check  exit 1 if a committed file is stale
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { dirname, resolve } from 'node:path'
import openapiTS, { astToString } from 'openapi-typescript'
import { parse } from 'yaml'

const here = dirname(fileURLToPath(import.meta.url))
const specPath = resolve(here, '../../api/openapi.yaml')
const outputs = {
  schema: resolve(here, '../src/api/schema.d.ts'),
  operations: resolve(here, '../src/api/operations.generated.ts'),
}

const HEADER = `// SPDX-License-Identifier: PostgreSQL
// Copyright (c) 2026, RooyeKhat Media Co
//
// GENERATED by scripts/gen-api.mjs from kingres/api/openapi.yaml. Do not edit by hand.
// Regenerate with: npm run api:generate

`

const norm = (s) => s.replace(/\r\n/g, '\n')

async function generateSchema() {
  const ast = await openapiTS(pathToFileURL(specPath), { defaultNonNullable: false })
  return HEADER + norm(astToString(ast))
}

function generateOperations() {
  const doc = parse(readFileSync(specPath, 'utf8'))
  const rows = []
  for (const [path, item] of Object.entries(doc.paths)) {
    for (const method of ['get', 'put', 'post', 'delete', 'patch']) {
      const op = item[method]
      if (!op) continue
      rows.push({
        id: op.operationId,
        role: op['x-required-role'],
        method: method.toUpperCase(),
        path,
      })
    }
  }
  rows.sort((a, b) => a.id.localeCompare(b.id))
  const auditActions = doc.components.schemas.AuditAction.enum
  const roles = [...new Set(rows.map((r) => r.role))]
  const body = rows
    .map((r) => `  ${r.id}: { role: '${r.role}', method: '${r.method}', path: '${r.path}' },`)
    .join('\n')
  return (
    HEADER +
    `export type RequiredRole = ${roles.map((r) => `'${r}'`).join(' | ')}\n\n` +
    `/** Minimum cluster role, HTTP method and path of every operation, from \`x-required-role\`. */\n` +
    `export const operations = {\n${body}\n} as const satisfies Record<\n  string,\n  { role: RequiredRole; method: string; path: string }\n>\n\n` +
    `export type OperationId = keyof typeof operations\n\n` +
    `/** The closed list of audit actions (components/schemas/AuditAction). */\n` +
    `export const auditActions = [${auditActions.map((a) => `'${a}'`).join(', ')}] as const\n`
  )
}

/** Returns { file: content } for every generated file. */
export async function generateAll() {
  return { [outputs.schema]: await generateSchema(), [outputs.operations]: generateOperations() }
}

function committed(file) {
  try {
    return norm(readFileSync(file, 'utf8'))
  } catch {
    return null
  }
}

/** Returns the list of generated files whose committed content differs from the spec. */
export async function staleFiles() {
  const all = await generateAll()
  return Object.entries(all)
    .filter(([file, content]) => committed(file) !== content)
    .map(([file]) => file)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes('--check')) {
    const stale = await staleFiles()
    if (stale.length > 0) {
      console.error(
        `Out of date with kingres/api/openapi.yaml:\n  ${stale.join('\n  ')}\nRun: npm run api:generate`,
      )
      process.exit(1)
    }
    console.log('Generated API files are up to date.')
  } else {
    for (const [file, content] of Object.entries(await generateAll())) {
      writeFileSync(file, content)
      console.log(`Wrote ${file}`)
    }
  }
}
