// Takes the logo files from kingres/brand/ (the source of truth) and produces what the panel needs:
//   public/favicon.svg, favicon-32.png, apple-touch-icon.png, icon-512.png   byte copies
//   src/components/brand.generated.ts   the exact path data of the logo, read from the SVG files
//
//   node scripts/brand-sync.mjs          write the files
//   node scripts/brand-sync.mjs --check  exit 1 if a committed file differs from its source
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const brand = resolve(here, '../../brand')
const web = resolve(here, '..')

/** Static files that must exist at a fixed URL: [source in brand/, target in public/]. */
export const COPIES = [
  ['svg/kingres-db-app-icon.svg', 'public/favicon.svg'],
  ['png/favicon-32.png', 'public/favicon-32.png'],
  ['png/favicon-180.png', 'public/apple-touch-icon.png'],
  ['png/favicon-512.png', 'public/icon-512.png'],
]
export const GENERATED = 'src/components/brand.generated.ts'

const svg = (name) => readFileSync(resolve(brand, 'svg', name), 'utf8').replace(/\r\n/g, '\n')

function must(match, what) {
  if (!match) throw new Error(`brand-sync: could not find ${what} in the SVG files`)
  return match
}

/** The crown, the shield clip and the two glyph paths of a mark SVG. */
function parseMark(source) {
  const clip = must(/<clipPath id="shg"><path d="([^"]+)"/.exec(source), 'the shield clip')[1]
  const crown = must(/<g fill="#14171F">\s*([\s\S]*?)<\/g>/.exec(source), 'the crown')[1]
  const shield = must(
    /<g fill="url\(#gdg\)" clip-path="url\(#shg\)" fill-rule="evenodd">\s*([\s\S]*?)<\/g>/.exec(
      source,
    ),
    'the shield glyphs',
  )[1]
  const stops = [...source.matchAll(/<stop offset="(\d)" stop-color="(#[0-9A-Fa-f]{6})"\/>/g)]
  const rect = must(
    /<rect x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)" rx="(\d+)"\/>/.exec(crown),
    'the crown band',
  )
  return {
    shieldClip: clip,
    crownPath: must(/<path d="([^"]+)"\/>/.exec(crown), 'the crown path')[1],
    crownCircles: [...crown.matchAll(/<circle cx="(\d+)" cy="(\d+)" r="(\d+)"\/>/g)].map((m) => [
      Number(m[1]),
      Number(m[2]),
      Number(m[3]),
    ]),
    crownBand: rect.slice(1, 6).map(Number),
    glyphPaths: [...shield.matchAll(/<path d="([^"]+)"\/>/g)].map((m) => m[1]),
    gradient: stops.map((m) => m[2]),
  }
}

function viewBox(source) {
  const m = must(/viewBox="0 0 (\d+) (\d+)"/.exec(source), 'the viewBox')
  return [Number(m[1]), Number(m[2])]
}

/** Builds the content of brand.generated.ts. */
export function generateBrandModule() {
  const mark = svg('kingres-db-mark-color-light.svg')
  const horizontal = svg('kingres-db-horizontal-color-light.svg')
  const stacked = svg('kingres-db-stacked-color-light.svg')
  const markData = parseMark(mark)

  // The lockups embed the same mark, scaled. Refuse to continue if the artwork ever differs.
  for (const [name, source] of [
    ['horizontal', horizontal],
    ['stacked', stacked],
  ]) {
    const inner = parseMark(source)
    if (JSON.stringify(inner) !== JSON.stringify(markData)) {
      throw new Error(`brand-sync: the mark inside the ${name} logo differs from the mark logo`)
    }
  }

  const horizontalWord = must(
    /<path d="([^"]+)" fill="#14171F"\/><path d="([^"]+)" fill="#C8962E"\/>/.exec(horizontal),
    'the horizontal wordmark',
  )
  const stackedWord = must(
    /<g transform="(translate\([^)]*\))"><path d="([^"]+)" fill="#14171F"\/><path d="([^"]+)" fill="#C8962E"\/><\/g>/.exec(
      stacked,
    ),
    'the stacked wordmark',
  )
  const transform = (source) =>
    must(
      /<g transform="(translate\([^)]*\) scale\([^)]*\))">/.exec(source),
      'the mark transform',
    )[1]

  const data = {
    mark: { viewBox: viewBox(mark), ...markData },
    horizontal: {
      viewBox: viewBox(horizontal),
      markTransform: transform(horizontal),
      wordmark: { kingres: horizontalWord[1], db: horizontalWord[2] },
    },
    stacked: {
      viewBox: viewBox(stacked),
      markTransform: transform(stacked),
      wordmarkTransform: stackedWord[1],
      wordmark: { kingres: stackedWord[2], db: stackedWord[3] },
    },
  }
  return (
    `// SPDX-License-Identifier: PostgreSQL\n` +
    `// Copyright (c) 2026, RooyeKhat Media Co\n` +
    `//\n` +
    `// GENERATED by scripts/brand-sync.mjs from kingres/brand/svg. Do not edit by hand.\n` +
    `// Regenerate with: npm run brand:sync\n\n` +
    `/** Exact path data of the KingresDB logo, as drawn in the supplied SVG files. */\n` +
    `export const brandArt = ${JSON.stringify(data, null, 2)} as const\n`
  )
}

/** Reads a file, or returns null when it does not exist. */
function readOrNull(path) {
  try {
    return readFileSync(path)
  } catch {
    return null
  }
}

/** Returns the target files (relative to web/) whose committed content differs from the source. */
export function staleBrandFiles() {
  const stale = []
  for (const [from, to] of COPIES) {
    const copy = readOrNull(resolve(web, to))
    if (copy === null || !readFileSync(resolve(brand, from)).equals(copy)) stale.push(to)
  }
  const generated = readOrNull(resolve(web, GENERATED))
  const current =
    generated === null
      ? null
      : generated.toString('utf8').split(String.fromCharCode(13, 10)).join(String.fromCharCode(10))
  if (current !== generateBrandModule()) stale.push(GENERATED)
  return stale
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes('--check')) {
    const stale = staleBrandFiles()
    if (stale.length > 0) {
      console.error(
        `Out of date with kingres/brand:\n  ${stale.join('\n  ')}\nRun: npm run brand:sync`,
      )
      process.exit(1)
    }
    console.log('Brand files are up to date.')
  } else {
    mkdirSync(resolve(web, 'public'), { recursive: true })
    for (const [from, to] of COPIES) {
      copyFileSync(resolve(brand, from), resolve(web, to))
      console.log(`Copied ${to}`)
    }
    writeFileSync(resolve(web, GENERATED), generateBrandModule())
    console.log(`Wrote ${GENERATED}`)
  }
}
