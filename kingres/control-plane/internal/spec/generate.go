package spec

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

// OperationsGo renders the Go source of the generated tables of package
// contract (operations_gen.go): the operations and the AuditAction enum.
func (d *Document) OperationsGo() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// SPDX-License-Identifier: PostgreSQL\n\n")
	b.WriteString("// Code generated by internal/contract/gen from kingres/api/openapi.yaml. DO NOT EDIT.\n\n")
	b.WriteString("package contract\n\n")
	b.WriteString("// operations is the operation table of the contract.\n")
	b.WriteString("var operations = []Operation{\n")
	for _, op := range d.Operations {
		fmt.Fprintf(&b, "\t{ID: %q, Method: %q, Path: %q, Tag: %q, Role: %q, Security: %s, PathParams: %s, QueryParams: %s},\n",
			op.ID, op.Method, op.Path, op.Tag, op.Role, goStrings(op.Security), goStrings(op.PathParams), goStrings(op.QueryParams))
	}
	b.WriteString("}\n\n")
	b.WriteString("// auditActions is the enum of schema AuditAction.\n")
	b.WriteString("var auditActions = " + goStrings(d.AuditActions) + "\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated source: %w", err)
	}
	return out, nil
}

func goStrings(v []string) string {
	if len(v) == 0 {
		return "nil"
	}
	q := make([]string, len(v))
	for i, s := range v {
		q[i] = fmt.Sprintf("%q", s)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}
