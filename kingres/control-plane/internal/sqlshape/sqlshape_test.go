func TestRefusedStatements(t *testing.T) {
	for _, c := range refused {
		t.Run(c.name, func(t *testing.T) {
			p := parse(t, c.sql, Hints{})
			if len(p.Refused) != 1 || len(p.Statements) != 0 {
				t.Fatalf("want one refusal, got %+v statements %+v", p.Refused, p.Statements)
			}
			r := p.Refused[0]
			if r.Kind != c.kind {
				t.Errorf("kind %q, want %q (%s)", r.Kind, c.kind, r.Reason)
			}
			if r.Reason == "" || r.Position != "f.sql#1" || !strings.Contains(r.Fingerprint, ":") {
				t.Errorf("incomplete refusal %+v", r)
			}
			if p.Valid() {
				t.Error("Valid on a refusal")
			}
		})
	}
}

// A refusal repeats nothing of the statement: a canary in every position of a refused statement never appears in the refusal.
func TestRefusalsCarryNoText(t *testing.T) {
	const canary = "CANARYvalue42"
	for _, sql := range []string{
		"CREATE TABLE public.t (" + canary + " int) TABLESPACE " + canary + ";",
		"GRANT " + canary + " TO " + canary + ";",
		"CREATE FUNCTION " + canary + "() RETURNS int AS '" + canary + "';",
		"ALTER TABLE public." + canary + " OWNER TO " + canary + ";",
		"COMMENT ON ROLE " + canary + " IS '" + canary + "';",
		"COMMENT ON " + canary + " x IS 'y';",
		"CREATE " + canary + " x;",
		"CREATE SCHEMA " + canary + " CREATE TABLE " + canary + " (a int);",
		"\\" + canary + " x\n",
		"CREATE TABLE public.t (a int DEFAULT " + canary + "(1)) " + canary + ";",
		"ALTER TABLE public.t ADD " + canary + ";",
		"CREATE TYPE public.t AS RANGE (" + canary + " = 1);",
	} {
		p := parse(t, sql, Hints{})
		if p.Valid() {
			t.Errorf("accepted: %s", sql)
			continue
		}
		for _, r := range p.Refused {
			if s := fmt.Sprintf("%+v", r); strings.Contains(strings.ToLower(s), strings.ToLower(canary)) {
				t.Errorf("refusal repeats text: %s", s)
			}
		}
	}
}

func TestInheritanceChild(t *testing.T) {
	h := Hints{InheritanceChildren: map[string]bool{"public.c": true}}
	p := parse(t, `CREATE TABLE public.c (x integer) INHERITS (public.p, other.q);`, h)
	if !p.Valid() || len(p.Statements[0].Inherits) != 2 || p.Statements[0].Inherits[0] != "other.q" {
		t.Fatalf("%+v %+v", p.Refused, p.Statements)
	}
	if !contains(p.Relations, "public.p") || !contains(p.Relations, "other.q") {
		t.Errorf("relations %v", p.Relations)
	}
	p = parse(t, `CREATE TABLE public.d (x integer) INHERITS (public.p);`, h)
	if p.Valid() {
		t.Error("a table that is not an inheritance child may not inherit")
	}
}

func contains(l []string, s string) bool {
	for _, x := range l {
		if x == s {
			return true
		}
	}
	return false
}

// GENERATED ... AS (pg_sleep(86400)) is accepted by shape; the function is collected so that 14c refuses it against pg_proc.
func TestFunctionsAreCollected(t *testing.T) {
	p := parse(t, `CREATE TABLE public.t (a integer, b integer GENERATED ALWAYS AS (pg_sleep(86400)::text::integer) STORED, c text DEFAULT lower('X'::text), d numeric(10,2) DEFAULT (1)::numeric(10,2), CONSTRAINT k CHECK (((a > 0) AND (public.myfn(a) OR (a IN (1, 2))))));
CREATE VIEW public.v AS SELECT pg_catalog.upper(c) AS u, COALESCE(a, 1) AS x, CAST(a AS numeric(5,2)) AS n FROM public.t JOIN other.z ON (z.id = t.a);
CREATE INDEX i ON public.t USING btree (public.myfn2(a)) WHERE (nullif(a, 0) > 0);`, Hints{})
	if !p.Valid() {
		t.Fatalf("%+v", p.Refused)
	}
	want := []string{"lower", "pg_catalog.upper", "pg_sleep", "public.myfn", "public.myfn2"}
	if strings.Join(p.Functions, ",") != strings.Join(want, ",") {
		t.Errorf("functions %v, want %v", p.Functions, want)
	}
	if !contains(p.Relations, "public.t") || !contains(p.Relations, "other.z") {
		t.Errorf("relations %v", p.Relations)
	}
}

func TestFactsOfTables(t *testing.T) {
	p := parse(t, `CREATE TABLE public.m (ts date NOT NULL, id integer, v text GENERATED ALWAYS AS (id::text) STORED) PARTITION BY HASH (id, ts) USING columnar;
CREATE TABLE public.m1 PARTITION OF public.m FOR VALUES WITH (modulus 2, remainder 0);
ALTER TABLE ONLY public.m ATTACH PARTITION public.m2 FOR VALUES WITH (modulus 2, remainder 1);`, Hints{})
	if !p.Valid() {
		t.Fatalf("%+v", p.Refused)
	}
	a := p.Statements[0]
	if a.Name != "public.m" || a.PartitionBy != "HASH" || strings.Join(a.PartitionKey, ",") != "id,ts" || a.AccessMethod != "columnar" || len(a.Columns) != 3 || !a.Columns[2].Generated || a.Columns[0].Type != "date" {
		t.Errorf("%+v", a)
	}
	if b := p.Statements[1]; b.PartitionOf != "public.m" || b.Name != "public.m1" {
		t.Errorf("%+v", b)
	}
	if c := p.Statements[2]; c.PartitionOf != "public.m" || c.Partition != "public.m2" {
		t.Errorf("%+v", c)
	}
	if p.ByKind["CREATE TABLE"] != 2 || p.ByKind["ALTER TABLE ATTACH PARTITION"] != 1 {
		t.Errorf("%v", p.ByKind)
	}
	if s := a.Fingerprint(); !strings.HasPrefix(s, fmt.Sprint(a.Length)+":") || len(s) != len(fmt.Sprint(a.Length))+1+16 {
		t.Errorf("fingerprint %q", s)
	}
}

