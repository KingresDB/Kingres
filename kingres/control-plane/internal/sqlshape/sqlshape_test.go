func TestAcceptedStatements(t *testing.T) {
	for _, c := range accepted {
		t.Run(c.name, func(t *testing.T) {
			p := parse(t, c.sql, Hints{})
			if !p.Valid() {
				t.Fatalf("refused: %+v", p.Refused)
			}
			if len(p.Statements) == 0 || p.Statements[0].Kind != c.kind {
				t.Fatalf("kind %v, want %s", p.Statements, c.kind)
			}
		})
	}
}

