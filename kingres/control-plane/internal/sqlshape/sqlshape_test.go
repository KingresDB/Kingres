func parse(t *testing.T, sql string, h Hints) *Plan {
	t.Helper()
	p, err := ParseFile(strings.NewReader(sql), "f.sql", h)
	if err != nil {
		t.Fatalf("ParseFile: %v\n%s", err, sql)
	}
	return p
}

