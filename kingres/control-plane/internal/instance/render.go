// ErrInvalid is wrapped by validation errors of this package.
var ErrInvalid = errors.New("invalid instance input")

func invalid(format string, a ...any) error {
	return fmt.Errorf("%w: %s", ErrInvalid, fmt.Sprintf(format, a...))
}

// HBARule is one rule of the managed part of pg_hba.conf.
type HBARule struct {
	// Type is host, hostssl or hostnossl.
	Type string
	// Databases and Users are names or the single word "all".
	Databases, Users []string
	// Address is a CIDR or "all".
	Address string
	// Method is scram-sha-256, cert or reject.
	Method string
	// Map is the pg_ident.conf map of a cert rule (optional).
	Map string
}

// IdentMap is the name of the pg_ident.conf map used for proxy connections.
const IdentMap = "kingres_proxy"

// ServiceRole is the role kingresd itself uses. Its rules are written first
// and cannot be removed or overridden by managed rules.
const ServiceRole = "kingresd"

// hbaName renders a database or role name: the keyword all as it is, any
// other name quoted. Characters that pg_hba.conf cannot carry are refused.
func hbaName(n string) (string, error) {
	if n == "all" {
		return "all", nil
	}
	if n == "" || len(n) > 63 || !utf8.ValidString(n) {
		return "", invalid("name %q has a bad length or is not UTF-8", trunc(n))
	}
	for _, r := range n {
		if r < 0x21 || r == 0x7f || r == '"' || r == ',' || r == '#' || r == '\\' || (r >= 0x80 && r <= 0x9f) {
			return "", invalid("name %q contains a character that pg_hba.conf cannot carry", trunc(n))
		}
	}
	if n[0] == '@' || n[0] == '+' {
		return "", invalid("name %q must not start with @ or +", trunc(n))
	}
	return `"` + n + `"`, nil
}

func trunc(s string) string {
	if len(s) > 30 {
		return s[:30] + "..."
	}
	return s
}

func hbaList(names []string) (string, error) {
	if len(names) == 0 {
		return "", invalid("a rule needs at least one name")
	}
	parts := make([]string, len(names))
	for i, n := range names {
		q, err := hbaName(n)
		if err != nil {
			return "", err
		}
		parts[i] = q
	}
	return strings.Join(parts, ","), nil
}

// RenderHBA renders the whole pg_hba.conf: the fixed rules for the service
// role first, then the managed rules in order, then a final rejection of
// everything else (also PostgreSQL's behavior, but explicit). When tlsRequired
// is set, plain host rules are refused.
func RenderHBA(rules []HBARule, tlsRequired bool) (string, error) {
	return RenderHBAWithNodes(rules, tlsRequired, NodeTrust{})
}

// RenderHBAWithNodes is RenderHBA with the certificate rules for the other
// servers of the cluster (design D3) in front of everything else.
func RenderHBAWithNodes(rules []HBARule, tlsRequired bool, nodes NodeTrust) (string, error) {
	if err := nodes.Validate(); err != nil {
		return "", err
	}
	var sb strings.Builder
	sb.WriteString("# Generated by kingresd. Do not edit: changes are overwritten.\n")
	sb.WriteString("# TYPE  DATABASE  USER  ADDRESS  METHOD\n")
	sb.WriteString(nodes.hbaLines())
	fmt.Fprintf(&sb, "local   all  %s  scram-sha-256\n", ServiceRole)
	fmt.Fprintf(&sb, "host    all  %s  127.0.0.1/32  scram-sha-256\n", ServiceRole)
	fmt.Fprintf(&sb, "host    all  %s  ::1/128  scram-sha-256\n", ServiceRole)
	// Roles that signed in are mapped to the operating system user of
	// kingresd (pg_ident.conf, see Manager.WriteIdent) so that kingresd can
	// open connections as them over the unix socket without their password.
	fmt.Fprintf(&sb, "local   all  all  peer map=%s\n", IdentMap)
	for i, r := range rules {
		line, err := renderRule(r, tlsRequired)
		if err != nil {
			return "", fmt.Errorf("rule %d: %w", i+1, err)
		}
		sb.WriteString(line)
		sb.WriteByte('\n')
	}
	return sb.String(), nil
}

func renderRule(r HBARule, tlsRequired bool) (string, error) {
	switch r.Type {
	case "hostssl":
	case "host", "hostnossl":
		if tlsRequired {
			return "", invalid("type %s is not allowed while TLS is required", r.Type)
		}
	default:
		return "", invalid("unknown connection type %q", trunc(r.Type))
	}
	switch r.Method {
	case "scram-sha-256", "reject":
	case "cert":
		if r.Type != "hostssl" {
			return "", invalid("method cert needs type hostssl")
		}
	default:
		return "", invalid("unknown method %q", trunc(r.Method))
	}
	dbs, err := hbaList(r.Databases)
	if err != nil {
		return "", err
	}
	users, err := hbaList(r.Users)
	if err != nil {
		return "", err
	}
	addr := r.Address
	if addr != "all" {
		p, err := netip.ParsePrefix(addr)
		if err != nil {
			return "", invalid("address %q is not a CIDR network or all", trunc(addr))
		}
		addr = p.String() // canonical text, no zone, no surprises
	}
	line := fmt.Sprintf("%-9s %s %s %s %s", r.Type, dbs, users, addr, r.Method)
	if r.Map != "" {
		if r.Method != "cert" || !identMapRE.MatchString(r.Map) {
			return "", invalid("map %q is only valid for the cert method and must be a plain name", trunc(r.Map))
		}
		line += " map=" + r.Map
	}
	return line, nil
}

// confValue quotes a value for postgresql.conf. Newlines and NUL cannot be
// represented and are refused.
func confValue(v string) (string, error) {
	if !utf8.ValidString(v) || strings.ContainsAny(v, "\x00\r\n") {
		return "", invalid("configuration value contains a newline, NUL or invalid UTF-8")
	}
	v = strings.ReplaceAll(v, `\`, `\\`)
	v = strings.ReplaceAll(v, `'`, `''`)
	return "'" + v + "'", nil
}

// ManagedSettings are the settings kingresd writes into the managed include
// file (design D3).
type ManagedSettings struct {
	// Port is the TCP port, 1024 to 65535.
	Port int
	// ListenAddresses is the listen_addresses value; "localhost" when empty.
	ListenAddresses string
	// SocketDir is unix_socket_directories.
	SocketDir string
	// ClusterName appears in process titles and logs.
	ClusterName string
	// TLSCertFile and TLSKeyFile turn ssl on when both are set; absolute paths.
	TLSCertFile, TLSKeyFile string
	// TLSCAFile makes the instance verify client certificates against the
	// cluster CA (ssl_ca_file) and TLSCRLFile is the revocation list
	// (ssl_crl_file); both optional.
	TLSCAFile, TLSCRLFile string
	// NodeConninfo is the value of kingres_shard.node_conninfo (see
	// NodeConninfo); empty leaves the setting unset.
	NodeConninfo string
	// MaxConnections defaults to 100.
	MaxConnections int
	// Extra holds additional settings by name (for example from the cluster
	// settings); names must be plain GUC names.
	Extra map[string]string
}

// RenderManaged renders kingres-managed.conf.
func RenderManaged(s ManagedSettings) (string, error) {
	if s.Port < 1024 || s.Port > 65535 {
		return "", invalid("port %d is not in 1024..65535", s.Port)
	}
	listen := s.ListenAddresses
	if listen == "" {
		listen = "localhost"
	}
	maxc := s.MaxConnections
	if maxc == 0 {
		maxc = 100
	}
	if maxc < 10 || maxc > 10000 {
		return "", invalid("max_connections %d is not in 10..10000", maxc)
	}
	type kv struct{ k, v string }
	settings := []kv{
		{"listen_addresses", listen},
		{"port", strconv.Itoa(s.Port)},
		{"max_connections", strconv.Itoa(maxc)},
		{"shared_preload_libraries", "kingres_shard,kingres_ledger"},
		{"password_encryption", "scram-sha-256"},
		{"max_prepared_transactions", strconv.Itoa(maxc)},
		{"logging_collector", "on"},
		{"log_directory", "log"},
		{"log_filename", "postgresql-%a.log"},
		{"log_truncate_on_rotation", "on"},
	}
	if s.SocketDir != "" {
		if err := validateConfPath(s.SocketDir); err != nil {
			return "", err
		}
		settings = append(settings, kv{"unix_socket_directories", s.SocketDir})
	}
	if s.ClusterName != "" {
		settings = append(settings, kv{"cluster_name", s.ClusterName})
	}
	if (s.TLSCertFile == "") != (s.TLSKeyFile == "") {
		return "", invalid("TLS certificate and key must be set together")
	}
	if s.TLSCertFile != "" {
		for _, p := range []string{s.TLSCertFile, s.TLSKeyFile} {
			if err := validateConfPath(p); err != nil {
				return "", err
			}
		}
		settings = append(settings, kv{"ssl", "on"}, kv{"ssl_cert_file", s.TLSCertFile}, kv{"ssl_key_file", s.TLSKeyFile})
		settings = append(settings, kv{"ssl_min_protocol_version", "TLSv1.3"})
		if s.TLSCAFile != "" {
			if err := validateConfPath(s.TLSCAFile); err != nil {
				return "", err
			}
			settings = append(settings, kv{"ssl_ca_file", s.TLSCAFile})
		}
		if s.TLSCRLFile != "" {
			if err := validateConfPath(s.TLSCRLFile); err != nil {
				return "", err
			}
			settings = append(settings, kv{"ssl_crl_file", s.TLSCRLFile})
		}
	}
	if s.NodeConninfo != "" {
		settings = append(settings, kv{"kingres_shard.node_conninfo", s.NodeConninfo})
	}
	reserved := map[string]bool{}
	for _, e := range settings {
		reserved[e.k] = true
	}
	names := make([]string, 0, len(s.Extra))
	for k := range s.Extra {
		names = append(names, k)
	}
	sort.Strings(names)
	for _, k := range names {
		if !validGUCName(k) || reserved[k] || k == "hba_file" || k == "data_directory" || k == "include" {
			return "", invalid("setting %q cannot be set here", trunc(k))
		}
		settings = append(settings, kv{k, s.Extra[k]})
	}
	var sb strings.Builder
	sb.WriteString("# Generated by kingresd. Do not edit: changes are overwritten.\n")
	for _, e := range settings {
		q, err := confValue(e.v)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&sb, "%s = %s\n", e.k, q)
	}
	return sb.String(), nil
}

func validGUCName(k string) bool {
	if k == "" || len(k) > 63 {
		return false
	}
	for i := 0; i < len(k); i++ {
		c := k[i]
		if (c < 'a' || c > 'z') && (c < '0' || c > '9') && c != '_' && c != '.' {
			return false
		}
	}
	return true
}

// validateConfPath checks a path that is written into postgresql.conf: it
// must be absolute, clean, free of control characters and of ".." elements.
func validateConfPath(p string) error {
	if p == "" || !strings.HasPrefix(p, "/") {
		return invalid("path %q must be absolute", trunc(p))
	}
	if strings.ContainsAny(p, "\x00\r\n") || !utf8.ValidString(p) {
		return invalid("path contains a control character")
	}
	for _, el := range strings.FieldsFunc(p, func(r rune) bool { return r == '/' || r == '\\' }) {
		if el == ".." {
			return invalid("path %q contains ..", trunc(p))
		}
	}
	if path.Clean(p) != p {
		return invalid("path %q is not clean", trunc(p))
	}
	return nil
}

// RenderIdent renders pg_ident.conf: the OS user osUser may connect as each of
// roles over the unix socket. Names that cannot be written safely are refused.
func RenderIdent(osUser string, roles []string) (string, error) {
	return RenderIdentWithNodes(osUser, roles, NodeTrust{})
}

// RenderIdentWithNodes is RenderIdent plus the map of the other servers'
// certificate names (design D3).
func RenderIdentWithNodes(osUser string, roles []string, nodes NodeTrust) (string, error) {
	if err := nodes.Validate(); err != nil {
		return "", err
	}
	if osUser == "" || len(osUser) > 64 || strings.ContainsAny(osUser, "\"\\\x00\r\n#\t ") || !utf8.ValidString(osUser) {
		return "", invalid("operating system user name %q", trunc(osUser))
	}
	var sb strings.Builder
	sb.WriteString("# Generated by kingresd. Do not edit: changes are overwritten.\n")
	sorted := append([]string(nil), roles...)
	sort.Strings(sorted)
	for _, r := range sorted {
		q, err := hbaName(r)
		if err != nil || r == "all" || r == ServiceRole {
			return "", invalid("role name %q cannot be mapped", trunc(r))
		}
		fmt.Fprintf(&sb, "%s \"%s\" %s\n", IdentMap, osUser, q)
	}
	sb.WriteString(nodes.identLines())
	return sb.String(), nil
}

var identMapRE = regexp.MustCompile(`^[a-z_][a-z0-9_]{0,62}$`)

// quoteConninfoValue quotes a value of a libpq connection string.
func quoteConninfoValue(v string) string {
	v = strings.ReplaceAll(v, "\\", "\\\\")
	v = strings.ReplaceAll(v, "'", "\\'")
	return "'" + v + "'"
}

// NodeConninfo builds the value of kingres_shard.node_conninfo (design D3): the
// options that make this server's outgoing node connections present its
// certificate and verify the peer's against the cluster CA and the names in it.
// The files are named, never their content; crl may be empty.
func NodeConninfo(cert, key, ca, crl string) (string, error) {
	parts := []string{"sslmode=verify-full"}
	for _, kv := range [][2]string{{"sslcert", cert}, {"sslkey", key}, {"sslrootcert", ca}, {"sslcrl", crl}} {
		if kv[1] == "" {
			if kv[0] == "sslcrl" {
				continue
			}
			return "", invalid("node connection option %s needs a file", kv[0])
		}
		if err := validateConfPath(kv[1]); err != nil {
			return "", err
		}
		parts = append(parts, kv[0]+"="+quoteConninfoValue(kv[1]))
	}
	return strings.Join(parts, " "), nil
}
