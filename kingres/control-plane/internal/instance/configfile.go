// configNameRE is the shape of a parameter name written to the override file: no space, quote,
// "=" or newline can be part of it, so a name can never become a second setting or a directive.
var configNameRE = regexp.MustCompile(`^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)?$`)

// MaxConfigValue is the longest value of the override file in bytes.
const MaxConfigValue = 4096

const configHeaderPrefix = "# kingresd configuration revision "

// RenderConfig renders the override file of an instance at a revision. Every line is generated
// from a checked name and a quoted value (confValue: backslash and quote doubled, newline, NUL and
// invalid UTF-8 refused), never assembled from request text, and the lines are sorted so the same
// values always give the same file.
func RenderConfig(revision int64, values map[string]string) (string, error) {
	names := make([]string, 0, len(values))
	for k := range values {
		names = append(names, k)
	}
	sort.Strings(names)
	var sb strings.Builder
	sb.WriteString("# Generated by kingresd. Do not edit: changes are overwritten.\n")
	sb.WriteString(configHeaderPrefix + strconv.FormatInt(revision, 10) + "\n")
	for _, k := range names {
		if !configNameRE.MatchString(k) || len(k) > 63 {
			return "", invalid("setting %q cannot be written", trunc(k))
		}
		if _, managed := ManagedParameters[k]; managed || forbiddenExtra[k] {
			return "", invalid("setting %q is managed and cannot be written here", trunc(k))
		}
		v := values[k]
		if len(v) > MaxConfigValue {
			return "", invalid("the value of %q is longer than %d bytes", trunc(k), MaxConfigValue)
		}
		q, err := confValue(v)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&sb, "%s = %s\n", k, q)
	}
	return sb.String(), nil
}

// ConfigRevision returns the revision in the header of an override file, 0 when there is none.
func ConfigRevision(text string) int64 {
	for _, l := range strings.Split(text, "\n") {
		if rest, ok := strings.CutPrefix(l, configHeaderPrefix); ok {
			n, err := strconv.ParseInt(strings.TrimSpace(rest), 10, 64)
			if err == nil {
				return n
			}
			return 0
		}
	}
	return 0
}

// ConfigPath is the path of the override file of instance id.
func (m *Manager) ConfigPath(id int) (string, error) {
	data, err := m.DataDir(id)
	if err != nil {
		return "", err
	}
	return filepath.Join(data, ConfigFileName), nil
}

// ReadConfig returns the override file of instance id; "" when it does not exist yet.
func (m *Manager) ReadConfig(id int) (string, error) {
	p, err := m.ConfigPath(id)
	if err != nil {
		return "", err
	}
	b, err := os.ReadFile(p) //nolint:gosec // path below the manager root
	if errors.Is(err, fs.ErrNotExist) {
		return "", nil
	}
	return string(b), err
}

// WriteConfig replaces the override file atomically. The file it replaces is copied to
// kingres-config.conf.prev first, so RestoreConfig can put it back when PostgreSQL rejects the new one.
func (m *Manager) WriteConfig(id int, text string) error {
	if _, err := m.Managed(id); err != nil {
		return err
	}
	p, _ := m.ConfigPath(id)
	if old, err := os.ReadFile(p); err == nil { //nolint:gosec // path below the manager root
		if err := writeAtomic(p+".prev", old); err != nil {
			return err
		}
	}
	return writeAtomic(p, []byte(text))
}

// RestoreConfig puts back the file that WriteConfig replaced (an empty file when there was none).
func (m *Manager) RestoreConfig(id int) error {
	p, err := m.ConfigPath(id)
	if err != nil {
		return err
	}
	b, err := os.ReadFile(p + ".prev") //nolint:gosec // path below the manager root
	if errors.Is(err, fs.ErrNotExist) {
		b = nil
	} else if err != nil {
		return err
	}
	return writeAtomic(p, b)
}

// EnsureConfig makes an instance created before configuration existed carry the include: it creates
// the empty override file and renders the managed file again from the stored settings (the layout
// changes, the effective values do not). It reports whether it changed anything.
func (m *Manager) EnsureConfig(id int) (bool, error) {
	if _, err := m.Managed(id); err != nil {
		return false, err
	}
	data, _ := m.DataDir(id)
	changed := false
	if _, err := os.Stat(filepath.Join(data, ConfigFileName)); errors.Is(err, fs.ErrNotExist) {
		if err := writeAtomic(filepath.Join(data, ConfigFileName), []byte("# Generated by kingresd. Do not edit: changes are overwritten.\n")); err != nil {
			return false, err
		}
		changed = true
	}
	cur, err := os.ReadFile(filepath.Join(data, "kingres-managed.conf")) //nolint:gosec // path below the manager root
	if err != nil {
		return changed, err
	}
	if strings.Contains(string(cur), "include_if_exists '"+ConfigFileName+"'") {
		return changed, nil
	}
	s, err := m.Settings(id)
	if err != nil {
		return changed, err
	}
	if err := m.WriteManaged(id, s); err != nil {
		return changed, err
	}
	return true, nil
}

// CheckValue asks PostgreSQL's own parser whether a value is valid for a parameter of PostgreSQL
// (postgres -C name -c name=value, design config-phase13.md V5). The program is run without a shell
// and the pair is one argument, so a value cannot become a second option. The answer is
// PostgreSQL's first line of complaint, or nil. It does not know the parameters of an extension.
func (m *Manager) CheckValue(ctx context.Context, id int, name, value string) error {
	if !configNameRE.MatchString(name) || strings.ContainsAny(value, "\x00\r\n") {
		return invalid("the parameter or value cannot be checked")
	}
	data, err := m.DataDir(id)
	if err != nil {
		return err
	}
	ctx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	out, err := m.run(ctx, "postgres", "-D", data, "-c", name+"="+value, "-C", name)
	return postgresCheckError(out, err)
}

func postgresCheckError(out string, err error) error {
	if err == nil {
		return nil
	}
	for _, l := range strings.Split(out, "\n") {
		if i := strings.Index(l, "FATAL:"); i >= 0 {
			return fmt.Errorf("%w: %s", ErrInvalid, strings.TrimSpace(l[i+len("FATAL:"):]))
		}
	}
	return fmt.Errorf("instance: postgres -C: %w", err)
}

// CheckConfig asks PostgreSQL's own parser whether the files of the instance, the override file
// included, can be loaded as they are now (postgres -C over the whole configuration). A restart that
// would fail on a value the parser refuses is found here, before the instance is stopped (P13R-02).
func (m *Manager) CheckConfig(ctx context.Context, id int) error {
	data, err := m.DataDir(id)
	if err != nil {
		return err
	}
	ctx, cancel := context.WithTimeout(ctx, 20*time.Second)
	defer cancel()
	out, err := m.run(ctx, "postgres", "-D", data, "-C", "data_directory")
	return postgresCheckError(out, err)
}

// MarkConfigGood keeps a copy of the override file as the last one an instance ran with
// (kingres-config.conf.good): a restart that cannot start the instance puts it back.
func (m *Manager) MarkConfigGood(id int) error {
	p, err := m.ConfigPath(id)
	if err != nil {
		return err
	}
	b, err := os.ReadFile(p) //nolint:gosec // path below the manager root
	if err != nil {
		return err
	}
	return writeAtomic(p+".good", b)
}

// EmptyConfigText is the override file without any value.
const EmptyConfigText = "# Generated by kingresd. Do not edit: changes are overwritten.\n"

// RestoreGoodConfig puts back the last file the instance started with, or the empty override file when none was kept
// (never the file that WriteConfig replaced, which can be a bad one: two changes made before a restart, P13S-01).
func (m *Manager) RestoreGoodConfig(id int) error {
	p, err := m.ConfigPath(id)
	if err != nil {
		return err
	}
	b, err := os.ReadFile(p + ".good") //nolint:gosec // path below the manager root
	if errors.Is(err, fs.ErrNotExist) {
		b = []byte(EmptyConfigText)
	} else if err != nil {
		return err
	}
	return writeAtomic(p, b)
}

func firstLineOf(s string) string {
	s = strings.TrimSpace(s)
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		s = s[:i]
	}
	if len(s) > 300 {
		s = s[:300]
	}
	return s
}

// rolledBackMark is the file that says the last start went back to the last good override file.
func (m *Manager) rolledBackMark(id int) (string, error) {
	p, err := m.ConfigPath(id)
	return p + ".rolledback", err
}

// fallBackToGoodConfig puts the last good override file back when the file now is another one, and leaves a mark with
// the reason. It reports whether it changed the file (then a second start is worth trying).
func (m *Manager) fallBackToGoodConfig(id int, why string) bool {
	p, err := m.ConfigPath(id)
	if err != nil {
		return false
	}
	cur, err := os.ReadFile(p) //nolint:gosec // path below the manager root
	if err != nil {
		return false
	}
	want, err := os.ReadFile(p + ".good") //nolint:gosec // path below the manager root
	if err != nil {
		want = []byte(EmptyConfigText)
	}
	if string(cur) == string(want) {
		return false
	}
	if err := writeAtomic(p, want); err != nil {
		return false
	}
	if mark, err := m.rolledBackMark(id); err == nil {
		_ = writeAtomic(mark, []byte(why+"\n"))
	}
	m.log.Warn("the instance did not start with its override file; the last good file was put back", "instance", id, "reason", why)
	return true
}

// TakeRollbackMark returns, and removes, the reason a start went back to the last good override file ("" and false when
// it did not). The configuration task asks before and after a restart.
func (m *Manager) TakeRollbackMark(id int) (string, bool) {
	mark, err := m.rolledBackMark(id)
	if err != nil {
		return "", false
	}
	b, err := os.ReadFile(mark) //nolint:gosec // path below the manager root
	if err != nil {
		return "", false
	}
	_ = os.Remove(mark)
	return strings.TrimSpace(string(b)), true
}

// AdoptGoodConfig keeps the override file of a running instance as its last good one when none was kept yet (an
// instance that started before the console could configure it, and has not been started since). The file a running
// instance holds at kingresd's start is the one it started with, or one a reload took, so it is the best there is.
func (m *Manager) AdoptGoodConfig(ctx context.Context, id int) {
	p, err := m.ConfigPath(id)
	if err != nil {
		return
	}
	if _, err := os.Stat(p + ".good"); err == nil {
		return
	}
	if up, _ := m.Running(ctx, id); up {
		_ = m.MarkConfigGood(id)
	}
}
