// configNameRE is the shape of a parameter name written to the override file: no space, quote,
// "=" or newline can be part of it, so a name can never become a second setting or a directive.
var configNameRE = regexp.MustCompile(`^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)?$`)

// MaxConfigValue is the longest value of the override file in bytes.
const MaxConfigValue = 4096

const configHeaderPrefix = "# kingresd configuration revision "

// RenderConfig renders the override file of an instance at a revision. Every line is generated
// from a checked name and a quoted value (confValue: backslash and quote doubled, newline, NUL and
// invalid UTF-8 refused), never assembled from request text, and the lines are sorted so the same
// values always give the same file.
func RenderConfig(revision int64, values map[string]string) (string, error) {
	names := make([]string, 0, len(values))
	for k := range values {
		names = append(names, k)
	}
	sort.Strings(names)
	var sb strings.Builder
	sb.WriteString("# Generated by kingresd. Do not edit: changes are overwritten.\n")
	sb.WriteString(configHeaderPrefix + strconv.FormatInt(revision, 10) + "\n")
	for _, k := range names {
		if !configNameRE.MatchString(k) || len(k) > 63 {
			return "", invalid("setting %q cannot be written", trunc(k))
		}
		if _, managed := ManagedParameters[k]; managed || forbiddenExtra[k] {
			return "", invalid("setting %q is managed and cannot be written here", trunc(k))
		}
		v := values[k]
		if len(v) > MaxConfigValue {
			return "", invalid("the value of %q is longer than %d bytes", trunc(k), MaxConfigValue)
		}
		q, err := confValue(v)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&sb, "%s = %s\n", k, q)
	}
	return sb.String(), nil
}

// ConfigRevision returns the revision in the header of an override file, 0 when there is none.
func ConfigRevision(text string) int64 {
	for _, l := range strings.Split(text, "\n") {
		if rest, ok := strings.CutPrefix(l, configHeaderPrefix); ok {
			n, err := strconv.ParseInt(strings.TrimSpace(rest), 10, 64)
			if err == nil {
				return n
			}
			return 0
		}
	}
	return 0
}

// ConfigPath is the path of the override file of instance id.
func (m *Manager) ConfigPath(id int) (string, error) {
	data, err := m.DataDir(id)
	if err != nil {
		return "", err
	}
	return filepath.Join(data, ConfigFileName), nil
}

// ReadConfig returns the override file of instance id; "" when it does not exist yet.
func (m *Manager) ReadConfig(id int) (string, error) {
	p, err := m.ConfigPath(id)
	if err != nil {
		return "", err
	}
	b, err := os.ReadFile(p) //nolint:gosec // path below the manager root
	if errors.Is(err, fs.ErrNotExist) {
		return "", nil
	}
	return string(b), err
}

// WriteConfig replaces the override file atomically. The file it replaces is copied to
// kingres-config.conf.prev first, so RestoreConfig can put it back when PostgreSQL rejects the new one.
func (m *Manager) WriteConfig(id int, text string) error {
	if _, err := m.Managed(id); err != nil {
		return err
	}
	p, _ := m.ConfigPath(id)
	if old, err := os.ReadFile(p); err == nil { //nolint:gosec // path below the manager root
		if err := writeAtomic(p+".prev", old); err != nil {
			return err
		}
	}
	return writeAtomic(p, []byte(text))
}

// RestoreConfig puts back the file that WriteConfig replaced (an empty file when there was none).
func (m *Manager) RestoreConfig(id int) error {
	p, err := m.ConfigPath(id)
	if err != nil {
		return err
	}
	b, err := os.ReadFile(p + ".prev") //nolint:gosec // path below the manager root
	if errors.Is(err, fs.ErrNotExist) {
		b = nil
	} else if err != nil {
		return err
	}
	return writeAtomic(p, b)
}

// EnsureConfig makes an instance created before configuration existed carry the include: it creates
// the empty override file and renders the managed file again from the stored settings (the layout
// changes, the effective values do not). It reports whether it changed anything.
func (m *Manager) EnsureConfig(id int) (bool, error) {
	if _, err := m.Managed(id); err != nil {
		return false, err
	}
	data, _ := m.DataDir(id)
	changed := false
	if _, err := os.Stat(filepath.Join(data, ConfigFileName)); errors.Is(err, fs.ErrNotExist) {
		if err := writeAtomic(filepath.Join(data, ConfigFileName), []byte("# Generated by kingresd. Do not edit: changes are overwritten.\n")); err != nil {
			return false, err
		}
		changed = true
	}
	cur, err := os.ReadFile(filepath.Join(data, "kingres-managed.conf")) //nolint:gosec // path below the manager root
	if err != nil {
		return changed, err
	}
	// An instance made by an earlier package preloads fewer libraries: bring the line up to date (it takes effect at the next restart). The list names
	// kingres_columnar only when the installation has the library: an instance whose preload names a file that is not there cannot start, and the next
	// restart, even after a crash, would take the server down.
	m.markColumnarPreload(id, string(cur)) // before the list is chosen: a file that names the library is the proof that the instance had it
	want := m.preloadListFor(id)
	if strings.Contains(string(cur), "include_if_exists '"+ConfigFileName+"'") && !preloadDiffers(string(cur), want) {
		return changed, nil
	}
	if preloadDiffers(string(cur), want) {
		m.log.Warn("shared_preload_libraries of an instance is brought up to date; it takes effect when the instance is restarted (standbys first), "+
			"and until then a columnar table cannot be written and pg_stat_statements collects nothing",
			"instance", id, "now", preloadOf(string(cur)), "next", want)
		for _, o := range optionalLibraries {
			if !libraryIn(want, o.name) {
				m.log.Warn("the installation has no "+o.name+" library: the instance does not preload it, and "+o.lack+" is not available on this server", "instance", id)
			}
		}
	}
	s, err := m.Settings(id)
	if err != nil {
		return changed, err
	}
	if err := m.WriteManaged(id, s); err != nil {
		return changed, err
	}
	// A running instance reads the new line at a reload and then shows the setting as pending a restart (pg_settings.pending_restart), which is what
	// getConfigSummary and the restart of the console list; without the reload it would not know.
	if up, _ := m.Running(context.Background(), id); up {
		if err := m.Reload(context.Background(), id); err != nil {
			m.log.Warn("reloading an instance after its preload list changed failed", "instance", id, "error", err)
		}
	}
	return true, nil
}

var preloadLineRE = regexp.MustCompile(`(?m)^shared_preload_libraries = '([^'
]*)'`)

// preloadOf returns the preload list of kingres-managed.conf, "" when it has none.
func preloadOf(managed string) string {
	m := preloadLineRE.FindStringSubmatch(managed)
	if m == nil {
		return ""
	}
	return m[1]
}

// preloadOutOfDate says whether kingres-managed.conf carries a preload list other than PreloadLibraries.
func preloadOutOfDate(managed string) bool { return preloadDiffers(managed, PreloadLibraries) }

// preloadDiffers says whether kingres-managed.conf carries a preload list, and another one than want.
func preloadDiffers(managed, want string) bool {
	have := preloadOf(managed)
	return have != "" && have != want
}

// columnarLibrary and statStatementsLibrary are the libraries whose absence from the installation makes the manager leave them out of the preload list.
const (
	columnarLibrary       = "kingres_columnar"
	statStatementsLibrary = "pg_stat_statements"
)

// optionalLibrary is a library of PreloadLibraries that an installation may lack (a package that was not upgraded with kingresd, an image that mixes
// versions). sticky says that an instance that has had it in its list keeps it even when the file is missing: that is for a library whose absence
// makes data unreadable (columnar tables need the resource manager). pg_stat_statements holds no data that matters, so it is not sticky: a missing
// file never keeps an instance from starting, and the library comes back into the list at the next EnsureConfig after the file is back.
type optionalLibrary struct {
	name   string
	marker string // file in the directory of the instance, for a sticky library
	sticky bool
	lack   string // what the server cannot do without it
}

var optionalLibraries = []optionalLibrary{
	{name: columnarLibrary, marker: columnarMarker, sticky: true, lack: "columnar storage"},
	{name: statStatementsLibrary, lack: "pg_stat_statements"},
}

func optionalOf(lib string) (optionalLibrary, bool) {
	for _, o := range optionalLibraries {
		if o.name == lib {
			return o, true
		}
	}
	return optionalLibrary{}, false
}

// preloadList is the value of shared_preload_libraries for an instance of this installation: PreloadLibraries, without the optional libraries that the
// installation has no library file for in its package library directory (a package that was not upgraded with kingresd, an image that mixes versions).
// The answer is looked up each time: the directory is read through pg_config, which is cheap, and a package that is upgraded while kingresd runs is seen.
func (m *Manager) preloadList() string { return m.preloadListWith(0, false) }

// preloadListWith builds the list; with keep, a sticky library that instance id has had stays in it when its file is missing.
func (m *Manager) preloadListWith(id int, keep bool) string {
	var out []string
	for _, n := range strings.Split(PreloadLibraries, ",") {
		o, optional := optionalOf(n)
		switch {
		case !optional || m.libraryExists(n):
			out = append(out, n)
		case keep && o.sticky && m.hadLibrary(id, o):
			m.log.Warn("the installation has no "+n+" library file, and this instance has preloaded it before and may have "+o.lack+": the library stays in its list, "+
				"and the instance cannot start until the package that has the file is installed", "instance", id)
			out = append(out, n)
		}
	}
	return strings.Join(out, ",")
}

// columnarMarker is the file in the directory of an instance that says the instance has had kingres_columnar in its preload list.
const columnarMarker = "columnar-preload"

func (m *Manager) hadLibrary(id int, o optionalLibrary) bool {
	dir, err := m.Dir(id)
	if err != nil {
		return false
	}
	_, err = os.Stat(filepath.Join(dir, o.marker))
	return err == nil
}

// markColumnarPreload records that the instance preloads kingres_columnar (the managed file at hand names it), so that the library is never taken out of the
// list of an instance that may have columnar tables because the file is missing for a moment (a package upgrade removes the old library before it installs the new).
func (m *Manager) markColumnarPreload(id int, managed string) {
	if !libraryIn(preloadOf(managed), columnarLibrary) {
		return
	}
	if dir, err := m.Dir(id); err == nil {
		_ = os.WriteFile(filepath.Join(dir, columnarMarker), []byte("1\n"), 0o600)
	}
}

func libraryIn(list, lib string) bool {
	for _, n := range strings.Split(list, ",") {
		if strings.TrimSpace(n) == lib {
			return true
		}
	}
	return false
}

// preloadListFor is preloadList for an instance: when the installation has no kingres_columnar file but the instance has had it in its list (it may have columnar
// tables), the library stays in the list and a warning says that the instance will not start until the library is back. A new instance, which never had it, gets
// the list without it.
func (m *Manager) preloadListFor(id int) string { return m.preloadListWith(id, true) }

// libraryExists tells whether the installation has the library file lib (lib.so, or the extension of the platform), through pg_config --pkglibdir.
// When pg_config cannot be run the library is assumed to be there, which is what the product did before.
func (m *Manager) libraryExists(lib string) bool {
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	out, err := m.run(ctx, "pg_config", "--pkglibdir")
	if err != nil || out == "" {
		return true
	}
	for _, ext := range []string{".so", ".dylib", ".dll"} {
		if _, err := os.Stat(filepath.Join(out, lib+ext)); err == nil {
			return true
		}
	}
	return false
}

// CheckValue asks PostgreSQL's own parser whether a value is valid for a parameter of PostgreSQL
// (postgres -C name -c name=value, design config-phase13.md V5). The program is run without a shell
// and the pair is one argument, so a value cannot become a second option. The answer is
// PostgreSQL's first line of complaint, or nil. It does not know the parameters of an extension.
func (m *Manager) CheckValue(ctx context.Context, id int, name, value string) error {
	if !configNameRE.MatchString(name) || strings.ContainsAny(value, "\x00\r\n") {
		return invalid("the parameter or value cannot be checked")
	}
	data, err := m.DataDir(id)
	if err != nil {
		return err
	}
	ctx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	out, err := m.run(ctx, "postgres", "-D", data, "-c", name+"="+value, "-C", name)
	return postgresCheckError(out, err)
}

func postgresCheckError(out string, err error) error {
	if err == nil {
		return nil
	}
	for _, l := range strings.Split(out, "\n") {
		if i := strings.Index(l, "FATAL:"); i >= 0 {
			return fmt.Errorf("%w: %s", ErrInvalid, strings.TrimSpace(l[i+len("FATAL:"):]))
		}
	}
	return fmt.Errorf("instance: postgres -C: %w", err)
}

// CheckConfig asks PostgreSQL's own parser whether the files of the instance, the override file
// included, can be loaded as they are now (postgres -C over the whole configuration). A restart that
// would fail on a value the parser refuses is found here, before the instance is stopped (P13R-02).
func (m *Manager) CheckConfig(ctx context.Context, id int) error {
	data, err := m.DataDir(id)
	if err != nil {
		return err
	}
	ctx, cancel := context.WithTimeout(ctx, 20*time.Second)
	defer cancel()
	out, err := m.run(ctx, "postgres", "-D", data, "-C", "data_directory")
	return postgresCheckError(out, err)
}

// MarkConfigGood keeps a copy of the override file as the last one an instance ran with
// (kingres-config.conf.good): a restart that cannot start the instance puts it back.
func (m *Manager) MarkConfigGood(id int) error {
	p, err := m.ConfigPath(id)
	if err != nil {
		return err
	}
	b, err := os.ReadFile(p) //nolint:gosec // path below the manager root
	if err != nil {
		return err
	}
	return writeAtomic(p+".good", b)
}

// EmptyConfigText is the override file without any value.
const EmptyConfigText = "# Generated by kingresd. Do not edit: changes are overwritten.\n"

// RestoreGoodConfig puts back the last file the instance started with, or the empty override file when none was kept
// (never the file that WriteConfig replaced, which can be a bad one: two changes made before a restart, P13S-01).
func (m *Manager) RestoreGoodConfig(id int) error {
	p, err := m.ConfigPath(id)
	if err != nil {
		return err
	}
	b, err := os.ReadFile(p + ".good") //nolint:gosec // path below the manager root
	if errors.Is(err, fs.ErrNotExist) {
		b = []byte(EmptyConfigText)
	} else if err != nil {
		return err
	}
	return writeAtomic(p, b)
}

func firstLineOf(s string) string {
	s = strings.TrimSpace(s)
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		s = s[:i]
	}
	if len(s) > 300 {
		s = s[:300]
	}
	return s
}

// rolledBackMark is the file that says the last start went back to the last good override file.
func (m *Manager) rolledBackMark(id int) (string, error) {
	p, err := m.ConfigPath(id)
	return p + ".rolledback", err
}

// fallBackToGoodConfig puts the last good override file back when the file now is another one, and leaves a mark with
// the reason. It reports whether it changed the file (then a second start is worth trying).
func (m *Manager) fallBackToGoodConfig(id int, why string) bool {
	p, err := m.ConfigPath(id)
	if err != nil {
		return false
	}
	cur, err := os.ReadFile(p) //nolint:gosec // path below the manager root
	if err != nil {
		return false
	}
	want, err := os.ReadFile(p + ".good") //nolint:gosec // path below the manager root
	if err != nil {
		want = []byte(EmptyConfigText)
	}
	if string(cur) == string(want) {
		return false
	}
	if err := writeAtomic(p, want); err != nil {
		return false
	}
	if mark, err := m.rolledBackMark(id); err == nil {
		_ = writeAtomic(mark, []byte(why+"\n"))
	}
	m.log.Warn("the instance did not start with its override file; the last good file was put back", "instance", id, "reason", why)
	return true
}

// TakeRollbackMark returns, and removes, the reason a start went back to the last good override file ("" and false when
// it did not). The configuration task asks before and after a restart.
func (m *Manager) TakeRollbackMark(id int) (string, bool) {
	mark, err := m.rolledBackMark(id)
	if err != nil {
		return "", false
	}
	b, err := os.ReadFile(mark) //nolint:gosec // path below the manager root
	if err != nil {
		return "", false
	}
	_ = os.Remove(mark)
	return strings.TrimSpace(string(b)), true
}

// AdoptGoodConfig keeps the override file of a running instance as its last good one when none was kept yet (an
// instance that started before the console could configure it, and has not been started since). The file a running
// instance holds at kingresd's start is the one it started with, or one a reload took, so it is the best there is.
func (m *Manager) AdoptGoodConfig(ctx context.Context, id int) {
	p, err := m.ConfigPath(id)
	if err != nil {
		return
	}
	if _, err := os.Stat(p + ".good"); err == nil {
		return
	}
	if up, _ := m.Running(ctx, id); up {
		_ = m.MarkConfigGood(id)
	}
}
